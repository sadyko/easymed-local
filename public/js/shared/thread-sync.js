// TELEGRAM_DRAFT_KEEP_V1 — когда переписку НУЖНО перерисовывать.
//
// Лента опрашивается каждые 10 секунд, и раньше каждый ответ сервера
// перерисовывал панель целиком — вместе с полем ввода. Набранный текст исчезал
// прямо во время печати: сотрудник писал пациенту, и на десятой секунде фраза
// пропадала.
//
// Перерисовывать надо, только когда переписка действительно изменилась. В
// остальных случаях (а это почти всегда) экран трогать нельзя.

// Отпечаток ленты: сколько сообщений и какое последнее. Этого достаточно —
// сообщения не редактируются задним числом, они только добавляются, а статус
// «прочитано» на вид ленты не влияет.
export function threadFingerprint(thread) {
    const msgs = (thread && thread.messages) || [];
    if (!msgs.length) return '0:';
    const last = msgs[msgs.length - 1] || {};
    return msgs.length + ':' + (last.id != null ? last.id : (last.created_at || ''));
}

export function threadChanged(prev, next) {
    return threadFingerprint(prev) !== threadFingerprint(next);
}
