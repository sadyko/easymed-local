export const ACT_AS_TAB_HEADER = 'X-Em-Act-As';

/**
 * Ревью безопасности (HIGH 2) — виды документов визита (visit_documents.doc_type),
 * которые составляет и подписывает врач: протокол приёма, заключение,
 * заключение диагностики, история болезни, лабораторный бланк. Их от чужого
 * имени не создают и не правят (R3); прочие (заметка, загруженный файл) — можно.
 */
export const ACT_AS_DOCTOR_DOC_TYPES = Object.freeze(['protocol', 'conclusion', 'diag', 'case_file', 'lab']);
export function isDoctorDocType(docType) {
  return typeof docType === 'string' && ACT_AS_DOCTOR_DOC_TYPES.includes(docType.trim().toLowerCase());
}

/** Работает ли этот пользователь сессии от имени (рядом — администратор). */
export function isActing(user) {
  return !!(user && user.acting_admin);
}

/**
 * Имя действующего для журналов клиники (patient_activity_log.actor_name,
 * invoice_audit_log.actor_name): «Иванова А. (от имени: адм. Петров П.)».
 * Номер (actor_user_id, created_by) остаётся номером сотрудника — права и
 * принадлежность записей работают как у него; кто действовал на самом деле —
 * в имени и в журнале act_as_actions. Без входа от имени — имя как есть.
 */
export function actingActorName(user, name) {
  if (!isActing(user)) return name;
  const admin = String(user.acting_admin.full_name || '').trim();
  return `${String(name == null ? '' : name).trim()} (от имени: адм. ${admin})`.trim();
}
