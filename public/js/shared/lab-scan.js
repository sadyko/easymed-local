// BC-780, не прочитав штрихкод пробирки, присылает пробу со своим номером
// «Inv.<номер прогона>_<штатив>-<место>» (снимок владельца: «Inv.114220_2-1»,
// «Inv.114245_2-2» — штатив 2, места 1 и 2). Проба ложится в «Необработанные».
// В лотке видно, где пробирка (штатив, место); «Привязать» принимает этикетку,
// отсканированную сканером компьютера (8 цифр под штрихкодом), и приём кладёт пробу
// так, как будто этот номер прислал сам анализатор (server/lis/ingest.js scanLabel).
// Номер заказа без нулей («123») или «LAB-000123» — прежняя ручная привязка.
//
// Модуль чистый: без DOM, без сети, без импортов — его грузят и сервер, и браузер.

/**
 * Номер пробы, которым анализатор называет пробирку с непрочитанным штрихкодом.
 * Это не номер заказа: цифры из него не берутся никогда (номер прогона совпал бы
 * с чужим заказом). null — не такой номер.
 * @returns {{run:string, rack:number, pos:number}|null}
 */
export function noReadSample(raw) {
    const m = /^Inv\.(\d+)_(\d+)-(\d+)$/i.exec(String(raw == null ? '' : raw).trim());
    return m ? { run: m[1], rack: Number(m[2]), pos: Number(m[3]) } : null;
}

/**
 * Что отсканировали или набрали в «Привязать»:
 *   { label }   — ровно 8 цифр (этикетка строки или дня визита): приём — как у прибора;
 *   { orderId } — номер заказа цифрами («123») или прежней этикеткой «LAB-000123»
 *                 («ДФИ-000123» — она же на русской раскладке): ручная привязка, как прежде;
 *   null        — не номер.
 */
export function attachInput(typed) {
    const s = String(typed == null ? '' : typed).trim();
    if (/^\d{8}$/.test(s) && Number(s) > 0) return { label: s };
    const m = /^(?:lab|дфи)-(\d+)$/iu.exec(s);
    const n = m ? Number(m[1]) : /^\d+$/.test(s) ? Number(s) : 0;
    return Number.isSafeInteger(n) && n > 0 ? { orderId: n } : null;
}
