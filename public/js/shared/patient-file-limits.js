// PATIENT_PHOTO_V1 (2026-09-05) — ФОТОГРАФИЯ — НЕ ДОКУМЕНТ.
//
// Правила выше описывают ВЛОЖЕНИЕ к карте: скан направления, PDF выписки,
// таблицу анализов. Их кладут, чтобы потом ОТКРЫТЬ и рассмотреть, поэтому они
// хранятся ровно такими, какими пришли, и предел у них большой.
//
// Фотография пациента и врача живёт по другим законам:
//   • она ВСЕГДА картинка — Word и Excel «фото» быть не могут;
//   • её показывают квадратиком 96 px (карточка пациента) и 156 px (профиль
//     врача), а телефон снимает 4000×3000 и 5–12 МБ. Хранить исходник, чтобы
//     нарисовать из него аватар, — это платить диском и КАЖДОЙ ЕЖЕДНЕВНОЙ
//     резервной копией (снимок storage делается жёсткими ссылками, но первая
//     копия каждого файла — настоящая) за то, чего никто не увидит;
//   • регистратура снимает её ВЕСЬ ДЕНЬ, по одной на каждого нового пациента.
//
// Поэтому браузер УМЕНЬШАЕТ фотографию перед отправкой (photo-downscale.js), а
// предел здесь — это потолок ДЛЯ УЖЕ УМЕНЬШЕННОГО файла и для всякого клиента,
// который уменьшать не стал (curl, старый браузер без canvas).
// ---------------------------------------------------------------------------

// 8 МБ. После уменьшения портрет весит 100–250 КБ, то есть предел не задевает
// НИ ОДНОГО честного снимка: он ловит попытку залить в аватар исходник с
// зеркалки или видео, переименованное в .jpg. Меньше документного (20 МБ)
// намеренно — это разные вещи, и одинаковое число сделало бы вид, будто они
// одна.
export const MAX_PATIENT_PHOTO_BYTES = 8 * 1024 * 1024;
export const MAX_PATIENT_PHOTO_MB = Math.round(MAX_PATIENT_PHOTO_BYTES / (1024 * 1024));

// СПИСОК — ТОЛЬКО ТО, ЧТО БРАУЗЕР КЛИНИКИ УМЕЕТ ПОКАЗАТЬ в <img>. Это не
// придирка: продукт работает на Windows-машинах регистратуры, и Chrome там не
// рисует HEIC. Принять .heic значило бы сохранить файл, который навсегда
// останется битым квадратом на месте лица, — отказ с объяснением честнее.
export const ALLOWED_PHOTO_EXT = Object.freeze(['.jpg', '.jpeg', '.png', '.webp', '.gif', '.bmp']);

const PHOTO_OK = new Set(ALLOWED_PHOTO_EXT);
// Отдельная ветка отказа: айфон снимает в HEIC по умолчанию, и человек, который
// это получил, должен узнать НЕ «формат не подходит», а что именно переключить.
const HEIC = new Set(['.heic', '.heif']);

export function isAllowedPhoto(name) {
    return PHOTO_OK.has(extensionOf(name));
}

/**
 * Годится ли файл на роль фотографии. Возвращает null или {code, template,
 * params} — тот же вид отказа, что patientFileRefusal, и та же логика: перевод
 * шаблона целиком, подстановка потом (I18N_COVERAGE_V1).
 */
export function photoRefusal({ name, size }) {
    const ext = extensionOf(name);
    if (HEIC.has(ext)) {
        return {
            code: 'photo_heic',
            template: 'Формат HEIC браузер клиники не показывает. Переснимите в JPEG или переключите камеру телефона на «Наиболее совместимый».',
            params: {},
        };
    }
    if (!isAllowedPhoto(name)) {
        return {
            code: 'photo_not_an_image',
            template: 'Фото должно быть картинкой, а «{ext}» ею не является. Подойдут JPG, PNG и WebP.',
            params: { ext: ext || String(name || '').slice(-20) || '?' },
        };
    }
    if (!Number.isFinite(Number(size)) || Number(size) <= 0) {
        return { code: 'file_empty', template: 'Фотография пустая — сохранять нечего.', params: {} };
    }
    if (Number(size) > MAX_PATIENT_PHOTO_BYTES) {
        return {
            code: 'file_too_large',
            template: 'Фотография {got} МБ — это больше предела в {max} МБ. Переснимите в меньшем качестве.',
            params: { got: mb(size), max: String(MAX_PATIENT_PHOTO_MB) },
        };
    }
    return null;
}

// Уменьшение: длинная сторона 1024 px. Это в 6.5 раза больше самого крупного
// места, где фотографию сегодня показывают (156 px в профиле врача), и вдвое
// больше того же места на экране с двойной плотностью, — то есть запас на
// «показать покрупнее» есть, а исходника с телефона нет.
//
// ВНИМАНИЕ: уменьшается ТОЛЬКО портрет из двух виджетов фото. Вложение карты
// пациента (скан направления, снимок анализа) проходит МИМО — его открывают,
// чтобы прочитать мелкий текст, и ужать его значило бы тихо испортить
// документ. Разные пути, разные правила, и это единственная причина, по
// которой уменьшение живёт здесь, а не в общем загрузчике.
export const PHOTO_MAX_SIDE = 1024;
export const PHOTO_JPEG_QUALITY = 0.85;

/**
 * Во что превратить картинку w×h. null — уменьшать нечего (она уже меньше
 * предела): увеличивать снимок ради «стандартного размера» бессмысленно, он от
 * этого лучше не станет, а весить будет больше.
 */
export function photoTargetSize(w, h, maxSide = PHOTO_MAX_SIDE) {
    const W = Math.round(Number(w) || 0), H = Math.round(Number(h) || 0);
    if (W <= 0 || H <= 0) return null;
    const longest = Math.max(W, H);
    if (longest <= maxSide) return null;
    const k = maxSide / longest;
    return { width: Math.max(1, Math.round(W * k)), height: Math.max(1, Math.round(H * k)) };
}
