// LAB_ONE_BARCODE_V1 (решение владельца 2026-11-07, п. 10) — ОДИН ШТРИХ-КОД НА ДЕНЬ ВИЗИТА.
//
// Было (3.21, LAB_TUBE_LABEL_V1): «Штрих-код» карточки печатал этикетку на каждую
// пробирку, номер — строка заказа (8 цифр: «00000123»). Лаборатория клеит одну
// этикетку на все пробирки; номер строки «СОЭ» (материал не указан) на пробирке
// крови, и BC-780 заполнял только её, а ОАК («Кровь», второй в списке) оставался
// пустым («не использованы»): приём делил пробирку по материалу заказа номера.
//
// Стало: на карточке ОДИН номер на день визита — для всех анализов этого дня, одна и
// та же этикетка на каждую пробирку. Номер — не заказ, а ДЕНЬ ВИЗИТА: приём по нему
// заполняет КАЖДУЮ строку этого дня визита, которую кормит прибор, в любом порядке
// (ingest.js dayAnchor). Чтобы приём отличал такую этикетку от этикетки строки
// («Печать этикетки», «Забор пробы», этикетки 3.21 уже на пробирках — у них прежние
// правила), номер — в своём ряду: 9 и семь цифр — 90000000 + номер самой старой
// открытой оплаченной лабораторной строки дня. По этой строке приём находит визит и
// день; сама строка ничего не решает (выдана, возвращена — номер дня прежний).
// Строк заказов больше 9 999 999 в клинике нет; у такой строки этикетки дня нет —
// карточка печатает прежние этикетки пробирок.
//
// Модуль чистый: без DOM, без сети, без импортов — его грузят и сервер, и браузер.
export const DAY_LABEL_BASE = 90000000;
const LIMIT = 10000000;

/** Помещается ли номер строки в номер этикетки дня. */
export function dayLabelFits(lineId) {
    const n = Number(lineId);
    return Number.isInteger(n) && n > 0 && n < LIMIT;
}

/** Номер этикетки дня (8 цифр) по номеру строки; '' — не помещается. */
export function dayLabelValue(lineId) {
    return dayLabelFits(lineId) ? String(DAY_LABEL_BASE + Number(lineId)) : '';
}

/** Номер строки по номеру этикетки дня (число); null — это не этикетка дня. */
export function dayLabelLine(n) {
    const v = typeof n === 'number' ? n : Number(String(n == null ? '' : n).trim());
    if (!Number.isInteger(v) || v <= DAY_LABEL_BASE || v >= DAY_LABEL_BASE + LIMIT) return null;
    return v - DAY_LABEL_BASE;
}
