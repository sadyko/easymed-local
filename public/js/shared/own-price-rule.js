// своя цена действовала на любом ярусе как есть) — своя цена врача
// (users.service_rates[].price) получает ТУ ЖЕ скидку яруса, что и каталог.
// Каталог 200 000 первый визит, 60 000 второй, повторный бесплатно; своя цена
// 300 000 → 300 000, 90 000 (30 % своей), 0. Правило:
//   • своей цены нет — цена яруса (tierUnitPrice / котировка, с откатами
//     ярусов), а для первичного — каталог, как прежде;
//   • своя цена и первичный ярус (или у услуги нет ярусов, или строка
//     стационара без ярусов) — своя цена;
//   • своя цена и второй / повторный ярус — своя × (цена яруса ÷ каталог
//     первичного): цена яруса — та, что вернул priceForTier после откатов, база —
//     services.price. Бесплатный ярус — 0; ярус дороже первичного — дороже в той
//     же доле (без зажима); каталог первичного ≤ 0 или его нет — долю не
//     посчитать, берётся своя цена.
//   • Округление — до 0,01 (round2), как у строк и счетов (billing.js: строка
//     round2(цена × кол-во), скидки и итоги — round2); целые сумы — это
//     отображение, не расчёт. Экран и сервер получают одно и то же число, потому
//     что считают этой функцией.
// Ярус строки (price_tier) по-прежнему пишется — по нему считаются визиты;
// меняется только цена.
//
// Правило живёт ЗДЕСЬ и только здесь: его читают сервер (domain/pricing.js
// lineUnitPrice — счёт, «Ждут счёта», правки кассы, доля врача;
// rpc/service-price-quote.js — котировка) и экраны (мастер визита,
// Калькулятор). Вторая копия правила уже однажды разошлась с первой: смета
// называла одно, касса выставляла другое.
//
// Чистые функции: ни сети, ни DOM, ни базы.

/**
 * Сохранённая своя цена → число или null («своей цены нет»).
 * То же условие, что у сервера (domain/pricing.js OWN_PRICE_ENTRY): число JSON
 * или строка из цифр ('80000', '80000.5'), не меньше нуля. Пусто, null,
 * 'abc', отрицательное — своей цены нет, и строка берёт цену яруса. 0 —
 * настоящая бесплатная цена, а не «нет цены».
 *
 * Ревью 1 — строка разбирается РОВНО как у сервера, чтобы смета никогда не
 * разошлась со счётом:
 *   • отбор — trim(...) GLOB '[0-9]*' AND NOT GLOB '*[^0-9.]*': trim SQLite
 *     снимает только пробелы (не табуляцию), первая — цифра, дальше — цифры и
 *     точки;
 *   • число — CAST(... AS REAL): самое длинное начало строки, которое читается
 *     как число, остальное отбрасывается: '80.000.5' → 80, '80.' → 80.
 * (Сам этот разбор у сервера снисходителен — '80.000' читается как 80, а не
 * 80 000; экран его повторяет, а не исправляет: правило одно.)
 */
export function ownPriceValue(price) {
    if (price === null || price === undefined) return null;
    if (typeof price === 'number') return Number.isFinite(price) && price >= 0 ? price : null;
    if (typeof price === 'string') {
        const s = price.replace(/^ +| +$/g, '');
        if (!/^[0-9][0-9.]*$/.test(s)) return null;
        const n = Number(/^[0-9]+(?:\.[0-9]*)?/.exec(s)[0]);
        return Number.isFinite(n) && n >= 0 ? n : null;
    }
    return null;
}

/**
 * Своя цена врача по услуге из его списка ставок (users.service_rates) или
 * null. При дублях услуги в списке берётся первая запись С ЦЕНОЙ — правило
 * сервера (FINAL_MONEY_FIX_V1 M4): ставка без цены своей цены не отменяет.
 */
export function ownPriceFromRates(rates, serviceId) {
    if (!Array.isArray(rates)) return null;
    const sid = String(serviceId);
    for (const r of rates) {
        if (!r || String(r.service_id) !== sid) continue;
        const own = ownPriceValue(r.price);
        if (own !== null) return own;
    }
    return null;
}

// Деньги — до 0,01, как round2 в billing.js.
const round2 = (n) => Math.round(n * 100) / 100;

/**
 * ЦЕНА СТРОКИ УСЛУГИ (OWN_PRICE_TIER_RATIO_V1).
 * `own` — своя цена врача: ответ ownPriceValue / ownPriceFromRates /
 *   doctorPriceFor (null — своей нет);
 * `tierPrice` — цена яруса этой строки по каталогу, после откатов ярусов
 *   (первичный или услуга без ярусов — сам каталог);
 * `basePrice` — каталог первичного визита (services.price).
 * Своей цены нет — tierPrice как есть. Своя есть — own × tierPrice ÷ basePrice
 * до 0,01; ярус равен каталогу первичного — ровно own; каталога первичного нет
 * или он ≤ 0 — долю не посчитать, ровно own.
 */
export function serviceLinePrice(own, tierPrice, basePrice) {
    if (own === null || own === undefined) return tierPrice;
    const tier = Number(tierPrice);
    const base = basePrice === null || basePrice === undefined || basePrice === '' ? NaN : Number(basePrice);
    // Каталог первичного ≤ 0 или неизвестен — доля не считается: своя цена.
    if (!Number.isFinite(base) || base <= 0) return own;
    // Первичный ярус (цена яруса = каталог первичного) или цены яруса нет.
    if (!Number.isFinite(tier) || tier === base) return own;
    return round2(own * tier / base);
}
