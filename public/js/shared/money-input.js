// MONEY_INPUT_V2 — разбор и показ денежной суммы в поле ввода.
//
// Живёт отдельным модулем не ради красоты, а потому что здесь уже один раз
// потерялись два символа. В cashier-desk.js регулярки выглядели так:
//
//     value.replace(/D+/g, '')      // хотели \D — «всё, что не цифра»
//     /^d+$/.test(value)            // хотели \d
//
// Без обратной косой это литеральная буква «D»: из строки вычищались буквы D,
// а пробел-разделитель тысяч оставался. Дальше Number('5 0000') = NaN, а
// `Number(n) || 0` превращал NaN в ноль — и поле «Сумма» на пятой цифре
// схлопывалось в «0». Та же ошибка в moneyVal означала, что ЛЮБАЯ сумма от
// тысячи уходила на сервер нулём, даже когда на экране выглядела правильно.
//
// Внутри DOM такую вещь не проверить тестом, поэтому вся арифметика вынесена
// сюда — в чистые функции, у которых тесты есть.

// Только цифры. Пробелы, неразрывные пробелы, запятые, буквы — всё прочь.
export function digitsOf(value) {
    return String(value == null ? '' : value).replace(/\D+/g, '');
}

// «500000» -> «500 000». Разделитель — обычный пробел, как во всей кассе.
export function groupThousands(digits) {
    return String(digits).replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
}

// Что показать в поле после ввода. Пустая строка остаётся пустой: иначе поле
// нельзя было бы очистить, оно бы само подставляло «0».
export function moneyDisplay(value) {
    const d = digitsOf(value).replace(/^0+(?=\d)/, '');   // ведущие нули не нужны
    return d ? groupThousands(d) : '';
}

// Что отправить на сервер. Не Number(строка с пробелами), а число из цифр.
export function moneyNumber(value) {
    const d = digitsOf(value);
    if (!d) return 0;
    const n = Number(d);
    return Number.isSafeInteger(n) ? n : 0;
}
