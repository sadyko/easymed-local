// REFERRAL_SOURCE_CODE_V1 — как источник направления подписан ВЕЗДЕ, где его
// выбирает регистратор: мастер записи, подбор услуг, карточка визита.
//
// Один модуль на три экрана, потому что подпись должна совпадать: регистратор
// диктует номер по телефону и ищет по нему же, а три слегка разошедшихся
// написания превратили бы «нашёл 0007» в «нашёл в одном списке из трёх».
//
// НОМЕР ИДЁТ ПЕРВЫМ, и это не оформление. Списки партнёров — обычные <select>,
// а браузер ищет в них набором с начала подписи: пока номер стоит впереди,
// «0007» набором находит партнёра, а иначе не находит ничего.
export function referralSourceLabel(s) {
  if (!s) return '';
  const name = (s.name || '').trim() || '(без имени)';
  const code = (s.code || '').trim();
  return code ? code + ' · ' + name : name;
}
