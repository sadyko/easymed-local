// CLINIC_API_FIX_V1 — ФЛАГ ИЗ БАЗЫ: «ДА» — ЭТО true, 1 ИЛИ «1».
//
// SQLite не знает «да/нет»: флаг лежит числом 0/1, и /api/db отдаёт его как
// есть, без перевода в true/false. Экран, сравнивавший флаг с false/true,
// читал его наоборот: `0 !== false` — «включено», `1 === true` — «выключено».
// Так «Консультации врачей» (doctor_consultation_prices.available / is_free)
// возвращали снятую галочку «Ведёт» и теряли «Бесплатно», а окно записи и
// кабинет врача предлагали приём, который врач не ведёт.
//
// Всё прочее — false, 0, «0», null, пусто — «нет». Значение по умолчанию
// (строки нет вовсе) решает вызывающий: у него оно своё.
export function isOn(v) {
    return v === true || v === 1 || v === '1';
}
