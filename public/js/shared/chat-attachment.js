// TELEGRAM_CHAT_FILE_V1 — вложение в ответе оператора: общие правила.
//
// Живёт в public/js/shared/, потому что правила нужны ОБОИМ рантаймам: браузер
// по ним отбивает слишком большой файл ДО загрузки и рисует подпись к нему,
// сервер — решает, чем отправлять в Telegram и под каким именем это увидит
// пациент. Разъедься эти два набора, и оператор получил бы файл, который
// браузер принял, а сервер отказался слать (или наоборот). Тот же приём, что у
// shared/payment-methods.js и shared/doc-render.js.
//
// Модуль чистый: ни DOM, ни node-встроенных, поэтому грузится и там, и там.

// Потолок берём у СВОЕЙ загрузки (routes/storage.js: raw limit '20mb'), а не у
// Telegram, который принимает у бота до 50 МБ. Узкое место — наше, и отказ
// должен приходить сразу, а не после того, как оператор десять минут ждал
// заливку по клинической сети.
export const MAX_ATTACHMENT_BYTES = 20 * 1024 * 1024;

// Картинки уходят через sendPhoto, всё остальное — через sendDocument.
// Разница не косметическая: фото пациент видит прямо в переписке, а документ
// сначала надо скачать. Результат анализа сфотографирован телефоном — его
// смотрят, не скачивая.
//
// Список нарочно короткий и консервативный: это те форматы, которые Telegram
// точно покажет как фото. SVG сюда НЕ входит — Telegram его фотографией не
// считает и вернёт ошибку, а HEIC с айфона показывает не везде; оба уйдут
// документом и дойдут гарантированно.
// Подпись к файлу Telegram ограничивает 1024 символами — против 4096 у обычного
// сообщения. Кто отправляет, тот и решает, что делать с текстом длиннее: чат и
// рассылка одинаково отправляют его ОТДЕЛЬНЫМ сообщением целиком, а не режут.
export const CAPTION_LIMIT = 1024;

const IMAGE_EXT = ['.jpg', '.jpeg', '.png', '.gif', '.webp', '.bmp'];

export function extensionOf(name) {
    const s = String(name || '');
    const dot = s.lastIndexOf('.');
    return dot > 0 ? s.slice(dot).toLowerCase() : '';
}

export function isImageName(name) {
    return IMAGE_EXT.includes(extensionOf(name));
}

// Имя, которое УВИДИТ ПАЦИЕНТ. Это не имя файла на диске: на диск кладётся
// обезличенный ключ (storage.js), а в Telegram уходит то, как файл назвал
// оператор, — «Анализ крови.pdf» понятнее, чем «1737..-a3f9-.pdf».
//
// Поэтому кириллицу и пробелы здесь НЕ трогаем: режем только то, чем можно
// навредить, — разделители пути, NUL и управляющие символы. Это же значение
// уходит в multipart-заголовок, где перевод строки позволил бы подделать
// соседние поля формы.
export function safeAttachmentName(name) {
    const cleaned = String(name || '')
        .replace(/[\\/\0]+/g, '_')
        // eslint-disable-next-line no-control-regex
        .replace(/[\x00-\x1f\x7f]+/g, ' ')
        .replace(/\s+/g, ' ')
        .trim();
    if (!cleaned || cleaned === '.' || cleaned === '..') return 'file';
    return cleaned.slice(0, 120);
}

// Человеческий размер для подписи под вложением.
export function humanSize(bytes) {
    const n = Number(bytes) || 0;
    if (n < 1024) return n + ' Б';
    if (n < 1024 * 1024) return Math.round(n / 1024) + ' КБ';
    return (n / (1024 * 1024)).toFixed(n < 10 * 1024 * 1024 ? 1 : 0) + ' МБ';
}

// Почему файл нельзя отправить — текстом для оператора, или null, если можно.
//
// Возвращаем СООБЩЕНИЕ, а не false: «нельзя» без причины заставляет пробовать
// ещё раз тем же способом. Принимает и File из браузера, и { name, size } с
// сервера — проверка одна и та же с обеих сторон.
export function attachmentError(file) {
    if (!file) return 'Файл не выбран.';
    const size = Number(file.size);
    if (!Number.isFinite(size) || size <= 0) return 'Файл пустой — отправлять нечего.';
    if (size > MAX_ATTACHMENT_BYTES) {
        return `Файл больше ${humanSize(MAX_ATTACHMENT_BYTES)} (${humanSize(size)}) — такой отправить нельзя.`;
    }
    return null;
}
