export const KEY_LOSS_WARNING = 'Easy-Med не хранит ваш ключ синхронизации и не может прочитать переданные данные — '
  + 'а значит, не сможет и восстановить их, если ключ будет потерян. Единственная копия ключа — в самих филиалах.';

/**
 * Что написано под переключателем «резервный канал», для каждой роли отдельно.
 * Роли делают разные вещи: главный филиал ОТДАЁТ копию наружу, подключённый
 * только берёт уже лежащую, и путать эти два согласия нельзя.
 *
 * По одной строке на роль вместо двух предложений. Что делает переключатель,
 * уже написано на нём самом («Использовать сервер Easy-Med, когда прямая связь
 * недоступна»); здесь остаётся только то, чего на нём нет, — что копия
 * зашифрована и что прямой путь всё равно первый.
 *
 * Русская версия главного филиала («Зашифрованная копия справочника будет
 * лежать…») — вторая из двух строк, которые владелец видел по-русски на
 * английском экране: её тоже не было в i18n-strings.js. Новая короткая —
 * есть, во всех трёх языках.
 */
export function relayExplainer(status) {
  const role = status && status.role;
  if (role !== 'main') return 'Прямая связь пробуется первой; копия с сервера — только если она недоступна.';
  // RELAY_COPY_TRUTH_V1 — при выключенном канале нельзя говорить «копия
  // лежит»: рядом стоит publishLine со строкой «Копия на сервер не
  // отправляется», и вдвоём они рассказывали об одном и том же две разные
  // вещи. Владелец увидел эту пару на своём экране 2026-09-02.
  //
  // Условное наклонение — не смягчение, а факт: копии там сейчас нет.
  if (!status || !status.relay_enabled) {
    return 'Копия шифруется здесь: включите канал — на сервер ляжет блоб, который там не прочитать.';
  }
  return 'Копия лежит на сервере Easy-Med зашифрованной — прочитать её там нельзя.';
}

/**
 * Что показать про последнюю выгрузку копии — только у главного филиала.
 * Шаблоном: дата внутри фразы делала её непереводимой.
 *
 * @returns {{template:string, params:object}|null}
 */
export function publishLine(status) {
  if (!status || status.role !== 'main') return null;
  if (!status.relay_enabled) return { template: 'Копия на сервер не отправляется.', params: {} };
  const last = status.relay_last_publish;
  if (!last || !last.at) return { template: 'Копия на сервер ещё ни разу не отправлялась.', params: {} };
  return { template: 'Копия на сервере обновлена {date}.', params: { date: whenLabel(last.at) } };
}

/**
 * ПЕРВИЧНАЯ ЗАГРУЗКА — строка про засев (Задача 7e, I-3).
 *
 * Засев большой клиники идёт страницами и часами. Без числа страниц экран
 * говорит «идёт синхронизация», что неотличимо от «зависло», и владелец звонит
 * в поддержку на второй час. С числом — это ожидание, а не поломка.
 *
 * null — засева нет, и экрану про него говорить нечего.
 */
export function seedLine(status) {
  const seed = status && status.seed;
  if (!seed) return null;

  if (seed.receiving) {
    const { page, pages, from } = seed.receiving;
    // «~», потому что оценка и есть оценка: строки прибавляются по ходу.
    if (pages > 0) {
      return {
        tone: 'info',
        template: 'Первичная загрузка из филиала {letter}: страница {page} из ~{pages}.',
        params: { letter: from, page, pages },
      };
    }
    return {
      tone: 'info',
      template: 'Первичная загрузка из филиала {letter}: страница {page}.',
      params: { letter: from, page },
    };
  }

  const list = seed.sending || [];
  if (!list.length) return null;
  // Буквы отдельно, номер страницы отдельно: русский текст не склеивается со
  // значением плюсом (перевод идёт по ЦЕЛОЙ строке, и склейка ломает узбекскую
  // версию — это ловит i18n-coverage). Страница — самая отстающая: она и есть
  // ответ на вопрос «сколько ещё ждать».
  const page = list.reduce((min, b) => Math.min(min, b.page), list[0].page);
  return {
    tone: 'info',
    template: 'Идёт первичная загрузка в филиалы: {branches} (страница {page}). Это занимает несколько часов.',
    params: { branches: list.map((b) => b.letter).join(', '), page },
  };
}

/**
 * Можно ли перевыпустить ключ. Подключённый филиал — нельзя: его ключ выдаёт
 * главный, и перевыпуск у себя просто отвалил бы филиал от группы, ничего не
 * починив.
 */
export function canRegenerateKey(status, admin) {
  return !!(admin && status && status.role !== 'secondary');
}

/** Можно ли вообще нажимать «Синхронизировать сейчас». */
export function canSyncNow(status, admin) {
  return !!(admin && status && status.role === 'secondary');
}

