// BRANCH_SYNC_V1 — все РЕШЕНИЯ экрана «Настройки → Филиалы» о том, что писать
// на экране, отдельно от самого рисования. Тот же приём и по той же причине,
// что у system-logic.js: без фальшивого DOM проверяется именно то, ради чего
// экран существует — что филиал, который не достучался до главного, говорит об
// этом ровно и честно, а не «Ошибка».
//
// Ни сети, ни DOM, ни собственных часов. Любое поле ответа сервера может
// отсутствовать: экран обязан пережить и старый сервер, и испорченную запись о
// прошлой синхронизации — прочерк вместо факта, но никогда «undefined».
//
// -------------------------------------------------------------------------
// BRANCH_LIST_V2 (2026-08-30) — ДВА ПРАВИЛА, ПЕРЕПИСАВШИЕ ЭТОТ ФАЙЛ.
//
// 1. МЕНЬШЕ ТЕКСТА. Дословно от владельца: «can we remove the unnecessary
//    information and make clear list of main branch, and and the list of
//    branches keys etc, all the sloppy text that no one will read is
//    unnecessary». Под каждым управляющим элементом стоял абзац: около
//    пятнадцати строк прозы вокруг шести кнопок. Абзацы не читают — их
//    пролистывают, и вместе с ними пролистывают то единственное, что читать
//    было обязательно.
//
//    Правило теперь такое: фраза живёт там, где принимается решение. Всё
//    необратимое переехало в окно подтверждения (KEY_REISSUE_WARNING,
//    KEY_LOSS_WARNING, LETTER_PERMANENCE_WARNING, UNLINK_WARNING_*) — его
//    нельзя пролистать, его надо закрыть. Состояние строки списка стало
//    коротким словом или меткой вместо трёх строк объяснения. Ничего не
//    выброшено: каждое предупреждение ниже названо и у каждого есть адрес.
//
// 2. ПЕРЕВОДИМОСТЬ. tr() (i18n.js) ищет в словаре строку ЦЕЛИКОМ, поэтому
//    фраза, склеенная из кусков или с подставленной датой, не найдётся там
//    никогда и уедет в узбекскую клинику по-русски. Ровно это и случилось с
//    «Ключ синхронизации есть. Создан 12.08.2026.» — её нет и не могло быть в
//    i18n-strings.js.
//
//    Поэтому каждая динамическая фраза здесь возвращает не готовый текст, а
//    {template, params}: template — целая русская фраза с дырками {date},
//    и она же ключ словаря; экран делает tr(template) и только потом fill().
//    Тот же приём, что у updates-logic.js (коммит 08ab775) и branch-picker.js.
//    Куски, которые собираются внутри фразы (путь синхронизации, перечень
//    изменений), переводит переданный сюда translate — по умолчанию он ничего
//    не делает, чтобы файл оставался чистой функцией без i18n.js.

import { formatRuDateTime, DASH } from './system-logic.js';

// Названия таблиц справочника по-русски. Русские литералы: экран прогоняет их
// через translate (см. заголовок), а ru/uz/en живут в i18n-strings.js.
const TABLE_WORDS = {
  services: 'услуги',
  lab_panels: 'лабораторные панели',
  lab_panel_analytes: 'показатели',
  service_types: 'типы услуг',
  service_categories: 'категории услуг',
  departments: 'отделения',
};

/**
 * Переводчик по умолчанию — тождественный.
 *
 * Так этот файл остаётся тем, ради чего он заведён: чистыми функциями без
 * импорта i18n.js, которые тест зовёт напрямую. Экран передаёт сюда tr(), а
 * тест — свою пометку, чтобы проверить, что через переводчик прошла КАЖДАЯ
 * склеиваемая часть, а не только внешняя фраза.
 */
const ID = (s) => s;

/** Роль установки одной строкой + вид метки. */
export function roleBadge(status) {
  const role = status && status.role;
  if (role === 'main') return { label: 'Главный филиал', kind: 'ok' };
  if (role === 'secondary') return { label: 'Подключённый филиал', kind: 'info' };
  return { label: 'Не связан', kind: '' };
}

/**
 * Что эта установка делает — ОДНОЙ КОРОТКОЙ СТРОКОЙ под меткой роли.
 *
 * Раньше здесь стояло по два предложения на роль, и у подключённого филиала
 * они дословно повторяли абзац «Синхронизация переносит только справочник…»,
 * который висел ниже под кнопкой. Один и тот же факт, набранный дважды на
 * одном экране, — это не забота, а шум: он учит пролистывать оба.
 */
export function roleExplainer(status) {
  const role = status && status.role;
  if (role === 'main') return 'Раздаёт справочник филиалам: услуги, цены и лабораторные панели.';
  if (role === 'secondary') return 'Получает справочник из главного. Пациенты, визиты и деньги остаются здесь.';
  return 'Назначьте один компьютер главным, на остальных введите его ключ подключения.';
}

const dash = (v) => (v === null || v === undefined || v === '' ? DASH : v);

/** «12.08.2026 19:40» либо прочерк. */
export function whenLabel(iso) {
  return dash(formatRuDateTime(iso));
}

/**
 * Что изменила синхронизация, человеческими словами.
 *
 * Показывать «Готово» после каждого нажатия — значит не различать «приехали
 * новые цены» и «ничего не менялось», а это ровно тот вопрос, ради которого
 * владелец на экран и смотрит.
 *
 * Каждое СЛОВО отсюда идёт через translate по отдельности, а числа и знаки
 * препинания склеиваются вокруг уже переведённых слов: перечень вида
 * «добавлено: услуги — 4» собирается из данных сервера и целой строкой в
 * словаре не найдётся никогда.
 */
export function changesLabel(record, translate = ID) {
  if (!record || typeof record !== 'object' || record.ok !== true) return DASH;
  const parts = [];
  const group = (obj, word) => {
    if (!obj || typeof obj !== 'object') return;
    const items = Object.keys(obj)
      .filter((k) => TABLE_WORDS[k] && Number(obj[k]) > 0)
      .map((k) => `${translate(TABLE_WORDS[k])} — ${Number(obj[k])}`);
    if (items.length) parts.push(`${translate(word)}: ${items.join(', ')}`);
  };
  group(record.created, 'добавлено');
  group(record.updated, 'обновлено');
  if (record.settings) parts.push(translate('обновлены сведения о клинике'));
  if (!parts.length) return translate('Изменений не было — справочник уже совпадает.');
  return parts.join('; ') + '.';
}

/**
 * Каким путём приехал справочник. BRANCH_SYNC_RELAY_V1.
 *
 * Это не украшение строки состояния, а её смысл. Клиника платит за VPN между
 * зданиями; если он полгода как не работает и справочник всё это время ездит
 * через сервер поставщика (в зашифрованном виде, но всё же наружу), владелец
 * обязан видеть это на экране, а не узнать случайно. Поэтому путь называется
 * вслух в ОБОИХ случаях, а не только в «плохом».
 */
export function routeLabel(record, translate = ID) {
  return translate(record && record.route === 'relay'
    ? 'через сервер Easy-Med (зашифровано)'
    : 'напрямую');
}

/**
 * Одна строка о состоянии связи: когда получилось в последний раз, каким путём
 * и что случилось при последней попытке.
 *
 * ЧЕТЫРЕ ШАБЛОНА ВМЕСТО ОДНОЙ СКЛЕЙКИ. Раньше эта функция возвращала
 * `Синхронизировано ${when} — ${route}.${age} ${changes}` — строку, которой в
 * словаре нет и быть не может, поэтому вся она уезжала в узбекскую клинику
 * по-русски. Теперь наружу идёт целая русская фраза с дырками (она же ключ
 * словаря) и значения к ней отдельно.
 *
 * message приходит С СЕРВЕРА уже по-русски и через словарь экрана не проходит —
 * это известная дыра шире одного экрана, и она отмечена в отчёте, а не
 * замазана здесь.
 *
 * @returns {{tone:'ok'|'warn'|'none', template:string, params:object}}
 *   'warn' — последняя попытка провалилась; экран красит эту строку иначе.
 */
export function syncLine(status, translate = ID) {
  const attempt = status && status.last_attempt;
  const okRec = status && status.last_ok;
  if (!attempt && !okRec) return { tone: 'none', template: 'Синхронизации ещё не было.', params: {} };

  if (attempt && attempt.ok === false) {
    const message = typeof attempt.message === 'string' && attempt.message
      ? attempt.message
      : translate('Не удалось синхронизироваться.');
    const when = whenLabel(attempt.at);
    // Прошлый успех не прячется за свежей неудачей: «связь была и сломалась
    // вчера» и «связь не работала никогда» — это два разных вызова мастеру.
    if (okRec && okRec.at) {
      return {
        tone: 'warn',
        template: '{message} (попытка {when}). Последний раз получилось: {last} ({route}).',
        params: { message, when, last: whenLabel(okRec.at), route: routeLabel(okRec, translate) },
      };
    }
    return { tone: 'warn', template: '{message} (попытка {when}).', params: { message, when } };
  }

  const rec = okRec || attempt;

  // BRANCH_MAIN_PUSH_V1 — УСПЕХ ГЛАВНОЙ КЛИНИКИ РАССКАЗЫВАЕТ СЕРВЕР.
  //
  // Всё, что ниже, описывает ПРИНЯТЫЙ справочник: путь, возраст копии,
  // перечень изменений. У главной клиники ничего этого нет и быть не может —
  // она справочник не принимает, а раздаёт, — поэтому её удачное нажатие
  // рисовалось строкой «Синхронизировано … — напрямую. Изменений не было —
  // справочник уже совпадает.», то есть отчётом о пустом действии ровно там,
  // где копия ушла на сервер, а записи соседей приехали.
  //
  // Фраза берётся с сервера целиком (reasonText в rpc/branch-sync.js): она
  // несёт размер копии и числа записей, то есть то, чего экран не знает.
  // Через словарь она не проходит — известная дыра, отмеченная выше.
  if (rec && rec.ok === true && typeof rec.message === 'string' && rec.message) {
    return {
      tone: 'ok',
      template: '{message} (синхронизация {when}).',
      params: { message: rec.message, when: whenLabel(rec.at) },
    };
  }

  const route = routeLabel(rec, translate);
  const changes = changesLabel(rec, translate);
  // Возраст копии договаривается только для резервного пути, и это не
  // придирка: прямым путём приезжает сегодняшний справочник, а через сервер —
  // копия на момент последней выгрузки главного филиала. Разницу между «цены
  // свежие» и «цены такие, какими были в понедельник» видно только отсюда.
  if (rec.route === 'relay' && rec.relayed_at) {
    return {
      tone: 'ok',
      template: 'Синхронизировано {when} — {route}. Копия главного филиала от {copy}. {changes}',
      params: { when: whenLabel(rec.at), route, copy: whenLabel(rec.relayed_at), changes },
    };
  }
  return {
    tone: 'ok',
    template: 'Синхронизировано {when} — {route}. {changes}',
    params: { when: whenLabel(rec.at), route, changes },
  };
}

/**
 * Состояние КЛЮЧА СИНХРОНИЗАЦИИ — того самого, что создаётся при активации
 * клиники и которым шифруется всё, что уходит на сервер поставщика.
 *
 * Три честных состояния, и ни одного бодрого:
 *   'none'     — ключа нет вовсе (установка активирована до Маршрута Б и ещё не
 *                открывала этот экран);
 *   'unpaired' — ключ есть, но пара создана раньше и его не несёт: резервный
 *                канал заработает только после перевыпуска ключа подключения;
 *   'ready'    — ключ есть и работает.
 *
 * ШАБЛОНОМ, А НЕ СТРОКОЙ, и это ровно та ошибка, которую владелец увидел на
 * английском экране: «Ключ синхронизации есть. Создан 12.08.2026 19:40.»
 * собиралась склейкой, поэтому tr() не могла найти её в словаре ни при каком
 * языке. «Ключ синхронизации есть» вдобавок повторяло заголовок блока прямо
 * над собой — осталась только дата.
 *
 * @returns {{state:'none'|'unpaired'|'ready', template:string, params:object}}
 */
export function syncKeyLine(status) {
  const present = !!(status && status.sync_key_present);
  const ready = !!(status && status.relay_ready);
  if (ready) {
    return status.sync_key_created_at
      ? { state: 'ready', template: 'Создан {date}.', params: { date: whenLabel(status.sync_key_created_at) } }
      : { state: 'ready', template: 'Ключ создан.', params: {} };
  }
  if (present) {
    return {
      state: 'unpaired',
      template: 'Чтобы включить резервный канал, выдайте филиалам ключи заново.',
      params: {},
    };
  }
  return { state: 'none', template: 'Ключ синхронизации ещё не создан.', params: {} };
}

