/**
 * Показывать ли блок «Сделать главным филиалом» — и если нет, то ПОЧЕМУ.
 *
 * Правило то же, что у can_issue и can_relay: кнопка, которую показали и
 * которая всегда отказывает, хуже отсутствующей. Владелец нажимает, читает
 * отказ и идёт искать, что он сделал не так, — тогда как отказ был предрешён до
 * нажатия.
 *
 *   'branch'  — установка уже является филиалом (identity_role: 'secondary').
 *               Отвязка этого не меняет: буква напечатана на карточках, и
 *               branch_sync_make_key отказывает кодом identity_is_branch.
 *               Объяснение уже стоит выше отдельным блоком, поэтому здесь
 *               достаточно убрать блок «главный»;
 *   'unknown' — установка не смогла прочитать свою служебную запись
 *               (identity_role: null). Раздавать буквы ей тоже нельзя — сервер
 *               отказывает кодом identity_missing, — но лекарство другое, и
 *               потому это ОТДЕЛЬНОЕ состояние, а не «филиал»: восстановить
 *               базу, а не вводить ключ подключения;
 *   'allowed' — обычная новая установка: identity_role: 'main'.
 *
 * ОТСУТСТВУЮЩЕЕ ПОЛЕ — ТОЖЕ 'unknown', и это не перестраховка. Поле приходит из
 * той же установки, которая отдала этот файл браузеру, поэтому «поля нет» может
 * означать только «прочитать не удалось», а это ровно тот случай, в котором
 * сервер откажет. Тупика из этого не выходит: экран называет состояние словами
 * и говорит, что делать.
 *
 * @returns {'allowed'|'branch'|'unknown'}
 */
export function becomeMainState(status) {
  const role = status && status.identity_role;
  if (role === 'secondary') return 'branch';
  if (role === 'main') return 'allowed';
  return 'unknown';
}

