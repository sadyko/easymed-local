/** Уровни, которые ИМЕЮТ СМЫСЛ для раздела: [] — раздел открыт или закрыт. */
export function levelsFor(key) {
    if (String(key).startsWith('settings:')) return ['editor', 'admin'];   // section-crud.js: правка и удаление строк справочника
    const a = MODULE_ACTIONS[key];
    if (!a) return [];
    const out = [];
    if (a.editor) out.push('editor');
    if (a.admin) out.push('admin');
    return out;
}

/** Что даёт сам доступ к разделу — одной строкой. */
export function openAction(key) {
    if (String(key).startsWith('settings:')) return 'Видит этот раздел настроек';
    const a = MODULE_ACTIONS[key];
    if (a && a.open) return a.open;
    return MODULE_PLAIN[key] || '';
}

/** Подпись действия для уровня, или '' если уровень для раздела ничего не значит. */
export function actionFor(key, level) {
    if (String(key).startsWith('settings:')) {
        if (level === 'editor') return 'Добавляет и изменяет строки справочника';
        if (level === 'admin')  return 'Удаляет строки справочника';
        return '';
    }
    const a = MODULE_ACTIONS[key];
    return (a && a[level]) || '';
}

/**
 * Уровень, который надо сохранить, по отмеченным действиям.
 * Порядок значим: «удаление» включает «изменение» — так их и читает
 * accessLevelFor() в permissions.js.
 */
export function levelFromActions({ editor, admin }) {
    if (admin) return 'admin';
    if (editor) return 'editor';
    return 'viewer';
}

/** Обратно: какие действия отмечены при сохранённом уровне. */
export function actionsFromLevel(level) {
    return { editor: level === 'editor' || level === 'admin', admin: level === 'admin' };
}
