// PATIENT_SEARCH_TOKENS_V1 — разбор строки поиска пациента.
//
// Регистратура набирает «Эрг Жах», а не «Эргашев Жахонгир»: пара букв из
// фамилии и пара из имени. Прежний поиск искал ВСЮ строку как непрерывную
// подстроку full_name, поэтому такой запрос не находил никого.
//
// Каждое слово становится отдельным условием: слово должно найтись где-то в
// карточке (И между словами), но может найтись в любом поле (ИЛИ между полями,
// собирается в data.js). Порядок слов при этом не важен — «Жах Эрг» находит то
// же самое, а именно так и получается, когда фамилию с именем путают местами.
//
// Чистый модуль: ни DOM, ни supabase, поэтому правила проверяются тестом.

// Верхняя граница на всякий случай: каждое слово — отдельный OR-блок в SQL, и
// вставленный в поиск абзац не должен превращаться в запрос на сотню условий.
export const MAX_TOKENS = 6;

// В ilike «%» и «_» — подстановочные знаки. Пациент с «100%» в имени
// маловероятен, но незаэкранированный «%» в запросе означает «найди всех», а
// это худший вид тихой ошибки: экран выглядит рабочим и показывает не то.
function escapeLike(s) {
    return s.replace(/[\\%_]/g, (ch) => '\\' + ch);
}

export function searchTokens(term) {
    const raw = String(term == null ? '' : term).trim();
    if (!raw) return [];
    const seen = new Set();
    const out = [];
    for (const word of raw.split(/[\s,]+/)) {
        if (!word) continue;
        const key = word.toLowerCase();
        if (seen.has(key)) continue;
        seen.add(key);
        out.push(escapeLike(word));
        if (out.length >= MAX_TOKENS) break;
    }
    return out;
}

// PATIENT_SEARCH_PHONE_V1 — телефон хранится в ДВУХ форматах.
//
// Старая выгрузка: «998915930555». Новые карточки: «+998 94 877 67 67». Поэтому
// поиск по цифрам «9487767» находил только первых, а вторых — никогда.
//
// Возвращает шаблон, терпимый к разделителям («%9%4%8%7%7%6%7%»), или null,
// если так искать нельзя. Порог в 7 цифр не выдуман, а измерен на настоящей
// базе (69 995 карточек с телефоном): для 7+ цифр такой шаблон находит единицы
// (7 цифр — 3 карточки, 9 цифр — 1), а для 4 цифр — 559 против 28 у точного,
// то есть превращается в мусор. Ниже порога ищем как есть.
const PHONE_LOOSE_MIN_DIGITS = 7;

export function loosePhonePattern(token) {
    const digits = String(token == null ? '' : token).replace(/[^0-9]/g, '');
    if (digits.length < PHONE_LOOSE_MIN_DIGITS) return null;
    if (digits.length !== String(token).length) return null;   // только чисто цифровой запрос
    return '%' + digits.split('').join('%') + '%';
}
