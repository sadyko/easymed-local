// PASTEL_IDENTITY_V1 (2026-09-05) — ОДИН словарь оттенков на три доски.
//
// Владелец: «make cards of the kanban and the calendar bookings and the queue
// colorful. using pastel colors». Три экрана красятся по одному правилу, и
// правило живёт здесь, а не трижды в трёх видах: иначе «жёлтый» на календаре и
// «жёлтый» в очереди разъедутся при первой же правке.
//
// ЧТО ЦВЕТ ЗДЕСЬ ЗНАЧИТ. Пастель — это ЛИЧНОСТЬ: чей приём, к какой двери
// талон, какая ступень воронки. Не тяжесть. Тяжесть в этом продукте уже занята
// четырьмя семантическими парами (--ok-* / --warn-* / --crit-* / --info-*), и
// они остаются на своих местах: отменённый приём, неоплаченный талон, спорная
// запись помечаются ими и ТОЛЬКО ими. Правило, из которого всё следует:
//
//     если признак можно потерять — он не имеет права быть только заливкой.
//
// Поэтому отмена на карточке приёма — штриховка и зачёркнутая фамилия, а не
// «другой пастель»: заливка там уже занята врачом, и перекрасить её значило бы
// сказать «это другой врач».
//
// Сами числа (заливка / текст / край) лежат в admin.css как токены
// --pastel-<оттенок>-bg|-fg|-line и проверяются программно, всей шкалой сразу
// (__tests__/contrast-badge-hatch.test.mjs). Здесь — только выбор оттенка.

/**
 * Порядок ЗНАЧИМ: доски, которые красятся по позиции (воронка CRM), берут
 * оттенки подряд, и соседние колонки поэтому никогда не совпадают.
 * Восемь — не круглое число ради красоты: столько разных заливок человек
 * различает на одном экране, не сверяясь с легендой.
 */
export const PASTEL_HUES = ['sky', 'indigo', 'violet', 'lilac', 'rose', 'sand', 'amber', 'mint'];

/**
 * Класс-носитель оттенка. Классы описаны в admin.css и выставляют --p-bg /
 * --p-fg / --p-line; правила экранов читают ТОЛЬКО эти три переменные, поэтому
 * добавить девятый оттенок можно, не трогая ни один экран.
 */
export function pastelClass(hue) {
    return PASTEL_HUES.includes(hue) ? 'pastel-' + hue : '';
}

/**
 * Устойчивый оттенок из произвольного ключа: тот же врач — тот же цвет и
 * сегодня, и завтра, и на другой машине. Хэш тот же, что у avColor() в ui.js
 * (h * 31 + код символа, беззнаковый) — намеренно: два разных хэша на одних и
 * тех же данных дали бы врачу один цвет на аватарке и другой на карточке.
 *
 * Пустой ключ оттенка НЕ получает: «врач не назначен» — это отсутствие
 * личности, и карточка обязана остаться белой, а не притвориться чьей-то.
 */
export function hueOf(seed) {
    const s = String(seed == null ? '' : seed);
    if (!s) return '';
    let h = 0;
    for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) >>> 0;
    return PASTEL_HUES[h % PASTEL_HUES.length];
}

/** Тот же выбор, сразу классом: `pastelFor(doctorId)` → 'pastel-mint' или ''. */
export function pastelFor(seed) {
    return pastelClass(hueOf(seed));
}

/**
 * Оттенок по ПОЗИЦИИ в ряду, а не по имени. Для воронки CRM: ступени идут
 * по порядку, и красить их хэшем значило бы разрешить двум соседним колонкам
 * совпасть — ровно там, где различать нужнее всего. Позиция же даёт ряду
 * читаемое движение цвета слева направо.
 */
export function pastelAt(index) {
    // Именно Number.isInteger, а не Number(index): Number(null) равен нулю, и
    // «позиция не пришла» молча превратилась бы в первую ступень воронки —
    // цвет без основания, самый неприятный вид ошибки в раскраске.
    if (!Number.isInteger(index) || index < 0) return '';
    return 'pastel-' + PASTEL_HUES[index % PASTEL_HUES.length];
}

/**
 * ЗАКРЫТЫЕ наборы красятся таблицей, а не хэшем: у очереди ровно шесть видов
 * назначения, они не меняются, и «лаборатория всегда песочная» — это то, что
 * сотрудник выучивает за смену. Хэш дал бы то же постоянство, но при
 * переименовании ключа цвет бы прыгнул.
 */
export const QUEUE_KIND_HUE = {
    doctor:    'sky',
    room:      'mint',
    procedure: 'violet',
    lab:       'amber',
    imaging:   'indigo',
    other:     'sand',
};

/** Класс оттенка для вида назначения в очереди; неизвестный вид → «прочее». */
export function pastelForQueueKind(kind) {
    return pastelClass(QUEUE_KIND_HUE[kind] || QUEUE_KIND_HUE.other);
}
