// Запрет «один пациент на врача на слот» жил в RPC calendar_book, а писать
// visits.visit_date / doctor_id / status умел ещё и обычный /api/db — и им
// пользовались четыре шипнутых экрана: журнал визитов, кабинет врача,
// повторный визит и окно визита. В базе владельца нашлись ДВА живых
// scheduled-визита одного врача на 10:00, заведённые именно так.
//
// Отдельно ходил двухкликовый обход: записать визит отменённым поверх занятого
// времени, а потом переключить статус в «записан». Реестр (schema-registry.js)
// эти колонки больше не отдаёт вовсе, а весь экранный код ходит сюда.
//
// ─── ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ФУНКЦИЯ В КАЖДОМ ЭКРАНЕ ───────────────────
//
// Ровно по той же причине, по которой движок слотов один и живёт на сервере
// (slot-engine.js): пять копий одного правила — это пять разных ответов на
// один вопрос. Тест ловит грепом и возврат прямой записи в visits, и вторую
// копию расчёта слотов.
//
// Сами проверка и отказ здесь НЕ ЖИВУТ и жить не могут: их делает сервер
// (calendar_book), потому что проверка, которую можно обойти, выключив
// JavaScript, запретом не является. Этот файл — только вызов и слова отказа.

import { supabase } from '../../supabase.js';
// Клиент записи общий с мастерами: диалог экстренной причины, перевод отказа
// сервера по коду и сброс кэша слотов уже реализованы там, и заводить им
// вторую реализацию — то же самое, из-за чего появился slot-engine.js.
import { bookErrorText, calendarBookOrAsk, forgetSlots } from './service-picker-modal.js?v=aug17e';

export { bookErrorText, forgetSlots };

/**
 * Статусы, которые ЗАНИМАЮТ время врача — те же три, что у сервера
 * (slot-engine.js BUSY_STATUSES). Переход В них — это запись на слот; переход
 * ИЗ них (отмена, неявка) слот освобождает и проверки не требует.
 */
export const SLOT_HOLDING_STATUSES = ['scheduled', 'confirmed', 'arrived'];
export const holdsSlot = (status) => SLOT_HOLDING_STATUSES.includes(String(status || ''));

/**
 * ЗАПИСАТЬ / ПЕРЕНЕСТИ / РАСТЯНУТЬ. Один вход на три действия, потому что
 * проверка у всех трёх одна.
 *
 * args — как у calendar_book: { patient_id | visit_id, doctor_id?, room_id?,
 * service_id?, branch_id?, start, duration_minutes?, status?, notes? }.
 *
 * Возвращает { visit, created, emergency, cross_branch? } либо null — «человек
 * отказался от экстренной записи»; при null не создано и не изменено НИЧЕГО.
 * Бросает Error со словами сервера на прочих отказах.
 */
export async function bookVisit(args, opts = {}) {
    return calendarBookOrAsk(args, opts);
}

/**
 * СМЕНИТЬ СТАТУС. Тоже calendar_book — потому что смена статуса это тоже
 * расписание: перевод отменённой записи обратно в «записан» перепродаёт слот,
 * который она освободила, и сервер обязан это увидеть. Переход наружу
 * (отменён, не пришёл) сервер пропускает без проверки сам.
 *
 * visit — строка визита; нужны id и visit_date (время не меняется, оно
 * посылается как есть, чтобы серверу было что проверять).
 * Бросает Error со словами сервера; у ошибки остаётся .code (slot_taken).
 */
export async function setVisitStatus(visit, status) {
    const { data, error } = await supabase.rpc('calendar_book', {
        visit_id: visit.id,
        start: visit.visit_date,
        status,
    });
    if (error) {
        const e = new Error(bookErrorText(error));
        e.code = error.code;
        throw e;
    }
    forgetSlots();
    return (data && data.visit) || null;
}
