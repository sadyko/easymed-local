// Владелец (23.09): «выдача и списание просроченного предупреждают». Слова
// пишет СЕРВЕР (rpc/expiry.js expiryWarning): дверей, через которые товар
// уходит со склада, много — выдача со склада, карточка отдела, амбулаторная
// вкладка медсестры, койка, — и четыре собственных формулировки одной и той же
// беды читались бы как четыре разные беды.
//
// ЗДЕСЬ ТОЛЬКО ПОКАЗ, И ПОКАЗ ПОСЛЕДНИМ. Предупреждение не отменяет операцию
// (владелец сказал предупреждать, а не запрещать), поэтому экран сперва
// говорит «выдано», а предупреждение приходит СЛЕДОМ и остаётся на виду:
// плашка в программе одна (ui.js toast — единственный элемент #toast), и
// последняя вытесняет предыдущую. Порядок выбран так нарочно: спрятать беду
// внутрь зелёной плашки «готово» — верный способ, чтобы её не прочли.
//
// ВСЕ ПРЕДУПРЕЖДЕНИЯ ОДНОЙ ПЛАШКОЙ по той же причине: два просроченных товара
// в одной выдаче, показанные двумя плашками подряд, превратились бы в одну —
// вторую.
import { toast } from '../ui.js';

/** Предупреждения из ответа сервера — всегда массив, чем бы ответ ни оказался. */
export function stockWarnings(res) {
    const list = res && Array.isArray(res.warnings) ? res.warnings : [];
    return list.filter((w) => w && typeof w.message === 'string' && w.message);
}

/** Слова всех предупреждений одной строкой (пусто — предупреждать не о чем). */
export function stockWarningText(res) {
    return stockWarnings(res).map((w) => w.message).join(' ');
}

/** Показать их человеку. Возвращает число показанных — ради вызывающих тестов. */
export function toastStockWarnings(res) {
    const list = stockWarnings(res);
    if (list.length) toast(stockWarningText(res), 'warn');
    return list.length;
}
