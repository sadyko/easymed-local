// BRANCH_SYNC_HOURLY_V1 — маленькая кнопка «Синхронизация» в окнах, где
// работают люди, а не администраторы.
//
// Решение владельца 2026-09-02, дословно: «add small button to the registrator,
// and the laboratory window saying (syncronization) so clinic info get from the
// other branches and data is collected».
//
// ЗАЧЕМ ОНА, если есть часы. Часы (server/services/branch-sync/schedule-pull.js)
// ходят раз в час, и этого достаточно для отчётов владельца. Но у стойки бывает
// минута, когда ждать час нельзя: пациент стоит здесь, его карту завели в
// соседнем филиале десять минут назад. Кнопка — про эту минуту, а не про
// регулярность.
//
// ПОЧЕМУ ЕЁ ВИДНО НЕ ВСЕМ. Подавляющее большинство клиник — одиночные, филиалов
// у них нет вовсе. Кнопка «Синхронизация», которой физически не с кем
// синхронизироваться, — это не безобидный лишний элемент, а обещание, которое
// экран не может сдержать: человек нажмёт, ничего не произойдёт, и он решит,
// что система сломана. Поэтому кнопка появляется ТОЛЬКО на подключённом
// филиале, и до ответа сервера её нет вовсе (hidden), а не «есть, но серая».
//
// ПОЧЕМУ ЭТО НЕ ТРЕБУЕТ ПРАВ. Ровно то же действие каждый час выполняют часы,
// без человека. Кнопка не даёт новых возможностей — она лишь избавляет от
// ожидания; см. requireUser в server/services/rpc/branch-sync.js.

import { h, Icon, toast } from '../ui.js';
import { tr } from '../i18n.js';
import { supabase } from '../../supabase.js';

/**
 * Кнопка «Синхронизация» для окна регистратуры и лаборатории.
 *
 * Возвращает узел СРАЗУ и скрытым; роль установки выясняется потом, и кнопка
 * показывается сама, если выяснилось, что это филиал. Так вызывающий экран не
 * ждёт сети ради одной кнопки в шапке.
 *
 * @param {{ onDone?: () => void }} [opts] onDone — перерисовать список после
 *        успешной синхронизации: данные соседнего филиала уже в базе, но экран
 *        о них ещё не знает.
 * @returns {HTMLButtonElement}
 */
export function branchSyncButton({ onDone } = {}) {
    const btn = h('button', {
        class: 'btn btn-outline btn-sm',
        type: 'button',
        title: 'Забрать данные других филиалов',
    }, Icon('Refresh', { size: 14 }), ' ', 'Синхронизация');
    btn.hidden = true;

    revealIfBranch(btn);

    btn.addEventListener('click', async () => {
        btn.disabled = true;
        try {
            const { data, error } = await supabase.rpc('branch_sync_now');
            if (error) throw new Error(error.message || tr('Не удалось синхронизировать.'));

            if (data && data.ok) {
                // changed === 0 — это УСПЕХ, а не пустое действие: «у соседей
                // ничего нового» и «связи нет» для человека за стойкой две
                // совершенно разные новости, и путать их нельзя.
                toast(data.changed ? tr('Данные обновлены') : tr('Новых данных нет'), 'ok');
                if (data.changed && typeof onDone === 'function') onDone();
            } else {
                // Сообщение сервера уже конкретное и по-русски (reasonText в
                // server/services/rpc/branch-sync.js разбирает каждую причину),
                // поэтому показываем его, а не своё общее «ошибка».
                toast((data && data.message) || tr('Не удалось синхронизировать.'), 'err');
            }
        } catch (e) {
            toast(e.message || tr('Не удалось синхронизировать.'), 'err');
        } finally {
            btn.disabled = false;
        }
    });

    return btn;
}

/**
 * Показать кнопку, если эта установка — подключённый филиал.
 *
 * Молча ничего не делает при любой неудаче: не смогли узнать роль — кнопки
 * нет. Одиночной клинике лишняя кнопка вреднее, чем филиалу её отсутствие до
 * следующего открытия экрана.
 */
async function revealIfBranch(btn) {
    try {
        if (rolePromise === null) rolePromise = askRole();
        if (await rolePromise) btn.hidden = false;
    } catch (e) {
        /* роль не выяснили — кнопки нет */
    }
}

// Роль спрашивается ОДИН раз за сессию, а не при каждом открытии экрана.
// Кнопка живёт на двух экранах, между которыми ходят весь день, и установка
// не превращается из филиала в одиночную клинику между двумя кликами по меню.
// Лишний запрос на каждом открытии был бы не только тратой: он попадает в
// список вызовов, которым экраны проверяются, и делает их хрупкими.
let rolePromise = null;

async function askRole() {
    const { data, error } = await supabase.rpc('branch_sync_status');
    if (error) return false;
    return !!(data && data.role === 'secondary');
}
