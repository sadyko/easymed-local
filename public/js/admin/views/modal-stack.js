//
// Окна продукта лежат в document.body соседями, и кто кого накрывает, решает
// ТОЛЬКО z-index. Поэтому каждому окну, слушающему Escape на document, нужен
// один и тот же ответ: нажатие принадлежит ВЕРХНЕМУ окну, а не всем сразу.
//
// Ответ этот был написан дважды и по-разному: каталог услуг читал только
// встроенный style.zIndex, окно заведения пациента — встроенный, а при его
// отсутствии вычисленный. Две копии одного правила расходятся молча: окно,
// чей этаж задан классом, для одного из них стоит на нулевом этаже, а для
// другого — на своём. Наружу это выходит как «Esc закрыл не то окно».
//
// ПОРЯДОК ПРОДУКТА (числа живут у самих окон, здесь — только правило):
// страничные окна 100 · быстрая регистрация 120 · каталог услуг 130 ·
// привязка пациента в каталоге 150 · окно «Новый пациент» 155 · страж
// дубликатов и отказ 160 · шаблоны сметы и веб-камера 170 · выбор пакета 180 ·
// экстренная запись 190.
//
// Модуль намеренно НИЧЕГО не импортирует: его зовут экраны, и кольцо импортов
// (NO_IMPORT_CYCLES_V1) здесь невозможно по построению.

/**
 * Этаж подложки .modal, которому её никто не задавал.
 *
 * Это не «ноль», а 100: столько стоит в правиле .modal (admin.css). Окно,
 * открытое без встроенного z-index, стоит именно там — считать его нулевым
 * значило бы считать его ниже всех, а оно ровно на общем этаже окон.
 */
export const BASE_MODAL_Z = 100;

/**
 * Этаж окна: встроенный стиль, затем вычисленный, затем общий этаж окон.
 *
 * Встроенный — то, чем этаж задают все окна продукта
 * (h('div', { class: 'modal', style: { zIndex: '150' } })). Вычисленный стиль
 * спрашиваем только там, где он есть: в поддельном DOM проверок его нет, и без
 * этой оговорки проверка падала бы на ровном месте.
 *
 * @param {object} el подложка .modal
 * @returns {number} этаж
 */
export function modalZ(el) {
    if (!el) return 0;
    const inline = Number((el.style && el.style.zIndex) || 0);
    if (inline) return inline;
    try {
        if (typeof window !== 'undefined' && typeof window.getComputedStyle === 'function') {
            const z = Number(window.getComputedStyle(el).zIndex);
            if (z) return z;
        }
    } catch (e) { /* вычисленного стиля нет — считаем по общему этажу окон */ }
    return BASE_MODAL_Z;
}

/**
 * Самый верхний этаж среди ЧУЖИХ подложек .modal в документе.
 *
 * Ищем не по имени: у стража дубликатов data-dialog стоит на карточке, а у
 * каталога услуг его нет вовсе. Общее у всех окон одно — своя подложка .modal
 * в document.body. Перечень имён разошёлся бы с жизнью при первом же новом
 * диалоге; «есть чужая подложка» — нет.
 *
 * @param {object} [exclude] чью подложку не считать (свою)
 * @returns {number} 0 — чужих окон нет вовсе
 */
export function topmostModalZ(exclude) {
    const kids = (typeof document !== 'undefined' && document.body && document.body.children) || [];
    let top = 0;
    for (const el of kids) {
        if (!el || el === exclude) continue;
        if (!String(el.className || '').split(/\s+/).includes('modal')) continue;
        const z = modalZ(el);
        if (z > top) top = z;
    }
    return top;
}

/**
 * Стоит ли ПОВЕРХ этого окна чужое.
 *
 * Правило одно на все этажи и не зависит от имён окон: есть в документе
 * подложка .modal выше моей — Escape (и Enter) не мой. Соседняя подложка — это
 * ещё и ТЕ, КТО ОКНО ПОЗВАЛ: они стоят ПОД ним и заслонить его не могут.
 * Считая их дочерними, окно глохнет ровно в самом частом случае, и на экране
 * это читается как «окно зависло».
 *
 * @param {object} own моя подложка (.modal со своим z-index)
 * @returns {boolean}
 */
export function coveredByHigherModal(own) {
    if (!own) return false;
    return topmostModalZ(own) > modalZ(own);
}
