// record-origin.js — BRANCH_ORIGIN_V1: откуда запись.
//
// Одна строка данных, один вопрос: эта запись заведена ЗДЕСЬ или приехала от
// соседнего филиала? Ответ хранится в колонке `sync_origin` (миграция 083):
// NULL — своё, буква узла — приехало оттуда. Ставит её приём порции
// (server/services/branch-sync/records.js) и только при ВСТАВКЕ новой строки:
// происхождение записи не меняется от того, что сосед потом её поправил.
//
// Почему не буква MRN. MRN говорит, где пациент ЗАВЕДЁН, а не где произошла
// работа: пациент из «C» приходит в «B», и его визит — работа B. Фильтровать
// очереди по MRN значило бы прятать от лаборатории её собственные анализы.
// И наоборот: `visits.branch_id` до Фазы 1 ненадёжен (мастер проставляет
// первый активный филиал), поэтому и он не источник правды.
//
// Модуль ЧИСТЫЙ: ни DOM, ни сети — его читают и списки, и тесты.

/**
 * Буква филиала, из которого приехала строка, или null для своей.
 * @param {object|null|undefined} row строка как её вернул /api/db
 * @returns {string|null}
 */
export function originTag(row) {
  if (!row || typeof row !== 'object') return null;
  const v = row.sync_origin;
  if (typeof v !== 'string') return null;   // null, undefined, число — не буква
  const letter = v.trim();
  return letter === '' ? null : letter;
}

/**
 * Строка заведена в ЭТОМ здании? На этом стоят рабочие списки — лабораторная
 * очередь и кабинет врача (решение владельца 2026-09-02: «очередь и кабинет
 * врача — своего здания»). Отсутствующая колонка считается своей: экран, не
 * запросивший sync_origin, обязан показать работу, а не пустой список.
 * @param {object|null|undefined} row
 * @returns {boolean}
 */
export function isOwnBuilding(row) {
  return originTag(row) === null;
}
