//
// Узбекский интерфейс — латиница. Инспекция v3.12.0 нашла 21 узбекскую строку
// с кириллическими буквами: где-то одна буква-двойник посреди слова
// («rejalаshtirish», «Smenа», «Probirkа» — кириллическая «а» выглядит так же,
// но ломает поиск и сортировку), где-то целые русские названия экранов
// («+ Новый пациент», «Склад → Выдать»). И 16 английских строк цитировали
// русские названия экранов («Панели», «Необработанные») — англоязычный
// сотрудник искал кнопку, которой на его экране нет.
//
// Исключение одно и сознательное: слово подтверждения «УДАЛИТЬ» — его человек
// обязан набрать буква в букву, поэтому оно одно на все языки.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { STRINGS } from '../i18n-strings.js';

const CYR = /[Ѐ-ӿ]/;
const strip = (s) => String(s).replace(/УДАЛИТЬ/g, '');

test('узбекские строки не содержат кириллицы (кроме слова подтверждения «УДАЛИТЬ»)', () => {
  const bad = Object.entries(STRINGS).filter(([, v]) => v && v.uz && CYR.test(strip(v.uz))).map(([k, v]) => k + ' => ' + v.uz);
  assert.deepEqual(bad, [], 'кириллица в узбекском переводе:\n' + bad.join('\n'));
});

test('английские строки не цитируют русские названия экранов (кроме «УДАЛИТЬ»)', () => {
  const bad = Object.entries(STRINGS).filter(([, v]) => v && v.en && CYR.test(strip(v.en))).map(([k, v]) => k + ' => ' + v.en);
  assert.deepEqual(bad, [], 'кириллица в английском переводе:\n' + bad.join('\n'));
});
