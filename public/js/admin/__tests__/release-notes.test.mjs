// RELEASE_NOTES_FRESH_V1 (2026-09-05) — RELEASE_NOTES.md описывает ЭТОТ
// выпуск, а не предыдущий.
//
// Файл читает не разработчик. По docs/RELEASING.md он уезжает клинике и
// показывается ей на экране подтверждения обновления как «что нового». Пока
// его никто не проверял, он спокойно отставал на целый выпуск: после месяца
// работы над оболочкой, календарём записи и разделом «Пациенты» в нём всё ещё
// был текст про сеть филиалов, отчёты по зданиям и шифрование справочника —
// то есть клиника читала описание чужого обновления и не находила в программе
// ничего из обещанного.
//
// Тест не умеет проверить, что текст ПРАВДИВ, — это работа человека. Он
// проверяет ровно то, что можно проверить машиной и что как раз и сломалось:
// файл говорит про содержимое этого выпуска и не остался текстом прошлого.
// Оба списка ниже придётся править при следующем выпуске — это и есть смысл:
// «написать заметки» становится шагом, который нельзя молча пропустить.

import { test } from 'node:test';
import assert from 'node:assert';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(HERE, '..', '..', '..', '..');
const NOTES = fs.readFileSync(path.join(REPO_ROOT, 'RELEASE_NOTES.md'), 'utf8');

// То, что этот выпуск действительно принёс клинике. Формулировки — из самих
// заметок: тест обязан падать и при переписывании фразы, иначе он стережёт
// собственную выдумку, а не файл.
const THIS_RELEASE = [
    [/Версия 2\.0/, 'номер выпуска назван'],
    [/титульный лист по бланку 003/, 'титульный лист истории болезни'],
    [/Результаты с анализаторов теперь приходят сами/, 'приём результатов с анализаторов'],
    [/Восемь плиток на сегодня/, 'новая сводка клиники'],
    [/Помещения клиники строятся на плане/, 'план клиники'],
    [/четыре вкладки под шапкой/, 'вкладки лаборатории'],
];

// Фразы прошлых выпусков. Встретились в файле — значит заметки не переписали,
// и клиника прочитает описание чужого обновления.
const PREVIOUS_RELEASE = [
    // 0.8.0 — сеть филиалов
    /Отчёты главной клиники теперь считают все здания/,
    /Справочник по прямому каналу между зданиями теперь шифруется/,
    /Номера счетов и карт пациентов из другого здания больше не теряются/,
    // 0.9.x — оболочка, календарь записи, окно заведения пациента
    /Вкладок наверху больше нет/,
    /«Список», «Очередь» и «Записи»/,
    /Запись на приём наконец работает/,
    // 1.0.0 — отказы базы, дата рождения, бейдж Telegram
    /Кэшбэк начисляется/,
    /Дата рождения набирается цифрами/,
    /История болезни снова показывает пациента/,
    // 1.0.1 — роли и надстроечные роли расписаны в заметках
    /Главный врач и старшая медсестра выбираются только/,
    /Кухонный лист — не роль, а экран/,
    // 1.0.2 — отделы у кабинетов и палат
    /Кабинеты и палаты теперь принадлежат отделу/,
    /лишнее английское слово/,
    // 1.1.x — белый грунт, пять разделов услуги, хирургия на койку
    /поле страницы теперь белое/,
    /Разделов услуги стало пять/,
    /только лежащему пациенту/,
    // 1.1.2 — удаление услуги с особым номером, единицы и нормы ушли в панели
    /Услугу снова можно удалить или отключить/,
    /предложит отключить её вместо удаления/,
    /убраны единицы и нормы/,
];

test('заметки к выпуску говорят про ЭТОТ выпуск', () => {
    const missing = THIS_RELEASE.filter(([re]) => !re.test(NOTES)).map(([, what]) => what);
    assert.deepEqual(missing, [], 'в RELEASE_NOTES.md не сказано про:\n  ' + missing.join('\n  '));
});

test('заметки к выпуску не остались текстом предыдущего', () => {
    const stale = PREVIOUS_RELEASE.filter((re) => re.test(NOTES)).map(String);
    assert.deepEqual(stale, [], 'это фразы выпуска 0.8.0 — файл не переписан:\n  ' + stale.join('\n  '));
});

test('честность: оговорки про то, что работает не до конца, на месте', () => {
    // Обе проверены в коде перед тем, как попасть в заметки, и обе останутся
    // правдой, пока их не исправят:
    //   перетаскивание в календаре висит на mousedown (views/room-calendar.js)
    //     — ни касания, ни клавиатуры;
    //   «Очередь» открывается и пунктом меню, и вкладкой внутри «Пациентов»
    //     (views/queue.js, views/patients-hub.js).
    // Если поправят — уйдёт и оговорка, и эта проверка. Пока не поправили,
    // молчать о них в тексте, который читает клиника, нельзя.
    assert.match(NOTES, /нужна мышь/, 'не сказано, что перенос записи требует мыши');
    assert.match(NOTES, /Отдельный пункт «Очередь» остался только у тех/,
        'не сказано, что «Очередь» открывается из двух мест');

    const view = fs.readFileSync(path.join(REPO_ROOT, 'public', 'js', 'admin', 'views', 'room-calendar.js'), 'utf8');
    assert.match(view, /mousedown/, 'перетаскивание больше не на mousedown — перечитайте оговорку в заметках');
});

test('заметки написаны для заведующей клиникой, а не для разработчика', () => {
    // Правило docs/RELEASING.md: «Never write something like "fixed null
    // pointer in doc-render"». Проверяем ровно тот словарь, который туда
    // протекает сам собой, когда заметки пишутся по журналу коммитов.
    const JARGON = /\b(commit|refactor|RPC|API|SQL|миграци|эндпоинт|бэкенд|фронтенд|деплой|рефактор|null|undefined|CSS|DOM)\b/i;
    const hit = NOTES.match(JARGON);
    assert.equal(hit, null, `техническое слово «${hit && hit[0]}» в тексте для клиники`);
    // И без эмодзи — общее домашнее правило интерфейса.
    assert.equal(/\p{Extended_Pictographic}/u.test(NOTES), false);
    // Абзацы, а не список команд: файл целиком показывается на экране
    // обновления как сплошной текст.
    assert.equal(/^\s*[-*]\s/m.test(NOTES), false, 'маркированный список — на экране обновления он не оформится');
});
