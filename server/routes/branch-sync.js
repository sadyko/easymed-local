import { Router } from 'express';
import {
  exportCatalogue, withoutSealedTables, ACCEPT_HEADER, SEALED_FORM,
} from '../services/branch-sync/catalogue.js';
import { readPairing, verifySignature, skewMs, MAX_SKEW_MS, CATALOGUE_PATH } from '../services/branch-sync/pairing.js';
// STAFF_SYNC_SEAL_V1 — та же криптография, что у Маршрута Б, и НАРОЧНО та же:
// свой второй шифр на том же ключе — это второй способ ошибиться.
import { sealPayload } from '../services/branch-sync/relay-crypto.js';

// BRANCH_SYNC_V1 — сторона ГЛАВНОГО филиала: единственная точка, из которой
// другой филиал забирает справочник.
//
// Смонтирован рядом с телефонными вебхуками и по той же причине: запрос
// приходит от другой УСТАНОВКИ, а не из браузера сотрудника, и cookie сессии у
// него нет — requireAuth ответил бы 401 на каждый честный запрос. Поэтому
// маршрут гейтит себя сам: подпись на общем секрете пары, сверенная за
// постоянное время, плюс окно по времени.
//
// ЗАБИРАЕТ ПРИЁМНИК, а не рассылает источник. Так у главного филиала нет ни
// одного открытого наружу входа, который бы он инициировал, второй филиал сам
// решает, когда синхронизироваться (в клинике это «не в приёмные часы»), и —
// главное — направление данных совпадает с направлением доверия: получатель
// приносит изменения к себе и сам же снимает перед этим резервную копию.
//
// Ответы:
//   404 — эта установка не главный филиал. Именно 404, а не 403: наличие или
//         отсутствие роли не должно быть видно тому, кто просто щупает порт
//         (то же правило, что у telephony/webhooks.js).
//   401 — подпись не сошлась. Без подробностей.
//   401 + reason 'clock_skew' — подпись ВЕРНА, но часы разъехались. Причина
//         сообщается уже проверенной стороне, и это единственная ошибка,
//         которую невозможно диагностировать снаружи: экран филиала должен
//         сказать «сверьте часы», а не «ключ не подходит».
//
// -------------------------------------------------------------------------
// STAFF_SYNC_SEAL_V1 (ревью Фазы 3, C1) — ТЕЛО ОТВЕТА ЗАПЕЧАТАНО.
//
// ЧТО БЫЛО НЕ ТАК. С 9a1c75b в справочник входят учётные записи сотрудников —
// с bcrypt-хешами паролей, ФИО, телефонами, почтой и номерами лицензий. Этот
// маршрут отдавал их обычным JSON, а адрес главного филиала владелец вводит в
// виде «10.4.1.10:8000» (см. normalizeUrl в pairing.js: схема по умолчанию —
// http://). То есть в НОРМАЛЬНОЙ установке весь корпус хешей клиники ехал по
// локальной сети открытым текстом каждый час. Шапка миграции 086 обещает
// сквозное шифрование — до этой правки это было верно только про Маршрут Б.
//
// ЧЕМ ЗАПЕЧАТАНО. sealPayload/openPayload (relay-crypto.js) — AES-256-GCM +
// gzip на КЛЮЧЕ ГРУППЫ, который обе стороны уже держат на диске и который
// никогда не проходит через сервер поставщика. Новой криптографии здесь нет
// ни строки: она одна на оба маршрута, и разойтись им негде.
//
// КАК ДОГОВАРИВАЮТСЯ СТОРОНЫ. Обновляют парк не одномоментно — ровно та же
// забота, что у EMB1/EMB2 в pairing.js, и она обязана работать в обе стороны:
//   * филиал 0.8 -> главный 0.7.x: старый главный про заголовок не знает и
//     отвечает как раньше `{ok, group_id, catalogue}`. Филиал принимает и эту
//     форму — иначе обновившийся филиал перестал бы получать прайс;
//   * филиал 0.7.x -> главный 0.8: старый филиал заголовка не шлёт, и тогда
//     тело уходит ОТКРЫТЫМ, но БЕЗ users и role_permissions
//     (withoutSealedTables). Это и есть вторая половина совместимости:
//     «не понял — не получил», а не «не понял — получил хеши открытым текстом».
// Заголовок в подпись не входит, и это осознанно: снявший его посредник
// добьётся ровно одного — филиал не получит сотрудников. Понижения до
// открытых хешей такой ход не даёт, потому что открытого тела с ними больше
// не существует.
//
// ЕСЛИ ЗАПЕЧАТАТЬ НЕЧЕМ (у пары нет ключа группы — так выглядят связывания,
// сделанные ключом EMB1 до появления Маршрута Б), сотрудники не уезжают
// ВООБЩЕ, а в журнал пишется почему. Отката на открытый текст нет ни одного.
export function branchSyncRoutes(db, dataDir, { now = () => Date.now() } = {}) {
  const r = Router();

  r.get('/catalogue', (req, res) => {
    const pairing = readPairing(dataDir);
    if (!pairing || pairing.role !== 'main') {
      return res.status(404).json({ error: { code: 'not_found', message: 'Unknown API endpoint.' } });
    }

    const group = String(req.get('x-em-branch-group') || '');
    const ts = String(req.get('x-em-branch-ts') || '');
    const sig = String(req.get('x-em-branch-sig') || '');

    // Идентификатор группы проверяется ВНУТРИ подписи (он входит в подписываемую
    // строку), а не отдельным сравнением: чужая группа не сможет предъявить
    // подпись на нашем секрете, поэтому отдельная проверка ничего не добавляет,
    // зато отдельный ответ «такой группы нет» подтверждал бы гадающему, какая
    // группа существует.
    const ok = verifySignature({
      secret: pairing.secret,
      groupId: group,
      ts,
      requestPath: CATALOGUE_PATH,
      sig,
    });
    if (!ok) return res.status(401).json({ error: { code: 'unauthorized', message: 'Not authorised.' } });

    if (skewMs(ts, now()) > MAX_SKEW_MS) {
      return res.status(401).json({ error: { code: 'clock_skew', message: 'Request timestamp is out of range.' } });
    }

    // no-store, а не no-cache: между филиалами может стоять прокси, и
    // справочник с ценами не должен лежать в чужом кэше ни секунды.
    res.set('Cache-Control', 'no-store');

    // Ровно то тело, что отдавалось всегда. Оно же — то, что запечатывается:
    // приёмник обязан разбирать одно и то же, каким бы путём это ни приехало
    // (то же правило, что у relayBody в relay.js).
    const body = { ok: true, group_id: pairing.group_id, catalogue: exportCatalogue(db) };

    if (acceptsSealed(req)) {
      const sealed = sealPayload(pairing.group_key, body);
      if (sealed) {
        // v — не украшение: по нему приёмник отличает две формы, не гадая по
        // наличию поля. Идентификатор группы наружу не выносится: он лежит
        // ВНУТРИ запечатанного тела, где его нельзя ни прочитать, ни подменить.
        return res.json({ ok: true, v: 2, sealed: sealed.toString('base64') });
      }
      // Ключа группы нет. Филиал просил запечатанное — значит, он новый и
      // сотрудников ждёт; но отдать их открытым текстом нельзя ни при каких
      // обстоятельствах, поэтому он получит справочник без них и владелец
      // получит строку в журнале, объясняющую, что чинить.
      console.warn('[branch-sync] staff withheld: this pairing has no group key '
        + '(a pre-relay EMB1 connection key). Re-issue the connection key in the main clinic.');
    }
    return res.json({ ...body, catalogue: withoutSealedTables(body.catalogue) });
  });

  return r;
}

// STAFF_SYNC_SEAL_V1 — умеет ли спрашивающий распечатать ответ.
//
// Список через запятую, а не голое равенство: заголовок читается как перечень
// понимаемых форм, и завтрашняя третья форма добавится в него, не сломав эту
// проверку. Регистр и пробелы приводятся, потому что заголовок пишет другая
// установка, а не браузер.
function acceptsSealed(req) {
  return String(req.get(ACCEPT_HEADER) || '')
    .toLowerCase()
    .split(',')
    .map((s) => s.trim())
    .includes(SEALED_FORM);
}
