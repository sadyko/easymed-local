-- 109_service_types_five.sql
-- SERVICE_TYPES_FIVE_V1 — пять разделов услуги вместо шести.
--
-- Владелец: «we need to make 5 types of the services type… the surgery is
-- bundled so it goes with the hospitalization».
--
-- ═══ ЭТА МИГРАЦИЯ НАМЕРЕННО НЕ ТРОГАЕТ CHECK ═══
--
-- Две первые версии пытались завести отдельное значение 'surgery', а для этого
-- в SQLite нужно ПЕРЕСОБРАТЬ таблицу. Обе уронили запуск программы у клиники
-- с настоящими данными:
--
--     SqliteError: FOREIGN KEY constraint failed
--
-- connection.js включает foreign_keys = ON. DROP TABLE при включённых ключах
-- делает неявное удаление всех строк и падает на первой же строке визита,
-- ссылающейся на услугу. Обходы не помогли: PRAGMA foreign_keys внутри
-- транзакции не делает ничего (migrate.js гоняет файл в транзакции),
-- defer_foreign_keys откладывает проверку до COMMIT и падает там,
-- legacy_alter_table внутри транзакции тоже не срабатывает.
--
-- На пустой базе ничего этого не видно — ссылаться не на что. Именно поэтому
-- проверки прошли, а клиника встала.
--
-- ГЛАВНОЕ: отдельное значение в базе для этой задачи НЕ НУЖНО. Владельцу нужны
-- пять разделов в интерфейсе и правило «операция только лежащему пациенту».
-- И то и другое живёт в коде. Хирургия ХРАНИТСЯ под значением 'other' — как
-- хранилась всегда: в настройках услуг этот тип и был подписан «Хирургия», и
-- все 183 такие услуги в рабочем наборе — операции. Меняется подпись и
-- поведение, а не буквы в столбце.
--
-- Цена решения: в столбце services.type лежит 'other' там, где на экране
-- «Хирургия». Это записано здесь, в service-editor-logic.js и в queue.js.
-- Цена альтернативы: неработающая клиника. Сравнение не в пользу красоты.

-- «Рентген» убирается из интерфейса; строк с этим типом нет ни в одной базе,
-- но если найдутся — им место в диагностике. CHECK это значение разрешает,
-- пересборка не нужна.
UPDATE services SET type = 'imaging' WHERE type = 'radiology';

-- Группа услуги для операций. Миграция 056 раскладывала услуги по группам и
-- уже знала: 'other' → «Хирургия». Здесь только добираем тех, у кого группы
-- не оказалось.
INSERT INTO service_types (name, active)
  SELECT 'Хирургия', 1 WHERE NOT EXISTS (SELECT 1 FROM service_types WHERE name = 'Хирургия');
UPDATE services SET type_id = (SELECT id FROM service_types WHERE name = 'Хирургия')
 WHERE type_id IS NULL AND type = 'other';
