-- 149_visit_services_invoice_item_idx.sql — INPATIENT_SHARE_V1, ревью (C1).
--
-- Каждый денежный отчёт и кабинет врача ищут строку визита ПО СТРОКЕ СЧЁТА
-- (visit_services.invoice_item_id): ITEM_DOCTOR_JOIN группирует их, а доля
-- стационара проверяла «нет ли у строки счёта амбулаторного врача». Индекса у
-- этой колонки не было, и проверка шла полным проходом visit_services на
-- КАЖДУЮ строку счёта: 27 тысяч строк — 11 с, 51 тысяча — 39 с, а кабинет врача
-- спрашивал это при каждом открытии. better-sqlite3 синхронный — всё это время
-- стояла вся клиника.
--
-- Только индекс: данные не меняются, повторный накат ничего не ломает.
CREATE INDEX IF NOT EXISTS idx_visit_services_invoice_item ON visit_services(invoice_item_id);
