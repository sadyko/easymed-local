-- 088_invoice_number_branch.sql — BRANCH_MONEY_NUMBER_V1: номер документа несёт
-- букву здания.
--
-- ЗАЧЕМ. С миграции 087 счета ездят между зданиями, а `invoices.invoice_number`
-- объявлен UNIQUE ещё в 004. Счётчик у каждой установки свой (invoice_counters,
-- миграция 005), поэтому два здания в один и тот же январь чеканят один и тот
-- же 'INV-26-00001' — и приехавший счёт соседа отвергается уникальным индексом
-- НАСОВСЕМ: приём заворачивает отказ базы в savepoint, пишет строку в
-- sync_refused и едет дальше, а квитанция уезжает всё равно (иначе одна
-- «ядовитая» строка повторялась бы в каждом блобе вечно). То есть счёт просто
-- не доехал бы, и денежный отчёт главной клиники недосчитался бы его молча.
--
-- КАК. Ровно так же, как в своё время решили тот же вопрос про номер карты
-- пациента (миграция 080): номер получает БУКВУ ЗДАНИЯ из branch_identity, и
-- буквы во всей сети различны и никогда не переиспользуются
-- (branch_letters_spent). Было 'INV-26-00001' — стало 'INV-A-26-00001';
-- депозит был 'DEP-26-00001' — стал 'DEP-A-26-00001'. Главная клиника — буква
-- A (её ставит 080), филиалы получают свои при подключении (letters.js).
--
-- ПОЧЕМУ В ЭТОМ ФАЙЛЕ НЕТ SQL. Номер чеканится не триггером, а кодом —
-- nextInvoiceNumber (billing.js) и nextDepositNumber (deposits.js), — потому
-- что порядковый номер берётся из счётчика (invoice_counters/deposit_counters),
-- а не из MAX(...) по таблице. Менять здесь нечего: ни колонки, ни индекса, ни
-- данных. Файл существует, потому что решение о ФОРМАТЕ номера — часть схемы, и
-- искать его будут здесь, рядом с 080, а не в истории коммитов.
--
-- ЧТО УВИДИТ КЛИНИКА, дословно:
--   • СТАРЫЕ НОМЕРА НЕ МЕНЯЮТСЯ. 'INV-26-00041', выписанный вчера, остаётся
--     'INV-26-00041' — он напечатан на чеке, лежит в бумагах и в поиске. Ровно
--     то же решение, что 080 приняла про MRN: «existing MRNs are deliberately
--     NOT renumbered». Буква появляется только у номеров, выданных ПОСЛЕ
--     обновления.
--   • НУМЕРАЦИЯ НЕ НАЧИНАЕТСЯ ЗАНОВО. Счётчик per-year общий и продолжает
--     расти: за 'INV-26-00041' идёт 'INV-A-26-00042', а не 'INV-A-26-00001'.
--     Номер не выдаётся дважды, и это главное.
--   • ПОКА БУКВА НЕ НАЗНАЧЕНА, вид номеров не меняется вовсе. У любой клиники,
--     прошедшей 080, буква есть (главная — A), поэтому на практике это
--     означает: главная сразу начинает печатать 'INV-A-…', филиал — 'INV-B-…'
--     со дня, когда его подключили и он принял свою букву (identity.js).
--
-- ЧЕГО ЭТО НЕ ДЕЛАЕТ. Номер счёта не становится ключом слияния: строки
-- по-прежнему опознаются по uid (087/083). Буква нужна ровно для того, чтобы
-- UNIQUE-индекс принимающей базы не отверг честный чужой счёт.
