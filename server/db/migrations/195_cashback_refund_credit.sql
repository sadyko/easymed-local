-- 1. «Новые деньги» на балансе. Пациент заплатил наличными неврологу, тот
--    сказал «не мой пациент», кассир вернул оплату НА БАЛАНС, и с баланса
--    оплатили кардиолога. Кэшбэк первого счёта откатился с возвратом, а второй
--    счёт кэшбэка не давал: оплата с баланса новыми деньгами не считалась.
--    Итог — пациент терял кэшбэк за ошибку клиники.
--
--    Теперь строка баланса несёт new_money — сколько в ней «новых денег»:
--      • зачисление (credit) при возврате НАСТОЯЩЕЙ оплаты (наличные, карта,
--        перевод, эквайринг) — вся сумма; возврат оплаты с баланса — не больше
--        новых денег той оплаты, ещё не вернувшихся на баланс;
--      • списание (spend) — сколько из него взято из этого запаса новых денег
--        (не больше запаса и не больше настоящих денег пациента: кэшбэк и
--        депозит новыми деньгами не становятся).
--    Кэшбэк счёта (rpc/cashback.js cashbackBase) считает оплату с баланса
--    новыми деньгами ровно на её new_money. По-прежнему один раз за жизнь
--    счёта и с тем же откатом при возврате.
--
--    Задним числом строки не размечаются: зачисления до этой версии новыми
--    деньгами не считаются (траты с них до обновления не размечены, и запас
--    сосчитать честно нельзя).
ALTER TABLE patient_deposits ADD COLUMN new_money REAL;

-- 2. Миграция 161 отметила «кэшбэк оценён» у КАЖДОГО счёта, по которому уже
--    были деньги, — в том числе у частично оплаченных и долгов, которые
--    полностью оплачены ещё не были. Доплатив такой счёт после обновления,
--    пациент кэшбэка не получал. Отметка снимается у счетов, которые ещё НЕ
--    оплачены целиком (unpaid / partial / debt), по которым не было ни одного
--    возврата (без возврата счёт такого статуса полностью оплачен не бывал) и
--    у которых нет строки кэшбэка. Оплаченные, отменённые и возвращённые
--    счета не трогаются.
UPDATE invoices
   SET cashback_evaluated_at = NULL
 WHERE cashback_evaluated_at IS NOT NULL
   AND status IN ('unpaid', 'partial', 'debt')
   AND NOT EXISTS (SELECT 1 FROM payments p WHERE p.invoice_id = invoices.id AND p.amount < 0)
   AND NOT EXISTS (SELECT 1 FROM patient_deposits d WHERE d.kind = 'cashback' AND d.invoice_id = invoices.id);
