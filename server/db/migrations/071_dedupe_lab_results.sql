-- LAB_RESULTS_DEDUPE_V1 — чистка дублей, созданных потолком выборки.
--
-- Экран лаборатории читал результаты с .limit(2000). В день, когда строк стало
-- больше (2190), свежие заказы открывались ПУСТЫМИ: их строки не долетали до
-- браузера. Лаборант вводил значения заново, сохранение не находило прежней
-- строки и вставляло новую — у одного заказа накопилось шесть «Обьем мл»,
-- всего 89 лишних строк. Потолок убран (LAB_RESULTS_NO_CAP_V1, laboratory.js);
-- здесь убираем последствия.
--
-- Правило то же, что у формы ввода и у LIS-спеки: (заказ, показатель) — один
-- результат. Оставляем ПОСЛЕДНЮЮ запись (MAX(id) = самый свежий ввод — именно
-- его лаборант видел на экране как «сохранилось»), старые повторы удаляем.
DELETE FROM lab_results
 WHERE id NOT IN (
   SELECT MAX(id) FROM lab_results GROUP BY visit_service_id, parameter
 );
