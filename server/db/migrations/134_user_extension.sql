-- ПОЧЕМУ БЕЗ ЭТОЙ КОЛОНКИ ЗВОНОК НЕВОЗМОЖЕН. И Binotel, и onlinePBX звонят
-- одинаково: программа просит АТС соединить ВНУТРЕННИЙ НОМЕР сотрудника с
-- номером пациента — сначала поднимается трубка у оператора, потом набирается
-- пациент. То есть команда набора состоит из двух номеров, и второй берётся из
-- карточки пациента, а первый взять было неоткуда: у пользователя не было
-- места, где живёт его внутренний номер.
--
-- ОН ЖЕ — ПОДПИСЬ ОПЕРАТОРА. Таблица calls уже хранит internal_number у каждого
-- звонка (и у входящего тоже). Как только внутренний номер известен программе,
-- разбор «кто сколько звонил» считается по САМИМ ЗВОНКАМ, а не по отметкам
-- вручную: номер в звонке — это и есть имя оператора. Поэтому колонка одна и
-- лежит у пользователя, а не отдельная таблица «операторы колл-центра»:
-- оператор — это сотрудник клиники, а не отдельная сущность.
--
-- ТЕКСТ, А НЕ ЧИСЛО. У onlinePBX внутренние номера — 100…4999, у Binotel вид
-- номера свой; встречаются номера с ведущим нулём. Число съело бы ноль молча.
--
-- Без UNIQUE. Два сотрудника на одном номере (две смены за одним столом) —
-- нормальная жизнь регистратуры, и запрещать её базой нельзя. Разбор по
-- операторам в таком случае честно покажет их вместе — это правда о том, как
-- стоит телефон, а не ошибка учёта.
--
-- ТОЛЬКО ADD COLUMN.
ALTER TABLE users ADD COLUMN pbx_extension TEXT;
