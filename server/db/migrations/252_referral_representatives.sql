-- REFERRALS_CRM_V1 (2026-10-26) — «Реферирование» под CRM: представители и специальность.
--
-- Владелец прислал шесть снимков прежнего облачного экрана «Реферирование» и
-- попросил собрать его под CRM, перенеся внешних врачей из «Настроек», «без
-- изменения процесса в регистрации и других местах». Поэтому таблица
-- referral_sources и всё, что её читает и пишет, остаются как были; здесь
-- только то, чего экрану не хватало:
--
-- 1. representative_id — медпредставитель, за которым закреплён внешний врач
--    (вкладка «Представители»: группы по представителю и «Без представителя»).
--    Сотрудник; при его удалении закрепление снимается, а не падает.
--    Пишется ТОЛЬКО RPC referrals_assign_representative (в реестре колонки
--    нет): закрепить можно лишь действующего сотрудника с ролью медпредставителя.
-- 2. specialty — специальность внешнего врача (колонка снимка «Специальность»;
--    у внутренних врачей она в users.specialty, здесь — у внешних).
-- 3. Роль клиники «Медпредставитель» (код medrep). Пустое состояние вкладки
--    говорит: «Заведите сотрудника с ролью «Медпредставитель» в «Настройки →
--    Сотрудники»» — значит такая роль должна существовать заранее. Роль
--    клиники (custom_roles, CUSTOM_ROLES_V1), основа — колл-центр: у
--    представителя нет ни приёма, ни кассы; какие разделы ему видны, клиника
--    решает в «Ролях». INSERT OR IGNORE — у клиники, уже заведшей свою роль с
--    таким кодом, ничего не перезаписывается.
--
-- Индекс — по представителю: вкладка группирует источники по нему.
ALTER TABLE referral_sources ADD COLUMN representative_id INTEGER REFERENCES users(id) ON DELETE SET NULL;
ALTER TABLE referral_sources ADD COLUMN specialty TEXT;
CREATE INDEX idx_referral_sources_representative ON referral_sources(representative_id);

INSERT OR IGNORE INTO custom_roles (code, name, base_role) VALUES ('medrep', 'Медпредставитель', 'callcenter');
