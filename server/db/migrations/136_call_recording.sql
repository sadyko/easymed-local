-- Разбор делается ОДИН раз, в момент записи звонка (telephony/recording.js),
-- а здесь лежит готовый ответ.
--
-- Пустая колонка — нормальное состояние: у неотвеченного звонка записи нет, и
-- у клиники запись может быть вовсе не включена.
