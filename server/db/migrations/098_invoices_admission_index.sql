-- 098_invoices_admission_index.sql — ОДИН ИНДЕКС, И ОН ЖЕ ОБЪЯВЛЕН В 091.
--
-- ─── ПОЧЕМУ ОН ВООБЩЕ НУЖЕН ─────────────────────────────────────────────────
--
-- `invoices.admission_id` появилась в миграции 040 без индекса, и до
-- INPATIENT_FLOW_V1 это было незаметно: по этой колонке спрашивали редко.
-- Теперь по ней спрашивают постоянно:
--
--   • `admissionBalance` (rpc/inpatient.js) — «сколько госпитализация осталась
--     должна» — берёт счета госпитализации ДВУМЯ запросами, и оба без индекса
--     читают ВСЮ таблицу счетов клиники;
--   • `admission_discharge_queue` зовёт admissionBalance ПО КАЖДОЙ СТРОКЕ
--     очереди. Десять человек к оформлению — двадцать полных проходов по
--     счетам за одно открытие экрана.
--
-- EXPLAIN QUERY PLAN до:  SCAN invoices
-- EXPLAIN QUERY PLAN после: SEARCH invoices USING INDEX
--                           idx_invoices_admission (admission_id=?)
--
-- И то же самое, только страшнее, — на самой миграции 091. Она делает
-- `DROP TABLE admissions` при foreign_keys=ON, то есть неявный DELETE каждой
-- строки, и на каждую строку проверяет `invoices` целиком. Замер:
-- 3 000 госпитализаций / 100 000 счетов — 28.3 с; 8 000 / 250 000 — 447 с,
-- семь с половиной минут, за которые клиника не поднимается вовсе (миграции
-- идут на старте). С индексом — 19 мс и 39 мс.
--
-- ─── ПОЧЕМУ ОН НАПИСАН ДВАЖДЫ ───────────────────────────────────────────────
--
-- Тот же `CREATE INDEX IF NOT EXISTS` стоит в НАЧАЛЕ 091, до пересборки. Это
-- не копипаста и не забытая строка — две половины одной задачи:
--
--   091  чинит БУДУЩИЕ установки. База, которая ставится с нуля (или клиника,
--        которая обновляется с v0.8.0 сегодня), проходит 091 с уже созданным
--        индексом и не ждёт семь минут. Класть его в 098 для них поздно: 098
--        применяется ПОСЛЕ 091, когда медленный DROP уже случился.
--
--   098  чинит УЖЕ ОБНОВЛЁННЫЕ машины. На них 091 записана в
--        `schema_migrations`, и migrate() второй раз её не запустит — правка
--        внутри 091 до них не доедет НИКОГДА. Без этого файла у разработчика
--        и у любой машины, успевшей принять 091, индекса не будет, и оба
--        ежедневных запроса выше остались бы полным перебором.
--
-- Убрать любое из двух объявлений — значит потерять одну из половин. `IF NOT
-- EXISTS` делает вторую попытку безвредной: индекс создаётся один раз, кто бы
-- ни успел первым. Приём не новый: `idx_invoices_patient` объявлен и в 004, и
-- в 053 — ровно по той же причине и ровно так же.
--
-- ─── ПОЧЕМУ ЭТО БЕЗОПАСНО ДЛЯ ФИЛИАЛОВ ──────────────────────────────────────
--
-- `invoices` — в SHIPPED (branch-sync/journal.js): у неё есть uid, sync_origin
-- и триггеры *_journal_ins/upd/del. Предупреждение из шапок 084/087 гласит:
-- массовый UPDATE или пересборка такой таблицы — СЕТЕВОЕ СОБЫТИЕ, каждая
-- тронутая строка уедет соседям. Здесь этого не происходит и произойти не
-- может: CREATE INDEX не пишет в таблицу ни одной строки, триггеры UPDATE/
-- INSERT/DELETE не срабатывают, `sync_journal` не получает ни записи. Ни
-- пересборки, ни массового UPDATE в этом файле нет намеренно.
--
-- Стоимость индекса — одна запись в B-дерево на каждый новый счёт. Это ровно
-- та цена, которую уже платят idx_invoices_patient и остальные индексы этой
-- таблицы, и она несопоставима с полным перебором счетов на каждое открытие
-- очереди выписок.
CREATE INDEX IF NOT EXISTS idx_invoices_admission ON invoices(admission_id);
