-- 086_staff_sync.sql — STAFF_SYNC_V1: сотрудники и роли едут в филиалы.
--
-- Владелец, дословно: «the filial users (employees are not rendered to other
-- branches)», и раньше — «every information … users and roles … should be
-- movable across the branches». Правило, которое он выбрал для общих данных,
-- одно и оно же решает здесь всё: ГЛАВНАЯ КЛИНИКА ИМИ УПРАВЛЯЕТ. Филиал
-- получает, а не решает.
--
-- Поэтому сотрудники поехали по каналу СПРАВОЧНИКА (branch-sync/catalogue.js),
-- тем же, что и прайс: односторонним, главный → филиал, с усыновлением уже
-- заведённых строк и без единого удаления. Новый канал пришлось бы учить всему
-- этому заново.
--
-- ЧТО ДОБАВЛЯЕТ ЭТА МИГРАЦИЯ — одну колонку, которая отвечает на один вопрос:
-- «этого человека завели ЗДЕСЬ или он приехал из главной клиники?»
--
--   is_local = 1 — строку завели в этой установке. ЗНАЧЕНИЕ ПО УМОЛЧАНИЮ, и
--                  поэтому в главной клинике и в клинике из одного здания эта
--                  колонка не меняет ничего вовсе: там все строки местные, и
--                  экран «Сотрудники» работает ровно как работал.
--   is_local = 0 — строка приехала из главной клиники. Править её здесь нельзя
--                  (routes/users.js отвечает 409, экран показывает её только
--                  для чтения) — иначе правка, сделанная в филиале, молча
--                  исчезла бы при ближайшей синхронизации, и человек за
--                  стойкой третий раз вводил бы один и тот же телефон.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ КОЛОНКА, А НЕ ЗАПРОС В branch_sync_map. Соответствие «чужой
-- id → свой» — механика переноса, и она может быть пересобрана: карту чистят
-- при отвязке, она не переживает восстановление из чужой резервной копии.
-- «Этой строкой управляет главная клиника» — не механика, а факт продукта, от
-- которого зависит, покажет ли экран кнопку «Сохранить». Строка, которая тихо
-- стала бы редактируемой оттого, что опустела служебная таблица, — это ровно
-- та правка-призрак, ради предотвращения которой колонка и заведена.
--
-- ИСЧЕЗНУВШИХ ОТКЛЮЧАЕМ, А НЕ УДАЛЯЕМ. Сотрудника, которого главная клиника
-- убрала из выгрузки, филиал ставит в is_active = 0 и оставляет строку на
-- месте. Удалить её нельзя физически: за ней тянутся визиты, счета, выданные
-- результаты и подписанные документы ЭТОГО здания, и внешние ключи порвались бы
-- на первом же отчёте. Это то же решение, что и правило «ничего не удаляем» у
-- прайса, только доведённое до конца: у услуги главная клиника снимает
-- active сама, а уволенный сотрудник из выгрузки просто пропадает.
--
-- МЕСТНЫЕ СОТРУДНИКИ НЕ ИСЧЕЗАЮТ. Регистратора, нанятого в филиале до всего
-- этого, главная клиника не знает — и не должна: строки с is_local = 1
-- отключение по «его нет в выгрузке» не трогает вовсе. Именно поэтому проверка
-- идёт по этой колонке, а не по «нет в карте соответствий».
--
-- ПАРОЛЬ ЕДЕТ ВМЕСТЕ С ЧЕЛОВЕКОМ, и это отдельное, названное вслух решение
-- владельца: врач, приехавший принимать во второй корпус, должен войти там под
-- своим обычным логином и паролем, а не заводить себе второй. В базе лежит
-- bcrypt-хеш, канал между зданиями зашифрован сквозным групповым ключом
-- (relay-crypto.js), и filial получает ровно то же, что уже хранит у себя про
-- собственных сотрудников. Обратная сторона названа честно: пароль тоже
-- принадлежит главной клинике, и сменить его можно только там — см.
-- routes/auth.js, где самостоятельная смена пароля для такой учётной записи
-- отвечает отказом, а не молча откатывается ближайшей синхронизацией.
--
-- ПОЧЕМУ ФИЛИАЛ НЕ ОСТАНЕТСЯ БЕЗ АДМИНИСТРАТОРА. Главная клиника не умеет
-- отключить своего последнего активного администратора (routes/users.js), а
-- едут ВСЕ её сотрудники — значит хотя бы один активный админ доезжает всегда.
-- Плюс собственный админ филиала (is_local = 1), которого синхронизация не
-- касается. Отдельная защёлка здесь была бы решением филиала — тем самым,
-- которого правило владельца не предусматривает.
--
-- CHECK — потому что колонка отвечает «да/нет», а на «да/нет» смотрят и SQL
-- (WHERE is_local = 0), и JavaScript. Тройка, приехавшая из кривого импорта,
-- дала бы строку, которая ни местная, ни главная: экран считал бы её
-- редактируемой, а синхронизация — своей.
--
-- NOT NULL DEFAULT обязателен для ALTER TABLE ADD COLUMN в SQLite, и он же
-- проставляет 1 всем уже заведённым сотрудникам: отдельный UPDATE не нужен, а
-- «заведён здесь» — единственно верный ответ для строки, существовавшей до
-- того, как сотрудники вообще научились ездить.
ALTER TABLE users ADD COLUMN is_local INTEGER NOT NULL DEFAULT 1
  CHECK (is_local IN (0, 1));
