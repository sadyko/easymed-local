-- 104_case_documents.sql — CASE_DOCS_V1: история болезни становится КОМПЛЕКТОМ
-- документов, а не тремя записями.
--
-- ─── ЗАЧЕМ ЭТА МИГРАЦИЯ ВООБЩЕ НУЖНА ────────────────────────────────────────
--
-- Владелец показал мокап списка документов госпитализации: одиннадцать
-- обязательных бумаг в регламентном порядке — согласие, осмотр приёмного
-- врача, осмотр анестезиолога, предоперационный эпикриз, осмотр заведующего,
-- первичный осмотр, обоснование клинического диагноза, протокол операции,
-- дневник наблюдения, этапный и выписной эпикризы — плюс «прочие документы».
--
-- Место, где такой документ живёт, УЖЕ ЕСТЬ: `admission_reviews` (095). Там
-- есть черновик и публикация, автор и роль, которой воспользовались, и
-- `superseded_by` — исправление, которое не стирает исходник. Ровно это и
-- нужно каждой из одиннадцати бумаг.
--
-- Не хватало ОДНОГО: словаря. 095 закрыла `kind` тремя значениями
-- ('primary','round','discharge') — теми, у которых есть поведение маршрута, —
-- и написать «протокол операции» было некуда. Без этой миграции чек-лист
-- пришлось бы строить на ВТОРОЙ таблице документов, а вторая таблица под тот
-- же документ — это ровно то, чего 095 избегала вслух.
--
-- ─── ПОЧЕМУ ПЕРЕСБОРКА ТАБЛИЦЫ, А НЕ ALTER ──────────────────────────────────
--
-- SQLite не умеет менять CHECK. Пересборка — тот же приём, которым 046 меняла
-- воронку CRM: новая таблица, перенос строк, DROP, RENAME. Отличие одно и оно
-- важное: у `admission_reviews` ссылка НА САМУ СЕБЯ (`superseded_by`), а
-- foreign_keys в этой базе включены (server/db/connection.js). Перенести
-- строки одним INSERT…SELECT нельзя: строка №1, закрытая строкой №2, ссылалась
-- бы на ещё не вставленную №2, и внешний ключ отказал бы немедленно. Поэтому
-- перенос в ДВА прохода — сначала строки без ссылок, потом ссылки — и это
-- единственная причина, по которой здесь два оператора вместо одного.
--
-- Ничего, кроме `admission_reviews`, миграция не трогает: на неё не ссылается
-- ни одна другая таблица (grep по migrations/), реестр (schema-registry.js)
-- перечисляет её колонки поимённо и они не меняются, а в SHIPPED
-- (branch-sync/journal.js) её нет — стационар живёт в одном здании.
--
-- ─── ЧТО ОЗНАЧАЮТ НОВЫЕ РОДА ────────────────────────────────────────────────
--
-- Три прежних сохраняют смысл ДОСЛОВНО, вместе со всем поведением:
--   primary    первичный осмотр и план — единственный, кто двигает маршрут
--              ('admitted' → 'examined');
--   round      дневник наблюдения — ежедневная запись лечащего врача;
--   discharge  выписной эпикриз — тот, без которого не принимают заявку на
--              выписку (rpc/inpatient.js, admission_discharge_request).
--
-- Восемь новых поведения маршрута НЕ ИМЕЮТ и иметь не должны: это бумаги,
-- которые обязаны быть в истории болезни, а не шаги, которые кого-то куда-то
-- переводят. Сроки по ним считаются от времени размещения на койке
-- (rpc/inpatient-reviews.js, CASE_DOC_SET) и в базе не хранятся: срок — это
-- вычисление от даты госпитализации, а хранимая копия срока разошлась бы с
-- датой в первый же раз, когда дату поправят (ADMISSION_DATE_EDIT_V1 умеет
-- её править).
--
--   consent      согласие на госпитализацию / вмешательство
--   intake       осмотр приёмного (дежурного) врача
--   anesthesia   осмотр анестезиолога и согласие на анестезию
--   preop        предоперационный эпикриз
--   head_review  осмотр заведующего отделением
--   rationale    обоснование клинического диагноза
--   operation    протокол операции
--   interim      этапный эпикриз
--   other        прочие документы — второй раздел мокапа. Открытый род:
--                сюда попадает всё, что клиника подшивает в историю болезни
--                сверх регламентного набора (согласие на препарат пациента,
--                отказ от вмешательства, справка). В обязательный комплект он
--                не входит и на выписку не влияет.
--
-- ─── ЧЕГО ЗДЕСЬ НЕТ: ПРОФИЛЯ ОТДЕЛЕНИЯ ──────────────────────────────────────
--
-- Мокап подписывает список ярлыком «Хирург. профиль» — то есть обещает, что
-- состав обязательных бумаг задаёт отделение. СЕГОДНЯ ЭТОТ ПРОДУКТ ТАКОГО
-- СКАЗАТЬ НЕ МОЖЕТ, и притворяться нечестно: `admissions.department` — это
-- СВОБОДНЫЙ ТЕКСТ (миграция 092, «отделение СЛОВАМИ»), справочника отделений в
-- базе нет вовсе, а значит нет и места, где у отделения был бы профиль.
-- Завести профиль здесь означало бы завести справочник отделений, переписать
-- на него окно заявки и разобрать текст, который клиники уже набрали руками, —
-- отдельная работа, а не строчка в этой миграции.
--
-- Поэтому набор ОДИН на все госпитализации, а хирургический блок
-- (anesthesia / preop / operation) включается не профилем, а СОБЫТИЕМ: как
-- только по госпитализации появился хоть один из этих трёх документов —
-- значит оперируют, и остальные два становятся обязательными. Это данные, а не
-- догадка о профиле.
--
-- Следующий шаг назван вслух: DEPARTMENT_PROFILE_V2 — справочник отделений с
-- профилем и составом обязательного набора на профиль. Пока его нет, набор
-- ниже — общий, и чек-лист говорит об этом словами, а не ярлыком.

CREATE TABLE admission_reviews_v2 (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  admission_id INTEGER NOT NULL REFERENCES admissions(id),

  kind TEXT NOT NULL DEFAULT 'primary' CHECK (kind IN (
    'consent','intake','anesthesia','preop','head_review','primary',
    'rationale','operation','round','interim','discharge','other')),

  complaints TEXT NOT NULL DEFAULT '',
  objective  TEXT NOT NULL DEFAULT '',
  diagnosis  TEXT NOT NULL DEFAULT '',
  plan       TEXT NOT NULL DEFAULT '',
  body       TEXT NOT NULL DEFAULT '',

  author_id INTEGER REFERENCES users(id),
  author_role TEXT NOT NULL DEFAULT '',

  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now')),
  updated_at TEXT,
  published_at TEXT,

  superseded_by INTEGER REFERENCES admission_reviews_v2(id),
  CHECK (superseded_by IS NULL OR superseded_by <> id)
);

-- Проход 1: строки без ссылок друг на друга.
INSERT INTO admission_reviews_v2
  (id, admission_id, kind, complaints, objective, diagnosis, plan, body,
   author_id, author_role, created_at, updated_at, published_at, superseded_by)
SELECT id, admission_id, kind, complaints, objective, diagnosis, plan, body,
       author_id, author_role, created_at, updated_at, published_at, NULL
  FROM admission_reviews;

-- Проход 2: ссылки исправлений — теперь, когда все строки на месте.
UPDATE admission_reviews_v2
   SET superseded_by = (SELECT r.superseded_by FROM admission_reviews r WHERE r.id = admission_reviews_v2.id);

DROP TABLE admission_reviews;
ALTER TABLE admission_reviews_v2 RENAME TO admission_reviews;

-- Тот же индекс, что и в 095, и на те же три вопроса: «есть ли опубликованный
-- документ такого рода», «покажи всё по госпитализации по порядку», «покажи
-- дневник». С чек-листом он становится ещё горячее: одиннадцать строк экрана —
-- это одиннадцать таких вопросов на один показ карточки.
CREATE INDEX idx_admission_reviews_lookup
  ON admission_reviews (admission_id, kind, published_at);
