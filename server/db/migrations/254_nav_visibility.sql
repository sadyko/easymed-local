-- NAV_VISIBILITY_V1 (2026-10-26) — видимость разделов бокового меню для всей клиники.
--
-- Владелец (снимок хаба «Настройки → Основное» и бокового меню): «in here build
-- visibility setting of functions from here, only setting block can not be
-- unvisible». Плитка «Видимость разделов» в группе «Основное»: администратор
-- снимает галочки с разделов, которых в этой клинике нет (например, нет
-- стационара — нет «Стационара», «Задач медсестры», «Порционника», «Выписок»),
-- и они исчезают из меню у всех сотрудников, какие бы права у них ни были.
--
-- Это не права и не лицензия: права решают, КОМУ что можно (role_permissions),
-- лицензия — что КУПЛЕНО (licence.dat); здесь — чего в клинике нет вовсе.
-- Поэтому строка — просто id пункта меню (NAV в admin.js) и кто/когда спрятал;
-- список скрытых = все строки таблицы. «Настройки» сюда не попадают никогда
-- (rpc/nav-visibility.js отказывает): иначе негде было бы вернуть остальное.
CREATE TABLE nav_visibility (
  nav_id    TEXT PRIMARY KEY,
  hidden_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  hidden_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now'))
);
