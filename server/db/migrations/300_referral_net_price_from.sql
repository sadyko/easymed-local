-- ОТ СУММЫ ПОСЛЕ СКИДКИ И НДС.
--
-- Владелец (2026-11-24, по снимку «Подробнее» врача-источника: «here it should show
-- sum after VAT and discount, and then it should calculate %»; на вопрос — «да,
-- сменить правило», «для всех»): процент вознаграждения — от того, что осталось у
-- клиники: цена строки − скидка (в том числе скидка после продажи) − НДС. Прежде, с
-- 3.22.0 (мигр. 283, REFERRAL_FULL_PRICE_V1), — от цены строки до скидки, с НДС.
-- Фиксированная сумма — за услугу, как и была.
--
-- «С дня обновления», как и в 3.22.0: счета, выставленные ДО этого момента, считаются
-- по своему прежнему правилу (reports.js rewardBaseOf), и прошлые суммы не меняются
-- ни на одном экране — ни в закрытых, ни в открытых месяцах.
--
-- Момент пишется ОДИН раз — сейчас, в UTC ISO, как invoices.created_at, — и только у
-- клиники, где счета уже есть. У новой базы строки нет — новое правило для всех
-- счетов. Своя таблица по той же причине, что 283: связь зданий её не возит, у
-- каждого здания свой момент обновления. Одна строка (id = 1).
CREATE TABLE referral_net_price_from (
  id      INTEGER PRIMARY KEY CHECK (id = 1),
  from_at TEXT NOT NULL
);

INSERT INTO referral_net_price_from (id, from_at)
SELECT 1, strftime('%Y-%m-%dT%H:%M:%SZ', 'now')
 WHERE EXISTS (SELECT 1 FROM invoices);
