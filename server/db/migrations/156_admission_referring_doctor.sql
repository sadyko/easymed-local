-- INPATIENT_BONUS_V1, ревью I1 (2026-09-26) — НАПРАВИВШИЙ ВРАЧ ГОСПИТАЛИЗАЦИИ.
--
-- Бонус «за направление в стационар» (users.inpatient_referral_pct / _fixed)
-- платился врачу из admissions.doctor_id. Но эту колонку заполняет и
-- назначение лечащего (admitPatient, admission_set_attending,
-- admission_change_attending пишут COALESCE(doctor_id, лечащий)), поэтому
-- лечащий получал «за направление» за СВОЮ госпитализацию, которую никуда не
-- направлял.
--
-- Теперь направивший — ОТДЕЛЬНАЯ колонка, и пишется она только там, где
-- направившего называют явно:
--   * заявка врача из кабинета (request_admission) — врач, оформивший заявку;
--   * заявка регистратуры (admission_order_create) с явным doctor_id.
-- Лечащего сюда не пишет никто. Записан явно — платится, даже если это тот же
-- человек, что потом стал лечащим.
--
-- Старые госпитализации не заполняются: по данным не отличить «направил» от
-- «лечащий, записанный через COALESCE». Раздел не выпускался (155 — та же
-- неопубликованная работа), так что потерь выплат у клиник нет.
--
-- Врача удалили — госпитализация остаётся, без направившего.
ALTER TABLE admissions ADD COLUMN referring_doctor_id INTEGER
  REFERENCES users(id) ON DELETE SET NULL;
