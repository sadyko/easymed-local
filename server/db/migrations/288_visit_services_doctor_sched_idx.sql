-- Время врача теперь держит и строка визита со своим врачом и временем («Добавить в этот
-- визит»: врач Б на 15:00 в визите пациента к врачу А) — rpc/calendar.js loadLineBusy.
-- Запрос спрашивает строки врача в окне времени: doctor_id = ? AND scheduled_at в диапазоне.
-- Прежний индекс visit_services(doctor_id, created_at) (миграция 210) отвечает только на
-- врача, и запрос перебирал ВСЕ строки врача за всю историю.
--
-- ЗАМЕР (синтетическая клиника: 3000 визитов в день × 120 дней, 360 тыс. визитов,
-- 583 тыс. строк, 6,5 тыс. строк на врача; медиана):
--   calendar_slots одного врача на день: до правки 0,52 мс; правка без индекса 29 мс;
--     с индексом 1,27 мс;
--   calendar_windows 60 врачей × 7 дней: 52 мс; без индекса 1822 мс; с индексом 111 мс;
--   calendar_windows 6 врачей × 1 день: 17 мс; без индекса 180 мс; с индексом 20 мс.
-- План с индексом: SEARCH vs USING INDEX idx_visit_services_doctor_sched
-- (doctor_id=? AND scheduled_at>? AND scheduled_at<?).
--
-- ЧАСТИЧНЫЙ: строки без времени (анализы «на дату» без врача, услуги без записи) времени не
-- держат и в индекс не попадают. Условие запроса scheduled_at >= ? само означает
-- scheduled_at IS NOT NULL, поэтому SQLite берёт частичный индекс.
--
-- ТОЛЬКО ИНДЕКС. Ни одна строка не меняется, журнальные триггеры (084) не срабатывают,
-- в sync_journal не появляется ничего. IF NOT EXISTS — на случай повтора.
CREATE INDEX IF NOT EXISTS idx_visit_services_doctor_sched ON visit_services(doctor_id, scheduled_at) WHERE scheduled_at IS NOT NULL;
