-- LAB_PANEL_DEDUP_V1 (мигр. 272, 2026-11-03, выпуск 3.21.0, ревью M1) — «УДАЛИТЬ»
-- ПАНЕЛЬ В ГЛАВНОМ ЗДАНИИ, ПОКА ФИЛИАЛЫ ЕЩЁ НА 3.20.
--
-- 3.21 научил «Удалить» удалять панель вместе с показателями, и клиника делает
-- ровно это: удаляет сломанную панель и заводит новую на ту же услугу. Удалённая
-- панель просто исчезает из выгрузки справочника, а филиал 3.20 не умеет
-- отвязывать исчезнувшее (это умеет только приём 3.21): его старая панель держит
-- услугу, новая панель главного здания упирается в «одна услуга — одна панель»
-- (UNIQUE, мигр. 048), и приём справочника у такого филиала откатывается при
-- каждой синхронизации — цены, сотрудники, права — пока он не обновится.
--
-- Поэтому главное здание с подключёнными филиалами панель не стирает, а СПИСЫВАЕТ
-- (rpc/lab-panels.js lab_panel_delete): выключает, отвязывает от услуги и от
-- анализатора и ставит retired_at. Списанная панель едет в выгрузке как обычное
-- ИЗМЕНЕНИЕ строки, раньше новой панели (выгрузка идёт по id), — филиал любой
-- версии отвязывает свою копию и принимает замену. На экранах списанная панель не
-- показывается (views/lab-panels.js), её показатели остаются как были.
-- NULL — панель живая. Клиника без филиалов удаляет панель, как и прежде.
ALTER TABLE lab_panels ADD COLUMN retired_at TEXT;
