-- MY_STOCK_V1 (2026-09-23) — «МОИ ЗАПАСЫ» И «МОЙ ОТДЕЛ» СТАНОВЯТСЯ ПРАВОМ.
--
-- ЧТО БЫЛО. Два новых пункта меню решались ТОЛЬКО кодом: «Мои запасы» —
-- списком ролей (permissions.js MY_STOCK_ROLES), «Мой отдел» — полем
-- users.department_id. Экран «Настройки → Роли» о них не знал вовсе: клиника
-- не могла ни выдать их своей роли, ни отнять, а сторожевой тест 055 («каждый
-- пункт меню должен быть выдаваем роли») падал на обоих — и падал по делу.
-- Пункт меню, которого нельзя выдать, для любой ненастроенной роли невидим
-- навсегда; тот же класс ошибки, что чинила 055.
--
-- ЧТО ТЕПЕРЬ. Один ключ `my-stock` на ОБА экрана — идиома `beds` (092): «Мои
-- запасы» и «Мой отдел» это две стороны одной работы (что у меня на руках и
-- чем живёт мой отдел), и второй ключ был бы ловушкой в обе стороны: клиника,
-- выдавшая подотчёт, молча не увидела бы карточку отдела, а роль могла бы
-- получить право тратить, не получив права видеть, чем она тратит.
--
-- ФАКТ «СОСТОИТ В ОТДЕЛЕ» КЛЮЧОМ НЕ СТАНОВИТСЯ и остаётся поверх него
-- (permissions.js personalStockAllowed): «Мой отдел» ведёт на карточку СВОЕГО
-- отдела, и человеку без отдела вести туда некуда даже с выданным ключом.
--
-- КОМУ ВЫДАЁМ. Ровно тем, у кого этот экран есть СЕГОДНЯ, — списку
-- MY_STOCK_ROLES: врач, медсестра, старшая медсестра, главный врач (склад
-- выдаёт им под отчёт — rpc/procurement.js issue_stock_lines) и администратор,
-- чтобы увидеть СВОЁ. Кассиру, регистратуре, лаборанту и оператору
-- колл-центра товар на руки не выдают: ключ им не пишется, и экран у них не
-- появляется. Выдать его такой роли клиника по-прежнему может сама — галочкой,
-- которой до этой миграции не существовало.
--
-- УРОВЕНЬ 'viewer' — «только просмотр», и это правда об экране: ни «Мои
-- запасы», ни карточка своего отдела ничего не пишут. Право выдать со склада
-- живёт в «Закупках» (ключ `inventory`), право изменить отдел — на карточке и
-- решается сервером (department_form can_form), а не этой галочкой.
--
-- СВОИ РОЛИ КЛИНИКИ (CUSTOM_ROLES_V1) — ПО ОСНОВЕ, а не по имени: имён их
-- никто заранее не знает, а «Старшая смена» на основе медсестры держит товар
-- на руках ровно так же, как медсестра. Пропусти мы их — обновление молча
-- отняло бы у них экран. Роль, заведённая ПОСЛЕ обновления, берёт права своей
-- основы копией (roles-editor.js createRole), то есть получает ключ сама.
--
-- ИДИОМА — 092 дословно: json_insert в конец массива sections и уровень
-- рядом, и только там, где ключа ещё нет. Уровень пишется json_patch, а не
-- json_set: путь '$.levels.my-stock' SQLite разбирает по точке, и дефис в
-- имени ключа делает такой путь неоднозначным — слияние по RFC 7386 создаёт
-- `levels`, если его нет, и дополняет, если есть. Защита от повтора та же:
-- NOT LIKE по имени ключа — повторный накат и клиника, уже проставившая
-- галочку руками, ничего не получают заново.
UPDATE role_permissions
   SET permissions = json_patch(
         json_insert(permissions, '$.sections[#]', 'my-stock'),
         '{"levels":{"my-stock":"viewer"}}')
 WHERE json_valid(permissions)
   AND permissions NOT LIKE '%"my-stock"%'
   AND (role IN ('admin', 'doctor', 'nurse', 'senior_nurse', 'head_doctor')
        OR role IN (SELECT code FROM custom_roles
                     WHERE base_role IN ('admin', 'doctor', 'nurse', 'senior_nurse', 'head_doctor')));
