-- 116_review_type_kind.sql — CASE_DOC_SET_V2: запись СВОЕГО рода клиники.
--
-- Миграция 115 позволила клинике завести свой документ. Записать его было
-- нечем: admission_reviews.kind несёт CHECK со списком из двенадцати родов,
-- написанным ещё до того, как набор стал настраиваемым.
--
-- ПОЧЕМУ НЕ СНЯТЬ CHECK. В SQLite ограничение снимается только пересборкой
-- таблицы: создать новую, перелить, переименовать. На admission_reviews лежит
-- вся история болезни всех клиник, и ровно такая пересборка стоила версии
-- 1.1.0 (клиники получили сборку, которая не поднималась). Пересборок мы
-- больше не делаем.
--
-- КАК ВМЕСТО ЭТОГО. Своя запись хранится родом 'other' — он в CHECK есть и
-- значит ровно «документ сверх набора», — а НАСТОЯЩИЙ род лежит в новой
-- колонке. Чтение везде берёт `type_kind`, если он есть, и `kind`, если нет:
-- одна строка в загрузчике, и вся остальная логика (цепочки редакций,
-- разовость, порядок в собранной истории) продолжает работать с одним полем.
--
-- У встроенных родов колонка пуста, и старые записи не тронуты — им и нечего
-- менять.
--
-- Только ADD COLUMN — пересборок нет.
ALTER TABLE admission_reviews ADD COLUMN type_kind TEXT;

-- Чек-лист группирует записи по роду; свои роды ищутся этой же колонкой.
CREATE INDEX IF NOT EXISTS idx_admission_reviews_type_kind ON admission_reviews (admission_id, type_kind);
