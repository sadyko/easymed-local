-- CRM_VIEW_LEVEL_RESTORE (2026-09-28) — РОЛИ, СОХРАНЁННЫЕ ДО 3.12, СНОВА ВЕДУТ ЗАЯВКИ.
--
-- ЧТО СЛУЧИЛОСЬ. До версии 3.12 у раздела «CRM · Заявки» в «Настройки → Роли»
-- не было уровней: раздел либо выдан, либо нет, и экран сохранял выданный
-- раздел с уровнем «viewer». Уровень ничего не значил — заявки вела любая роль
-- с разделом. В 3.12 (V3120_FIX) уровень стал проверяться: «просмотр» — только
-- смотреть. И каждая роль, сохранённая на старом экране, — «Руководитель
-- колл-центра», своя роль оператора, пересохранённый штатный колл-центр —
-- получила «Раздел «CRM · Заявки» выдан вам только на просмотр — менять
-- заявки нельзя.»
--
-- ЧТО ТЕПЕРЬ. Уровень «viewer» у CRM, записанный ДО 3.12, выбран не человеком,
-- а старым экраном, — поднимаем его до «editor» (вести заявки, как и было).
-- Удаление («admin») не выдаём: его никто не выбирал. Настоящий «только
-- просмотр» администратор теперь выбирает сам — у CRM на экране «Роли» есть
-- отдельная галочка «Ведёт заявки».
--
-- Ключ grants.crm (матрица прав) со значением «view», записанный тем же
-- старым экраном, поднимаем так же, до «edit». Повторный накат ничего не
-- меняет: условие уже не выполняется.
UPDATE role_permissions
   SET permissions = json_set(permissions, '$.levels.crm', 'editor')
 WHERE json_valid(permissions)
   AND json_extract(permissions, '$.levels.crm') = 'viewer';

UPDATE role_permissions
   SET permissions = json_set(permissions, '$.grants.crm', 'edit')
 WHERE json_valid(permissions)
   AND json_extract(permissions, '$.grants.crm') = 'view';
