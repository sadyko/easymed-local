-- BRANCH_SYNC_V1 (docs/plans/2026-08-29-branch-sync-DESIGN-QUESTION.md, Stage 1)
-- Каждый филиал — отдельная установка Easy-Med со своей базой. Главный филиал
-- раздаёт справочник (компания, услуги/цены, лабораторные панели), остальные
-- его забирают. Клинические данные (пациенты, визиты, анализы, деньги) Этап 1
-- не трогает вообще — это Этап 2/3.
--
-- Здесь ровно одна таблица, и она решает единственную по-настоящему опасную
-- задачу переноса: КАК ОПОЗНАТЬ ТУ ЖЕ САМУЮ СТРОКУ В ДРУГОЙ БАЗЕ.
--
-- Соблазн — переносить строки «как есть», сохраняя id. Так делать НЕЛЬЗЯ:
-- id в services раздаются автоинкрементом независимо в каждой установке, и в
-- принимающей базе на этот же id УЖЕ ссылаются свои invoice_items,
-- visit_services и doctor_rates. Переписать строку services(id=7) значениями
-- чужой седьмой строки — значит молча переименовать услугу во всех выставленных
-- счетах филиала. Это ровно тот класс ошибки («счёт задваивается», «результат
-- уехал не тому пациенту»), из-за которого синхронизация разбита на этапы.
--
-- Поэтому у принимающей базы СВОИ id, а соответствие «строка главного филиала →
-- своя строка» хранится здесь. Локальная история остаётся целой: ни один id,
-- на который уже ссылаются счета, не меняет смысла.
--
-- remote_id — id строки в базе главного филиала. Вторичный филиал спарен ровно
-- с одним главным (см. services/branch-sync/pairing.js), поэтому пары
-- (table_name, remote_id) достаточно: отдельного идентификатора установки в
-- ключе нет намеренно — если филиал перепаривают к ДРУГОМУ главному, старое
-- соответствие теряет смысл и стирается вместе с парой (branch_sync_unpair).
--
-- Таблица нужна ТОЛЬКО принимающей стороне. На главном филиале она есть, но
-- пуста — миграции одинаковы во всех установках, и отдельной «серверной» схемы
-- у этого продукта нет.
CREATE TABLE branch_sync_map (
  table_name TEXT    NOT NULL,
  remote_id  INTEGER NOT NULL,
  local_id   INTEGER NOT NULL,
  synced_at  TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now')),
  PRIMARY KEY (table_name, remote_id)
);

-- Обратный поиск: «эта локальная строка уже кем-то занята?». Нужен при
-- усыновлении (adopt) — когда во вторичном филиале справочник уже заведён
-- руками и его надо сопоставить с чужим, а не продублировать. Без индекса
-- проверка «строка ещё не сопоставлена» была бы полным перебором таблицы на
-- каждую строку справочника.
CREATE INDEX idx_branch_sync_map_local ON branch_sync_map(table_name, local_id);
