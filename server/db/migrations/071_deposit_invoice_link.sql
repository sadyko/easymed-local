-- DEPOSIT_REVENUE_V1 — принятый депозит становится НАСТОЯЩИМ счётом.
--
-- Раньше приём депозита писал только строку в ящик (cash_movements): деньги
-- сходились на пересчёте смены, но выручкой не считались — предоплата
-- признавалась доходом позже, когда баланс уходил в оплату услуг.
--
-- Клиника решила иначе: доход — это когда деньги ВЗЯЛИ. Поэтому приём теперь
-- создаёт счёт (invoices) и платёж (payments) тем способом, каким кассир взял
-- деньги, и депозит виден в «Приёме оплат» наравне с остальными счетами.
--
-- Чтобы возврат знал, какой счёт отменять, а список — какой счёт показывать,
-- связь хранится явно. Без неё пришлось бы искать счёт по номеру строкой, а
-- номер — вещь, которую однажды захотят поменять.
ALTER TABLE patient_deposits ADD COLUMN invoice_id INTEGER REFERENCES invoices(id);

CREATE INDEX idx_patient_deposits_invoice ON patient_deposits(invoice_id);
