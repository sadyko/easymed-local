-- 099_calendar_booking.sql — CALENDAR_BOOKING_V1: три колонки и один индекс,
-- без которых «Календарь записи» не может показать НИ ОДНОЙ записи.
--
-- ─── ЧТО ИМЕННО СЛОМАНО СЕГОДНЯ ─────────────────────────────────────────────
--
-- views/room-calendar.js существует с RESCAL_V2 и ни в одной клинике не
-- нарисовал ни одного приёма. Причина не в разметке и не в правах: КАЖДЫЙ его
-- запрос просит колонки, которых нет, компилятор запросов отвечает
-- «unknown column» (400), а вызывающий код гасит ошибку в catch и рисует
-- пустую сетку. Из пяти запросов экрана падали пять:
--
--   branches.name_ru        — колонки нет ни в таблице, ни в реестре;
--   floors.branch_id        — колонки нет ни в таблице, ни в реестре;
--   rooms.working_hours     — НЕТ В ТАБЛИЦЕ (эта миграция добавляет);
--   rooms.department_id     — колонки нет и никогда не было;
--   users.branch_id         — В ТАБЛИЦЕ ЕСТЬ с миграции 019, но не в реестре;
--   visits.service_id       — НЕТ В ТАБЛИЦЕ (эта миграция добавляет);
--   visits.room_id          — НЕТ В ТАБЛИЦЕ (эта миграция добавляет).
--
-- Половина чинится реестром (schema-registry.js), половина — здесь. Файл
-- добавляет РОВНО то, что экрану нужно, и ничего сверх: недостающая колонка,
-- которую «дозаведём на будущее», — это колонка, которую никто не заполняет и
-- на которую через год кто-нибудь начнёт полагаться.
--
-- ─── ПОЧЕМУ visits.service_id И visits.room_id ──────────────────────────────
--
-- Владелец описал карточку календаря как «пациент + врач + услуга», а ось
-- сетки — как «врачи ИЛИ кабинеты, переключателем». Обе половины упираются в
-- одну строку визита:
--
--   service_id — из него берётся ДЛИТЕЛЬНОСТЬ слота (services.duration_minutes,
--     по умолчанию 15; у лабораторных своя). Без него высота карточки — это
--     всегда visits.duration_minutes, то есть 30 по умолчанию таблицы, и сетка
--     врёт про занятость: пятиминутный забор крови занимает полчаса, а
--     сорокаминутное УЗИ — те же полчаса.
--   room_id — ось кабинетов. Без неё «Кабинеты» показывают пустые дорожки
--     всегда, чем бы ни была занята комната.
--
-- Обе колонки УЖЕ ПИШЕТ мастер визита: service-picker-modal.js:2480 кладёт их
-- в payload вставки визита. Компилятор молча выбрасывает ключи вне списка
-- записи (insertStatement, «Compat layer: silently drop payload keys»), и
-- значения два года уходили в никуда — вставка проходила, данные терялись.
-- То есть эта миграция не заводит новый поток данных, а ПОДКЛЮЧАЕТ уже
-- существующий.
--
-- ─── ПОЧЕМУ rooms.working_hours ─────────────────────────────────────────────
--
-- Ось кабинетов владелец назвал прямо, значит у кабинета должен быть свой
-- рабочий день: процедурная открывается позже регистратуры, забор крови
-- закрывается в 11:00. Форма JSON — В ТОЧНОСТИ users.working_hours (мигр. 019),
-- потому что окно дня считает ОДИН общий движок (services/rpc/slot-engine.js) и
-- две разные формы означали бы две разные правды о том, что свободно.
-- TEXT NOT NULL DEFAULT '' — тоже как у users.working_hours: пустая строка
-- значит «часов не задано», и движок берёт часы клиники (branches.working_hours
-- / is_24_7). Существующие кабинеты после обновления работают ровно так же, как
-- работали, — это и есть смысл значения по умолчанию.
--
-- ─── ПОЧЕМУ floors.branch_id ЗДЕСЬ НЕТ (решение, а не пропуск) ──────────────
--
-- Экран сегодня спрашивает floors.branch_id, чтобы подписать кабинет буквой
-- здания. Колонка не добавляется, и вот почему:
--
--   1. Заполнять её нечем. `floors` — справочник ЭТОЙ установки: раздел
--      «Помещения» заводит этажи своего здания, и ни один редактор в коде не
--      может поставить этажу чужой филиал. Колонка была бы NULL у каждой
--      строки, а группировка по ней — группировкой по пустоте.
--   2. Спрашивать нечего. Календарь показывает работу СВОЕГО здания
--      (`.is('sync_origin', null)` — то же правило, что у кабинета врача,
--      процедур и лаборатории), поэтому здание у любого показанного кабинета
--      одно и то же. Подпись, одинаковая на всех карточках, — не информация.
--   3. Нужное уже есть. Регистратуре надо отличить кабинет от кабинета, а это
--      ЭТАЖ: rooms.floor_id → floors.name, и этот embed реестр уже объявляет.
--
-- У ВРАЧА всё наоборот, и поэтому users.branch_id (миграция 019, колонка
-- существует) добавляется в читаемые реестром: сотрудники ездят по зданиям
-- справочником (STAFF_SYNC_V1), у врача филиал ЗАПОЛНЕН и он разный. Это
-- единственная подпись здания, за которой стоят настоящие данные.
--
-- ─── ПОЧЕМУ ИНДЕКС ПО visit_date ────────────────────────────────────────────
--
-- Календарь на каждую перерисовку (смена дня, шага, периода, после каждой
-- записи и каждого перетаскивания) спрашивает ОДНО:
--   SELECT … FROM visits WHERE visit_date >= ? AND visit_date < ?
-- без врача — сетка показывает всех сразу. Индексы визитов
-- (idx_visits_doctor_date, idx_visits_patient) для этого не годятся: диапазон
-- по второй колонке составного индекса без равенства по первой не берётся.
-- EXPLAIN QUERY PLAN до: SCAN visits. То есть открыть календарь = прочитать
-- ВСЕ визиты клиники за всю её историю, и с каждым годом это медленнее.
-- После: SEARCH visits USING INDEX idx_visits_date (visit_date>? AND
-- visit_date<?). Цена — одна запись в B-дерево на новый визит, ровно та же,
-- что уже платят два соседних индекса этой таблицы.
--
-- ─── ПОЧЕМУ ЗДЕСЬ НЕТ ОГРАНИЧЕНИЯ «ОДИН ПАЦИЕНТ НА ВРАЧА НА СЛОТ» ───────────
--
-- Правило владельца — жёсткое, и соблазн записать его ограничением базы
-- (UNIQUE / триггер RAISE(ABORT)) велик: обойти базу нельзя. Так делать НЕЛЬЗЯ,
-- и это проверено на живых клиниках старшей системы, где такое ограничение
-- (visits_no_overlap) стояло:
--
--   ensure_visit (rpc/visits.js) заводит визит ДНЯ, и когда времени не назвали,
--   ставит его на 09:00 с длительностью по умолчанию 30 минут. Это не запись на
--   приём, это строка-контейнер для статистики. Второй пациент того же врача,
--   пришедший без записи в тот же день, получает ТУ ЖЕ 09:00 — и ограничение
--   базы отказало бы ему в регистрации вовсе. В старшей системе так и
--   получилось: живая очередь перестала регистрироваться, «не удаётся создать
--   визит», и чинилось это сдвигом на следующий свободный слот, то есть враньём
--   в данных ради обхода собственного ограничения.
--
-- Поэтому запрет двойной записи живёт в RPC `calendar_book`
-- (services/rpc/calendar.js): он знает разницу между ЗАПИСЬЮ НА ВРЕМЯ (её
-- проверяем) и визитом-контейнером, называет в отказе занятое время и имеет
-- явный экстренный путь с обязательной причиной. База остаётся способной
-- принять то, что клиника действительно делает, а правило — там, где его можно
-- сформулировать точно.
--
-- ─── ПОЧЕМУ ЭТО БЕЗОПАСНО ДЛЯ ФИЛИАЛОВ ──────────────────────────────────────
--
-- `visits` и `rooms` — таблицы с журнальными триггерами (084_sync_journal.sql).
-- Их шапка предупреждает: массовый UPDATE или ПЕРЕСБОРКА такой таблицы — сетевое
-- событие, каждая тронутая строка целиком уедет соседям под свежими метками.
-- Здесь нет ни того, ни другого НАМЕРЕННО: только ALTER TABLE ADD COLUMN и
-- CREATE INDEX. ADD COLUMN в SQLite не переписывает строки и не выполняет
-- INSERT/UPDATE/DELETE — ни один из триггеров visits_journal_ins/upd/del не
-- срабатывает, в sync_journal не появляется ни одной записи. Ни одного
-- UPDATE в файле нет вовсе, и это проверяется тестом (099.test.js).
--
-- Ещё одно следствие, и оно тоже намеренное: НОВЫЕ КОЛОНКИ НЕ УЕЗЖАЮТ.
-- SHIPPED.visits (branch-sync/journal.js) перечисляет visit_date,
-- duration_minutes, visit_kind, visit_type, status, notes — service_id и
-- room_id туда не добавляются, и triggers visits_journal_upd их не перечисляет,
-- значит правка ОДНОЙ такой колонки не даёт записи в журнал вовсе. Это ровно
-- то, что нужно на этом шаге: календарь показывает записи СВОЕГО здания, а
-- межфилиальный календарь — отдельная задача, и она требует решения про врача
-- (SHIPPED.visits не везёт doctor_id: локальный id указывал бы в пустоту).
-- Шов оставлен здесь и назван вслух.

ALTER TABLE visits ADD COLUMN room_id    INTEGER REFERENCES rooms(id);
ALTER TABLE visits ADD COLUMN service_id INTEGER REFERENCES services(id);

ALTER TABLE rooms  ADD COLUMN working_hours TEXT NOT NULL DEFAULT '';

CREATE INDEX IF NOT EXISTS idx_visits_date ON visits(visit_date);
