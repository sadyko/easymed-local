-- Решение владельца: направление врача, которое регистратор не оформил (с причиной), снимает
-- пациента со списка «Ждут регистрации». Чтобы список это знал, пропуск хранится не текстом
-- («строка визита № 12» в notes), а номером строки визита: invoice_audit_log.visit_service_id.
-- Пишет его только сервер (rpc/registrar-desk.js — пропуск направления, снятие строки записи
-- окном регистрации), в той же транзакции, что и действие.
--
-- ТОЛЬКО ДОБАВЛЕНИЕ. Колонка без значения по умолчанию: прежние строки журнала остаются как
-- были (NULL — «строка не названа»), ни одна существующая строка клиники не меняется.
-- REFERENCES нет нарочно, как у crm_request_services.visit_service_id (миграция 187): строку
-- визита снимают, а след в журнале обязан остаться. Индекс — частичный: строк журнала со строкой
-- визита единицы, и только их ищет список.
ALTER TABLE invoice_audit_log ADD COLUMN visit_service_id INTEGER;
CREATE INDEX IF NOT EXISTS idx_invoice_audit_log_vs ON invoice_audit_log(visit_service_id) WHERE visit_service_id IS NOT NULL;
