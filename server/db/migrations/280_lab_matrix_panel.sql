--
-- Бак. посев — не список показателей «имя — число», а таблица: разделы
-- («Определяемые микроорганизмы», «Антибиограмма», «Противогрибковая
-- чувствительность»), у каждого — свои графы («Положительный | Отрицательный»,
-- «Резистентный | Чувствительный»), строки — микроорганизмы и препараты, в ячейке —
-- степень (−, +, ++, +++, ++++).
--
-- lab_panels.kind — вид панели: '' — обычная (все существующие панели остаются
-- такими: DEFAULT проставляет их сам), 'matrix' — таблица.
-- lab_panels.matrix_json — устройство таблицы: {scale:[…], sections:[{title,
-- columns:[…], rows:[…]}]}. Пишет только сервер (rpc/lab-panels.js lab_panel_save).
--
-- Значения хранятся как у любой панели — строками lab_results: каждая ячейка —
-- показатель панели «строка · графа» в разделе (group_label) со списком степеней
-- (value_type 'select'). Поэтому карта пациента, бот и «Документы» видят результат
-- и без знания о таблице, а бланк лаборатории рисует таблицу.
--
-- Только добавление колонок: ни одна существующая панель, показатель и результат
-- не переписывается.
ALTER TABLE lab_panels ADD COLUMN kind TEXT NOT NULL DEFAULT '' CHECK (kind IN ('', 'matrix'));
ALTER TABLE lab_panels ADD COLUMN matrix_json TEXT;
