-- 090_sync_minted.sql — BRANCH_NUMBER_REMINT_V1, часть вторая: ПЕРЕЧЕКАНЕННЫЙ
-- НОМЕР БОЛЬШЕ НЕ МЕНЯЕТСЯ.
--
-- ЧТО БЫЛО НЕ ТАК. Миграция 088 и код приёма (branch-sync/records.js,
-- remintTakenKeys) договорились: приехавший 'INV-26-00001', который здесь уже
-- занят ДРУГИМ документом, ложится как 'INV-26-00001-C'. Решение считалось
-- ЗАНОВО на каждом приезде той же строки — от текущего состояния таблицы. А
-- состояние меняется: местный счёт, державший 'INV-26-00001', аннулировали и
-- удалили — и следующая же правка того же приезжего счёта возвращала ему
-- 'INV-26-00001'. То же с номером карты пациента.
--
-- Для владельца это худший из возможных ответов. Номер карты и номер счёта —
-- это то, что напечатано на квитанции, вписано в бумажный журнал и по чему
-- ищут в программе. Номер, который система один раз показала, не имеет права
-- смениться НИКОГДА — даже на «более правильный».
--
-- ЧТО ДЕЛАЕТ ЭТА ТАБЛИЦА. Хранит принятое решение: «строке (таблица, uid) в
-- колонке col приехало значение src, а мы записали value». Дальше это решение
-- только ЧИТАЕТСЯ: любой следующий приезд той же строки берёт value дословно и
-- ничего не пересчитывает. Даже когда позже приезжает БОЛЕЕ ТОЧНАЯ буква
-- здания (поле home на проводе, см. records.js) — номер остаётся тем, который
-- уже видели люди.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ КОЛОНКА В patients/invoices:
--   • решение поколоночное (mrn у пациента, invoice_number у счёта), и колонок
--     этих со временем может стать больше — UNIQUE_TEXT_KEYS в records.js
--     прямо предусматривает пополнение;
--   • колонка в самой таблице поехала бы соседям (SHIPPED) или потребовала бы
--     объяснять, почему не поехала: наша перечеканка — это НАШЕ местное
--     решение, соседу оно не нужно и вредно;
--   • у строки, которую перечеканивать не пришлось, здесь НЕТ записи вовсе —
--     а колонка была бы у каждой строки базы ради доли процента случаев.
--
-- ЧИСТКОЙ ЖУРНАЛА НЕ ЗАТРАГИВАЕТСЯ — ровно как sync_authored (084). Журнал
-- (sync_journal) чистится по подтверждению соседа, sync_seen — по горизонту в
-- 90 дней; если бы решение о номере лежало там, оно испарялось бы через
-- квартал и номер снова «плавал» бы. Здесь запись живёт СТОЛЬКО ЖЕ, СКОЛЬКО
-- САМА СТРОКА: её уносит только удаление строки (триггеры ниже).
--
-- ДЁШЕВО ЛИ ЭТО. Первичный ключ (tbl, uid, col) — ровно тот запрос, которым
-- приём и спрашивает; WITHOUT ROWID убирает второй уровень косвенности, потому
-- что таблица целиком состоит из своего ключа. Один точечный поиск на
-- уникальную колонку приехавшей строки, и только для patients и invoices.
CREATE TABLE sync_minted (
  tbl   TEXT NOT NULL,
  uid   TEXT NOT NULL,
  col   TEXT NOT NULL,
  -- Номер, КАК ОН ПРИЕХАЛ. Нужен не для истории, а для решения: приезд с ДРУГИМ
  -- исходным номером — это уже другой вопрос, и отвечать на него сохранённым
  -- ответом нельзя (приложение номера не правит, но полагаться на это молча —
  -- значит однажды переименовать документ в чужой).
  src   TEXT NOT NULL,
  -- Что мы записали в строку. Дословно, включая букву здания и цифру.
  value TEXT NOT NULL,
  at    TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now')),
  PRIMARY KEY (tbl, uid, col)
) WITHOUT ROWID;

-- УДАЛИЛИ СТРОКУ — УБРАЛИ И РЕШЕНИЕ. Тот же приём, что у sync_authored в 084:
-- чистит ТРИГГЕР, а не код приёма, потому что удалить строку можно и руками из
-- программы (аннулированный счёт, слитый дубль карты), а не только порцией
-- синхронизации. Останься запись — заведённая заново строка с тем же uid
-- получила бы номер от прошлой жизни.
--
-- Триггеры отдельные, а не дописанные в *_journal_del: файл миграции, который
-- уже применён у клиник, не переписывают (schema_migrations помнит имя, а не
-- содержимое).
--
-- ТОЛЬКО patients И invoices — ровно те таблицы, у которых есть ездящий
-- уникальный текстовый ключ (UNIQUE_TEXT_KEYS, records.js). Появится третья —
-- сюда нужен третий триггер, и об этом сказано там же.
CREATE TRIGGER patients_minted_del AFTER DELETE ON patients
  WHEN OLD.uid IS NOT NULL
  BEGIN
    DELETE FROM sync_minted WHERE tbl = 'patients' AND uid = OLD.uid;
  END;

CREATE TRIGGER invoices_minted_del AFTER DELETE ON invoices
  WHEN OLD.uid IS NOT NULL
  BEGIN
    DELETE FROM sync_minted WHERE tbl = 'invoices' AND uid = OLD.uid;
  END;
