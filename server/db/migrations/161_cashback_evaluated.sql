-- CASHBACK_SERVER_V2, третья проверка денег (2026-09-27) — КЭШБЭК ОЦЕНИВАЕТСЯ
-- ОДИН РАЗ, КОГДА СЧЁТ ВПЕРВЫЕ СТАЛ ОПЛАЧЕННЫМ.
--
-- «Один раз за жизнь счёта» смотрел только на строку кэшбэка. Счёт, оплаченный
-- без правила (или до этой версии), строки не имел — и «вернуть 1, оплатить 1»
-- переводил его в оплаченный заново и начислял кэшбэк задним числом, на любой
-- старый счёт. Теперь у счёта есть отметка: её ставит первая же полная оплата
-- при ЛЮБОМ исходе (правила нет, 0 %, начислено), и кэшбэк начисляется, только
-- пока отметки нет (rpc/cashback.js).
--
-- Задним числом кэшбэк не начисляется (решение владельца): каждый счёт, по
-- которому уже были деньги, получает отметку сейчас.
ALTER TABLE invoices ADD COLUMN cashback_evaluated_at TEXT;

UPDATE invoices
   SET cashback_evaluated_at = COALESCE(paid_at, created_at, strftime('%Y-%m-%dT%H:%M:%SZ','now'))
 WHERE status = 'paid' OR EXISTS (SELECT 1 FROM payments p WHERE p.invoice_id = invoices.id);
