-- ---------------------------------------------------------------------------
-- 2. История назначений стола
-- ---------------------------------------------------------------------------
-- ОДНА СТРОКА — ОДИН ПЕРИОД. Смена стола НИКОГДА не правит строку на месте: она
-- закрывает действующую (ended_at) и открывает новую. История — это и есть смысл
-- таблицы: «пациент на девятом столе» без даты, с которой он на нём, не отвечает
-- ни на один вопрос, ради которого об этом спрашивают.
--
-- ДЕЙСТВУЮЩИЙ стол = строка с ended_at IS NULL. Единственность обеспечивает
-- частичный UNIQUE ниже — не «договорённость в коде», а сама база: при
-- одновременной смене стола врачом и старшей медсестрой без него у пациента
-- оказалось бы два действующих стола, и порционник посчитал бы две порции.
CREATE TABLE admission_diets (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  admission_id INTEGER NOT NULL REFERENCES admissions(id),

  -- Ссылка по КОДУ, а не по id: код — то, что напечатано в порционнике и в
  -- истории болезни, и он переживает пересборку справочника.
  diet_code TEXT NOT NULL REFERENCES diet_tables(code),

  -- С какого момента стол действует.
  since TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now')),
  -- Закрыт следующим назначением (или выпиской). NULL = действует сейчас.
  ended_at TEXT,

  -- КТО НАЖАЛ. Именно нажал, а не «лечащий врач»: в референсе автором смены
  -- стола записывается лечащий врач независимо от того, кто её сделал, и это
  -- ошибка — стол в 03:40 меняет дежурная старшая медсестра, а подпись стоит
  -- врача, которого в клинике в ту ночь не было. Здесь пишется id вызывающего.
  assigned_by INTEGER REFERENCES users(id),
  note TEXT NOT NULL DEFAULT '',

  -- РАЗОВОСТЬ ПИТАНИЯ (3/4/5/6-разовое) живёт ЗДЕСЬ, а не в `admissions`.
  -- Три довода, по убыванию веса:
  --   1. Она меняется ВМЕСТЕ со столом и по тем же поводам: перевод с №15 на
  --      №9 — это и другой стол, и другая разовость. Одна строка — одно
  --      решение врача о питании; хранить половину решения в другой таблице
  --      значит рано или поздно рассинхронизировать половины.
  --   2. Ей нужна ТА ЖЕ история, что и столу: «с какого дня пациента кормят
  --      шесть раз» — тот же вопрос, что «с какого дня он на пятом столе».
  --      Колонка на `admissions` хранит только последнее значение.
  --   3. Колонка на `admissions` потребовала бы ПЕРЕСБОРКИ таблицы (SQLite не
  --      умеет добавить CHECK к существующей), а `admissions` в этом же
  --      релизе пересобирает соседняя задача маршрута. Две пересборки одной
  --      таблицы в одном выпуске — способ потерять одну из них молча.
  meals_per_day INTEGER NOT NULL DEFAULT 4
    CHECK (meals_per_day BETWEEN 3 AND 6),

  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now'))
);

-- Один действующий стол на госпитализацию — правилом базы, а не обещанием кода.
CREATE UNIQUE INDEX ux_admission_diet_current
  ON admission_diets(admission_id) WHERE ended_at IS NULL;

-- Порционник и карта пациента: «какой стол действовал у этой госпитализации на
-- эту дату» — ходят по admission_id и since.
CREATE INDEX idx_admission_diets_history
  ON admission_diets(admission_id, since);

-- Кухня считает порции ПО СТОЛУ: «сколько пятого на завтра».
CREATE INDEX idx_admission_diets_code
  ON admission_diets(diet_code) WHERE ended_at IS NULL;

-- ---------------------------------------------------------------------------
-- 3. Отметка приёмов пищи
-- ---------------------------------------------------------------------------
-- ОДНА СТРОКА — ОДИН ПРИЁМ ПИЩИ ОДНОГО ПАЦИЕНТА В ОДИН ДЕНЬ. Ключ
-- (госпитализация, ДАТА, приём) — та же форма, что у ключа отметки дозы в 093, и
-- по той же причине: без даты в ключе весь курс схлопнулся бы в одни сутки, а
-- повторное нажатие на общем планшете отделения дало бы вторую строку.
CREATE TABLE admission_meals (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  admission_id INTEGER NOT NULL REFERENCES admissions(id),

  -- Дата по МЕСТНОМУ календарю клиники, 'YYYY-MM-DD': завтрак — это завтрак
  -- настенных часов отделения, а не UTC-суток (тот же довод, что в
  -- domain/day.js).
  meal_date TEXT NOT NULL,

  -- Приёмы пищи — ЛАТИНСКИМИ кодами, подписи даёт словарь i18n.
  -- Русское значение в базе выглядело бы удобнее ровно до первого экрана на
  -- узбекском: строка из таблицы мимо tr() не переводится, а переводить
  -- содержимое базы по словарю — способ сломать его на первой же опечатке.
  --   breakfast  завтрак        tea    полдник
  --   breakfast2 2-й завтрак    dinner ужин
  --   lunch      обед           night  на ночь
  meal_key TEXT NOT NULL CHECK (meal_key IN
    ('breakfast','breakfast2','lunch','tea','dinner','night')),

  -- 'waiting' — приём ещё впереди (строка заведена планом);
  -- 'served'  — подано; 'eaten' — съедено; 'partial' — съедено частично;
  -- 'refused' — отказался; 'npo' — стол отменён (nil per os: перед операцией,
  --             перед наркозом, при кишечной непроходимости);
  -- 'missed'  — приём пропущен (был на исследовании, спал, не подали).
  -- 'refused' и 'missed' разведены намеренно: отказ пациента и промах отделения
  -- — разные события, и лечащий врач реагирует на них по-разному.
  status TEXT NOT NULL CHECK (status IN
    ('waiting','served','eaten','partial','refused','npo','missed')),

  marked_by INTEGER REFERENCES users(id),
  marked_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now')),
  note TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now')),

  -- Идемпотентность отметки — правилом базы. Повтор перезаписывает СВОЮ строку
  -- (UPSERT в rpc/diet.js), а не заводит вторую.
  UNIQUE (admission_id, meal_date, meal_key)
);

-- Лист питания отделения на дату: «кто что сегодня ел» — ходит по дате.
CREATE INDEX idx_admission_meals_date ON admission_meals(meal_date, admission_id);
