-- V3120_PERF (2026-09-27) — номер карты нового пациента без перебора всех карт.
--
-- Триггер patients_mrn_autogen (080) даёт карте номер <буква>-<ГГ>-<NNNNN>:
-- следующий после наибольшего номера ЭТОГО ГОДА среди всех карт —
--   SELECT COALESCE(MAX(CAST(substr(mrn, -5) AS INTEGER)), 0) + 1
--     FROM patients WHERE substr(mrn, -9, 4) = '-ГГ-'
-- Индекса под эти выражения не было, и каждая регистрация читала ВСЕ карты
-- клиники: 39 мс на 50 тыс. пациентов, линейно с ростом базы (в инспекции —
-- 61 мс), и всё это время база однопоточна.
--
-- Индекс ровно по тем же двум выражениям. SQLite сравнивает выражения индекса
-- и запроса по структуре, берёт индекс и отвечает на MAX одним спуском по
-- дереву (SeekLE + Prev) — 0,6 мс на вставку, независимо от числа пациентов.
--
-- ПОЧЕМУ НЕ ТАБЛИЦА-СЧЁТЧИК. Счётчик помнил бы только номера, выданные этим
-- триггером. Но в тот же MAX входят и карты, приехавшие от соседних зданий
-- (branch-sync пишет mrn готовым, 'B-26-00042'), и номера, введённые руками, и
-- номер освобождается, если удалили последнего. Счётчик, не видящий этих
-- путей, разошёлся бы с MAX — и следующая регистрация упёрлась бы в UNIQUE на
-- mrn, то есть пациента нельзя было бы зарегистрировать. Индекс отвечает на
-- ТОТ ЖЕ вопрос тем же ответом, поэтому правило номера не меняется вовсе, а
-- триггер не пересоздаётся (порядок AFTER-триггеров, см. шапку 084, не
-- трогается).
--
-- БЕЗОПАСНО ДЛЯ ФИЛИАЛОВ: только CREATE INDEX — ни одна строка не меняется,
-- журнал обмена (084) не пишет ничего.
CREATE INDEX IF NOT EXISTS idx_patients_mrn_seq
  ON patients(substr(mrn, -9, 4), CAST(substr(mrn, -5) AS INTEGER));
