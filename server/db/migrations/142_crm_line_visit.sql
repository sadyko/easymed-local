-- 142_crm_line_visit.sql — CRM_REAL_BOOKING_V1: У СТРОКИ ЗАЯВКИ ПОЯВЛЯЕТСЯ ЕЁ ВИЗИТ.
--
-- Владелец (2026-09-21): запись колл-центра — это НАСТОЯЩИЙ СЛОТ В КАЛЕНДАРЕ, а
-- не пожелание («a call-centre booking holds a real calendar slot»). До этой
-- миграции «Сохранить и записать» писало только услугу и день: в календаре не
-- появлялось ничего, время у врача никем не держалось, и регистратура в день
-- приёма узнавала о записи из сметы, а не из сетки.
--
-- ССЫЛКА ЖИВЁТ НА СТРОКЕ, А НЕ НА ЗАЯВКЕ. С миграции 057 заявка — это НЕ одна
-- дата: «УЗИ во вторник, анализы в среду» — одна заявка и две строки, у каждой
-- свой день и своя услуга. Значит и визитов у неё столько же, сколько дней:
-- колонка на родителе смогла бы удержать только первый, а остальные дни
-- остались бы без слота — ровно тот дефект, который эта задача и чинит.
--
-- NULL — это «строка дня без времени» и вся история до сегодня. Строка без
-- врача (лаборатория, анализы) записывается датой, как и раньше, и визита у
-- неё нет; ни одна уже заведённая строка задним числом ничего не получает.
--
-- ИНДЕКС — ДЛЯ ОБРАТНОГО ВОПРОСА. По ссылке ходят в обе стороны: «какие строки
-- у этого визита» (отметка прихода — server/services/crm/visit-status.js) и
-- «из какой заявки эта запись» (сетка календаря спрашивает про ВСЕ блоки дня
-- одним `in('visit_id', …)`). Без индекса второй вопрос — это полный перебор
-- таблицы на каждую перерисовку календаря.
--
-- ФИЛИАЛАМ ЭТА КОЛОНКА НЕ ЕЗДИТ, и не потому, что её забыли внести в список.
-- Обмен между зданиями везёт РОВНО те таблицы, что перечислены в SHIPPED
-- (server/services/branch-sync/journal.js), а crm_request_services там нет
-- вовсе: доска заявок — своя у каждого здания. Даже окажись она там,
-- visit_id уехать не мог бы: это id ЭТОЙ базы, у соседа под тем же номером
-- лежит чужая строка (потому визиты и ездят по uid, а не по id, — миграция
-- 083). Журнальных триггеров у этой таблицы тоже нет (миграция 084 завела их
-- четырём таблицам обмена), поэтому правка visit_id не даёт в журнале ни
-- записи — обмену о ней знать неоткуда и незачем.
--
-- ТОЛЬКО ADD COLUMN + ИНДЕКС.
ALTER TABLE crm_request_services ADD COLUMN visit_id INTEGER REFERENCES visits(id);
CREATE INDEX IF NOT EXISTS idx_crm_req_services_visit ON crm_request_services(visit_id);
