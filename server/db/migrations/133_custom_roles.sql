--
-- Владелец (2026-09-16): «and also aviable option to create a new role with
-- editing permissions?» — и на вопрос, как быть с правами к данным, выбрал
-- «своё название на базе встроенной».
--
-- ПОЧЕМУ ИМЕННО ТАК. Права к ДАННЫМ сервер проверяет по восьми штатным ролям:
-- реестр таблиц (schema-registry.js) и гарды RPC перечисляют их по именам. Роль
-- с новым именем не значила бы для сервера ничего — человек видел бы разделы и
-- получал отказ на каждом сохранении. Поэтому у своей роли есть ОСНОВА: одна из
-- штатных ролей, по которой сервер и решает, что человеку отдать. Название и
-- набор разделов — свои.
--
-- ЧТО ЧЕМУ ХОЗЯИН:
--   • основа (base_role) — потолок: своя роль не может получить у сервера
--     больше, чем её основа;
--   • её собственные права (строка в role_permissions по коду роли) ЗАМЕНЯЮТ
--     права основы на экранах: «Старший регистратор» может видеть МЕНЬШЕ, чем
--     регистратура, и это главное, ради чего роль заводят.
--
-- Код роли — латиница, цифры, дефис и подчёркивание: он попадает в
-- role_permissions.role рядом со штатными именами и не должен с ними
-- столкнуться. Имя штатной роли кодом своей быть не может (UNIQUE + проверка в
-- routes/users.js).
--
-- ТОЛЬКО CREATE TABLE + ADD COLUMN.
CREATE TABLE IF NOT EXISTS custom_roles (
    id         INTEGER PRIMARY KEY AUTOINCREMENT,
    code       TEXT    NOT NULL UNIQUE,
    name       TEXT    NOT NULL,
    base_role  TEXT    NOT NULL,
    active     INTEGER NOT NULL DEFAULT 1,
    created_at TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now')),
    updated_at TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now'))
);

-- Сотрудник со своей ролью ХРАНИТ И ОСНОВУ: users.role остаётся штатной ролью
-- (по ней сервер отдаёт данные), а код своей роли лежит рядом. Пусто — человек
-- работает по штатной роли, как раньше.
ALTER TABLE users ADD COLUMN custom_role_code TEXT;
