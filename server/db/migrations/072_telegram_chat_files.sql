-- TELEGRAM_CHAT_FILE_V1 — оператор отправляет пациенту файл.
--
-- Отправить файл бот умел и раньше, но только САМ: по кнопке «Мои документы»
-- он отдавал сгенерированный PDF. Ответить пациенту файлом — прислать снимок,
-- направление, результат из другой лаборатории — было нельзя, и оператор
-- пересылал такое из личного мессенджера, мимо клиники и мимо журнала.
--
-- Вид сообщения ('document') в CHECK уже разрешён: это тот же вид, которым
-- помечается выдача документа ботом. Не хватало только одного — ГДЕ лежит
-- отправленное. Без этого лента показывала бы имя файла, которое ничего не
-- открывает, и «что мы ему вчера отправили?» осталось бы без ответа.
--
-- Путь — внутри корзины telegram-media (data/storage/telegram-media/...), без
-- имени самой корзины: ровно так же хранится картинка рассылки
-- (telegram_broadcasts.image_path). Для входящих и текстовых сообщений колонка
-- пустая.
