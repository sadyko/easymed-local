-- COVERAGE_SPLIT_V1 — счёт знает, КОМУ он выставлен.
--
-- Раньше плательщик жил только на карте пациента (patients.payer_id), то есть
-- «на кого идёт счёт» было свойством человека, а не документа. Из-за этого
-- нельзя было разделить визит: часть услуг покрывает страховая, остальное
-- платит пациент. Теперь у каждого счёта свой плательщик:
--   payer_id IS NULL — платит пациент (касса принимает деньги);
--   payer_id = <id>  — счёт выставлен организации/страховой (пациенту в кассе
--                      его предъявлять нельзя).
ALTER TABLE invoices ADD COLUMN payer_id INTEGER REFERENCES payers(id);

-- Касса и отчёты фильтруют «чьи это деньги», поэтому колонка индексируется.
CREATE INDEX IF NOT EXISTS idx_invoices_payer ON invoices(payer_id);
