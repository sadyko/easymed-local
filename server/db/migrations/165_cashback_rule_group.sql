-- CASHBACK_BY_GROUP_V1 (2026-09-27) — ПРАВИЛО КЭШБЭКА ПРИВЯЗАНО К ГРУППЕ ПАЦИЕНТА.
--
-- Владелец (B1): кэшбэк зависит от группы пациента (patient_categories). У
-- правила появляется группа:
--
--   category_id = группа  — правило только для пациентов этой группы;
--   category_id = NULL    — правило «для всех».
--
-- Какое правило действует (rpc/cashback.js, cashbackRuleFor):
--   • у пациента есть группа и у группы есть действующее правило — берутся
--     ТОЛЬКО правила группы (из них — с наибольшим процентом). Правило группы
--     с 0 % значит «этой группе кэшбэка нет», а не «возьми общее»;
--   • у группы действующих правил нет, или у пациента группы нет — правила
--     «для всех» (из них — с наибольшим процентом).
--
-- Существующие правила группы не получают: они «для всех», как и работали
-- до этой версии, — поведение сегодняшних клиник не меняется.
ALTER TABLE cashback_rules ADD COLUMN category_id INTEGER REFERENCES patient_categories(id) ON DELETE SET NULL;
CREATE INDEX idx_cashback_rules_category ON cashback_rules(category_id);
