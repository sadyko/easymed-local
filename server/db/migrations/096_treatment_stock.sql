-- 096_treatment_stock.sql — MED_ADMIN_CHARGE_V1: отметка о введении списывает
-- препарат со склада и попадает в счёт (Задача 6 плана «Стационар»).
--
-- Миграция ДОБАВЛЯЕТ ТРИ КОЛОНКИ и НЕ ТРОГАЕТ БОЛЬШЕ НИЧЕГО. Ни одной таблицы
-- не пересобирается, ни одной строки не переписывается, `invoices` не
-- упоминается вовсе — предупреждение из шапки 084_sync_journal.sql
-- («никогда не перестраивать и не обновлять массово таблицу с триггерами
-- синхронизации») соблюдено буквально. `treatment_orders`,
-- `treatment_administrations` и `products` в SHIPPED не входят, триггеров на
-- них нет, и эта миграция их там не заводит.
--
-- ─── 1. СКОЛЬКО СПИСЫВАТЬ ЗА ОДНУ ДОЗУ ──────────────────────────────────────
--
-- `dose` — свободный текст врача: «1 г», «2 таб.», «по схеме». Склад считает
-- штуки, миллилитры и граммы (`products.unit`). Моста между ними нет: «1 г»
-- цефтриаксона — это один флакон, если флакон по грамму, и два, если по
-- полграмма, и ни одна формула этого не знает.
--
-- Правило (domain/dose.js) поэтому такое: считаем из дозы ТОЛЬКО когда это
-- честно (доза без единицы = счёт единиц склада; «500 мг» при складе в «г» =
-- 0.5), а во всех прочих случаях НЕ УГАДЫВАЕМ — отметка записывается, списание
-- пропускается, и человек это видит.
--
-- `stock_qty` — выход из этого тупика: врач (или экран назначения) говорит
-- ЯВНО, сколько единиц склада уходит на одну дозу, и тогда текст дозы больше
-- ни на что не влияет. NULL = «не сказано», работает разбор дозы.
ALTER TABLE treatment_orders ADD COLUMN stock_qty REAL;

-- ─── 2. ЧТО СЛУЧИЛОСЬ СО СПИСАНИЕМ У ЭТОЙ ОТМЕТКИ ───────────────────────────
--
-- Медсестра нажала «дала» — доза введена, и это медицинский факт, который
-- записывается ВСЕГДА. Списание же может не получиться: количество не выводится
-- из дозы, товара нет на остатке, позиция погашена. План говорит об этом прямо:
-- «Нет остатка — предупреждение, а не запрет». Значит у отметки есть ВТОРАЯ,
-- складская судьба, и она обязана быть видимой — иначе клиника узнаёт о
-- несписанных препаратах при инвентаризации, через месяц.
--
-- Значения (пишет rpc/treatment-orders.js):
--   ''          нечего было делать: отметка не 'given', либо ещё не обработана;
--   'ok'        списано и начислено;
--   'none'      списывать нечего по правилу: препарат ПАЦИЕНТА (source='patient')
--               или назначение без ссылки на склад (уход, режим, процедура);
--   'skipped'   количество не выведено из дозы — НЕ СПИСАНО, ждёт человека;
--   'short'     склад отказал (нет остатка, позиция погашена) — НЕ СПИСАНО;
--   'reversed'  отметку сняли, склад и счёт возвращены.
--
-- CHECK на эти значения нет намеренно: SQLite не умеет ADD CONSTRAINT, а
-- пересборка таблицы ради списка из шести слов — ровно тот риск, которого эта
-- миграция избегает. Список держит сервер, и он же единственный, кто сюда
-- пишет (write.roles = [] в schema-registry.js).
ALTER TABLE treatment_administrations ADD COLUMN stock_status TEXT NOT NULL DEFAULT '';

-- Человеческая причина: «не списано: не удалось определить количество (доза
-- «1 г», склад в «шт»)». Её показывает экран и читает старшая медсестра —
-- поэтому текст, а не код: код пришлось бы переводить обратно в ту же фразу.
ALTER TABLE treatment_administrations ADD COLUMN stock_note TEXT NOT NULL DEFAULT '';

-- ─── 3. СЧЁТ НЕСПИСАННЫХ ────────────────────────────────────────────────────
--
-- «Их надо считать» — единственная причина этого индекса. Частичный: 'ok' и
-- 'none' — это норма и их подавляющее большинство, а разбирают всегда только
-- две группы, и обе редкие.
CREATE INDEX idx_treatment_admin_stock_issue
  ON treatment_administrations(order_id, due_date)
  WHERE stock_status IN ('skipped','short');
