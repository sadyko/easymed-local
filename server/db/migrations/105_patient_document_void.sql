-- 105_patient_document_void.sql — PATIENT_FILE_ATTACH_V1.
--
-- «Документы» карты пациента получили настоящее хранилище файлов (загрузка,
-- ограничения, права, резервная копия). Здесь — ЕДИНСТВЕННОЕ, что для этого
-- нужно от базы: документ пациента перестаёт УДАЛЯТЬСЯ и начинает ОТЗЫВАТЬСЯ.
--
-- ПОЧЕМУ ОТЗЫВ, А НЕ УДАЛЕНИЕ. Правило продукта уже существует, его не
-- изобретают заново: отметку медсестры не стирают, а гасят voided_at/voided_by/
-- void_reason (093_treatment_orders.sql), счёт не стирают, а аннулируют
-- (status 'void'), результат анализа не стирают вовсе. Скан направления —
-- такая же клиническая запись: если регистратор приложил чужой файл, клинике
-- нужно, чтобы он перестал показываться, И нужно, чтобы осталось видно, что он
-- был, кто его приложил и кто убрал. Строку, которой больше нет, объяснить
-- пациенту (или проверяющему) нечем.
--
-- ФАЙЛ ПРИ ОТЗЫВЕ ОСТАЁТСЯ НА ДИСКЕ. Отозванный документ не открывается через
-- карту (сервер отказывает), но байты никуда не деваются: отзыв — это решение
-- клиники, а не команда «уничтожить доказательство». Место возвращает только
-- «Сброс к заводским настройкам», который и так удаляет storage/ целиком.
--
-- Ничего не отнимает: у всех существующих строк три новых поля = NULL, то есть
-- «действует», и карта показывает их ровно как вчера.

ALTER TABLE visit_documents ADD COLUMN voided_at TEXT;
ALTER TABLE visit_documents ADD COLUMN voided_by INTEGER REFERENCES users(id);
ALTER TABLE visit_documents ADD COLUMN void_reason TEXT;

-- Карта пациента читает документы по patient_id и почти всегда — только
-- действующие. Частичный индекс держит этот список коротким и после того, как
-- за годы накопятся отозванные.
CREATE INDEX IF NOT EXISTS idx_visit_documents_live
  ON visit_documents(patient_id, created_at)
  WHERE voided_at IS NULL;
