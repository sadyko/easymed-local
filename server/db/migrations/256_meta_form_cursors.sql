--
-- Ревью выпуска 3.18.0: опрос заявок Meta (server/services/meta/poller.js)
-- держал ОДИН курсор since_ts на все формы страницы и двигал его на самую
-- свежую заявку прохода. Форма, у которой заявки старше этой отметки (форма,
-- созданная после подключения, или форма, чей проход отказал), теряла их
-- навсегда: следующий запрос просил «новее курсора», а курсор уже ушёл вперёд
-- по чужой форме.
--
-- Теперь у каждой формы своя отметка — время её самой свежей подшитой заявки;
-- опрос просит «новее отметки минус 10 минут» (перекрытие: заявка, которую
-- Meta показала с опозданием, не проскочит; повтор бесплатен — leadgen_id в
-- журнале уникален). Форма без своей отметки (новая, или ещё без заявок)
-- читается от meta_settings.since_ts, который больше не двигается опросом и
-- значит «забирать с этого момента» (включение или «за последние N дней»).
--
-- Строки заводит и двигает только опрос; «Удалить токен» их стирает.
-- Только CREATE TABLE: прежние таблицы не тронуты.
CREATE TABLE meta_form_cursors (
  form_id    TEXT    PRIMARY KEY,
  since_ts   INTEGER NOT NULL DEFAULT 0,
  updated_at TEXT    NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ', 'now'))
);
