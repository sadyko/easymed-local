-- Решение владельца (ревью, 25.09): выдать по умолчанию.
--
-- ЧТО БЫЛО. Отчёт колл-центра (callcenter_report) показывает оператору ЕГО
-- цифры — свою строку в «Операторах» и свои/ничьи заявки (CRM_HEAD_MERGE_TAGS_V1).
-- Но с ROLE_REPORTS_SETTINGS_V1 отчёт стал группой «Колл-центр» раздела
-- «Отчёты», и сервер пускает к ненастроенной группе только того, кому выдан
-- раздел «Отчёты» (reports-hub). Штатному оператору его не выдавала ни одна
-- миграция (059/141) — значит, отчёт, написанный для него, был ему недоступен.
--
-- ЧТО ТЕПЕРЬ. Роли `callcenter` и своим ролям клиники на её основе выдаётся
-- ОДНА группа — `reports.callcenter: view`. Остальные группы отчётов у неё
-- ненастроены и живут прежним правилом (reports-hub не выдан — не видны), так
-- что хаб отчётов откроется оператору с одной плиткой «Колл-центр».
--
-- ИДИОМА — 141/144: json_patch дополняет словарь grants (создаёт его, если
-- нет), не трогая чужих ключей; NOT LIKE по имени ключа — повторный накат и
-- клиника, уже настроившая этот ключ руками (в том числе в «Нет»), ничего не
-- получают заново. Своя роль без строки прав не трогается: она работает по
-- основе и получит ключ через неё.
UPDATE role_permissions SET permissions = json_patch(permissions, '{"grants":{"reports.callcenter":"view"}}')
 WHERE json_valid(permissions)
   AND permissions NOT LIKE '%"reports.callcenter"%'
   AND (role = 'callcenter'
        OR role IN (SELECT code FROM custom_roles WHERE base_role = 'callcenter'));
