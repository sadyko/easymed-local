-- У документа истории болезни пять колонок текста (жалобы, объективно,
-- диагноз, план, дополнительно) и НИ ОДНОГО места под то, чего в этих пяти
-- нет: свой раздел с именем или без. В кабинете врача такие разделы есть
-- давно — приём хранится одним JSON, и добавить в него поле ничего не стоит.
-- У истории болезни поля колоночные, и это правильно: по ним ищут, считают
-- сроки и собирают историю. Значит нужна ОДНА колонка сверх — для того, что
-- заведомо не колонка.
--
-- ЧТО В НЕЙ ЛЕЖИТ. JSON вида
--   {"titles": {"complaints": "Жалобы пациента"},
--    "extra":  [{"title": "Осмотр стопы", "html": "<p>…</p>"}]}
-- где titles — переименованные подписи ЭТОГО документа, extra — свои разделы
-- по порядку. Пусто — колонка NULL, и старые записи ничем не отличаются от
-- новых.
--
-- ПОЧЕМУ ИМЯ РАЗДЕЛА ХРАНИТСЯ С ЗАПИСЬЮ, А НЕ ТОЛЬКО В НАБОРЕ. Документ
-- печатают через год. Он обязан читаться так, как его писали: клиника,
-- переименовавшая раздел в марте, не должна переписать февральские документы.
--
-- Только ADD COLUMN — пересборок нет (урок 1.1.0).
