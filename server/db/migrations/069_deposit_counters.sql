-- DEPOSIT_V1 — собственная нумерация депозитов: DEP-<ГГ>-<00001>.
--
-- Депозит — это отдельный документ, а не счёт: денег за услугу по нему ещё не
-- взяли, выручкой он не становится, и в ряду INV-… ему делать нечего. Отдельный
-- префикс означает, что номер депозита нельзя спутать с номером счёта ни в
-- поиске, ни в бумагах.
--
-- Счётчик устроен ровно как invoice_counters (миграция 005) и по той же
-- причине: COUNT(*)+1 переиспользует номер после удаления строки. Инкремент
-- идёт в ОДНОЙ транзакции со вставкой депозита, поэтому откат вставки
-- откатывает и номер — ни дыр от неудачных попыток, ни повторов от удачных.
CREATE TABLE deposit_counters (
  year     TEXT PRIMARY KEY,
  next_seq INTEGER NOT NULL DEFAULT 1
);

