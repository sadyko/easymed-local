-- 095_admission_reviews.sql — INPATIENT_REVIEW_V1 (Задача 3 плана
-- docs/plans/2026-09-04-inpatient-workflow.md): у ОСМОТРА появляется место,
-- где он живёт.
--
-- ─── ЗАЧЕМ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ ПОЛЕ В `admissions` ───────────────────────
--
-- Миграция 091 дала маршруту состояние 'examined' и подпись шага
-- (`examined_at`, `examined_by`) — то есть ФАКТ осмотра. Самого осмотра там
-- нет: ни жалоб, ни объективного статуса, ни диагноза, ни плана лечения. Пока
-- его нет, «первичный осмотр главного врача» — это галочка, а не документ, и
-- ответить на вопрос «что именно врач увидел у пациента 4 сентября» нечем.
--
-- Полем в `admissions` этого не решить, и причина не в размере текста:
--
--   • осмотров у одной госпитализации МНОГО. Первичный — один, а обходов
--     столько, сколько суток пациент лежит (Задача 5), плюс выписной эпикриз
--     (Задача 8). Одна колонка на все — это либо потеря всех, кроме
--     последнего, либо склейка их в одну строку, из которой уже не выделить
--     ни автора, ни дату;
--   • осмотр ИСПРАВЛЯЮТ. Врач ошибся в диагнозе и переписал — в истории
--     болезни обязаны остаться ОБЕ записи (см. `superseded_by` ниже). UPDATE
--     по колонке в `admissions` стирает первую бесследно, и именно этого
--     медицинский документ не прощает;
--   • черновик — не документ. Осмотр набирают в кабинете и публикуют, когда он
--     дописан; до публикации он никого никуда не двигает. Колонка в
--     `admissions` не умеет быть «наполовину сохранённой», а `published_at
--     IS NULL` — умеет.
--
-- ─── ПОЧЕМУ `author_role`, А НЕ ТОЛЬКО `author_id` ──────────────────────────
--
-- Референс (Aurora) записывает у осмотра ОДНО ИМЯ и больше ничего. Этого не
-- хватает ровно в том месте, ради которого вся Задача 3 и делается: право
-- провести первичный осмотр есть у главного врача, и главный врач — это
-- НАДСТРОЙКА (extra_roles, миграция 091), а не профессия. Один и тот же
-- человек утром ведёт своих пациентов как врач, а днём подписывает первичные
-- осмотры как главный врач. Через год у него могут отобрать надстройку, и
-- тогда по `users.extra_roles` уже не сказать, в каком качестве он подписал
-- запись, — а разбор («кто пустил пациента в лечение без осмотра?») приходит
-- именно за этим. Поэтому роль, КОТОРОЙ ВОСПОЛЬЗОВАЛИСЬ, пишется в саму
-- запись, в момент записи.
--
-- ─── ЧЕГО ЗДЕСЬ НЕТ ─────────────────────────────────────────────────────────
--
-- Справочника МКБ. `diagnosis` — свободный текст: подбор кода МКБ-10 в
-- стационаре — отдельная работа (в базе уже есть свой справочник ICD, и
-- связать его с осмотром можно позже, добавив колонку). Заводить сейчас FK на
-- код значило бы запретить врачу написать диагноз, которого нет в загруженном
-- справочнике, — то есть остановить осмотр из-за справочника.
--
-- ─── СИНХРОНИЗАЦИЯ ФИЛИАЛОВ ─────────────────────────────────────────────────
--
-- Новая таблица в SHIPPED (branch-sync/journal.js) НЕ ВХОДИТ, как и сама
-- `admissions`: у неё нет ни uid, ни sync_origin, ни триггеров журнала, и
-- создание таблицы не пишет в `sync_journal` ни строки. Стационар — работа
-- одного здания.
CREATE TABLE admission_reviews (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  admission_id INTEGER NOT NULL REFERENCES admissions(id),

  -- Род записи. 'primary' — первичный осмотр (двигает маршрут: 'admitted' →
  -- 'examined'); 'round' — дневниковая запись обхода лечащего врача;
  -- 'discharge' — выписной эпикриз (его пишет Задача 8; место под него
  -- объявлено здесь, чтобы вторую таблицу под тот же документ потом не заводить).
  kind TEXT NOT NULL DEFAULT 'primary' CHECK (kind IN ('primary','round','discharge')),

  -- Четыре части врачебной записи по отдельности, а не одним полем. Разделение
  -- не косметическое: жалобы и объективный статус читает медсестра, диагноз
  -- уходит в счёт и в выписку, план лечения превращается в лист назначений
  -- (Задача 4). Склеенные в один текст, они перестают быть данными.
  complaints TEXT NOT NULL DEFAULT '',
  objective  TEXT NOT NULL DEFAULT '',
  diagnosis  TEXT NOT NULL DEFAULT '',
  plan       TEXT NOT NULL DEFAULT '',
  -- Всё остальное, что врач счёл нужным написать: анамнез, сопутствующее,
  -- обоснование. Без этого поля врач начнёт дописывать это в `plan`, и план
  -- лечения перестанет быть планом.
  body       TEXT NOT NULL DEFAULT '',

  author_id INTEGER REFERENCES users(id),
  -- Роль, КОТОРОЙ ВОСПОЛЬЗОВАЛИСЬ ('head_doctor' / 'admin' / 'doctor') — см.
  -- шапку. Пустая строка вместо NULL по образцу `department` (092): «не
  -- записали роль» и «роли не было» здесь не различают.
  author_role TEXT NOT NULL DEFAULT '',

  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now')),
  updated_at TEXT,
  -- NULL = ЧЕРНОВИК. Черновик — это ещё не осмотр: он не двигает маршрут, его
  -- не видит отделение и его правит автор. Публикация — необратимое событие со
  -- своим временем, а не флаг: «когда осмотр стал документом» — вопрос, на
  -- который история болезни обязана отвечать.
  published_at TEXT,

  -- ИСПРАВЛЕНИЕ НЕ СТИРАЕТ ИСХОДНИК. Опубликованный осмотр не переписывается
  -- никогда; врач публикует НОВУЮ запись, а прежняя получает сюда её id и
  -- уходит в историю целиком — с прежним текстом, прежним автором и прежним
  -- временем. Это ровно то правило, по которому в этой базе живут отменённые
  -- назначения (093) и отменённые заявки (091): медицинский документ не
  -- удаляют, его закрывают следующим.
  superseded_by INTEGER REFERENCES admission_reviews(id),
  CHECK (superseded_by IS NULL OR superseded_by <> id)
);

-- Один индекс на три вопроса, которые задают этой таблице:
--   «есть ли у этой госпитализации ОПУБЛИКОВАННЫЙ первичный осмотр» (гейт
--   маршрута — самый частый), «покажи все записи этой госпитализации по
--   порядку» (карточка) и «покажи обходы» (лист врача, Задача 5).
CREATE INDEX idx_admission_reviews_lookup
  ON admission_reviews (admission_id, kind, published_at);
