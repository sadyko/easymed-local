-- PERF_PATIENTS_INDEX_V1 — реестр на 70 032 пациента сканировался целиком.
--
-- Замеры на живой базе (EXPLAIN QUERY PLAN + время):
--   список пациентов, сортировка по умолчанию  — 83–103 мс   SCAN + TEMP B-TREE
--   вкладка «Активные» (registration_date >= …) — 75 мс      SCAN
--   значок в меню: COUNT(*) WHERE active = 1    — 29 мс       SCAN, каждые 20 с
--   та же таблица, сортировка А-Я по last_name  — 0.5 мс      INDEX
--   та же таблица, сортировка по mrn            — 0.2 мс      INDEX
--
-- Последние две строки — доказательство: дело не в размере таблицы, а в том,
-- что у колонок, по которым реестр сортируют И фильтруют ПО УМОЛЧАНИЮ, индекса
-- не было, а у остальных — был.
--
-- Почему это ощущается как «система тормозит», а не «список чуть медленный»:
-- better-sqlite3 работает СИНХРОННО, процесс один. Эти 83 мс — не «ждёт тот, кто
-- открыл список», а «ждут ВСЕ»: пока идёт скан, сервер не отвечает никому.
--
-- Порядок колонок повторяет ORDER BY реестра (registration_date DESC,
-- created_at DESC) — иначе SQLite возьмёт индекс для поиска, но всё равно
-- построит временное B-дерево для сортировки, и половина выигрыша пропадёт.
CREATE INDEX IF NOT EXISTS idx_patients_reg_created
  ON patients(registration_date DESC, created_at DESC);

-- Значок «Пациенты» в левом меню опрашивается каждые 20 секунд КАЖДОЙ открытой
-- вкладкой. Частичный индекс — только по активным: он меньше самого дешёвого
-- полного и отвечает ровно на тот вопрос, который задаёт счётчик.
CREATE INDEX IF NOT EXISTS idx_patients_active
  ON patients(active) WHERE active = 1;
