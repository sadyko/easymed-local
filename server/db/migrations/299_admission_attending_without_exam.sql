-- Переключатель «Лечащий врач — только после осмотра» (inpatient_settings,
-- миграция 298) решает, можно ли СЕЙЧАС назначить лечащего прямо с койки. Но что
-- делать с осмотром, который пишут уже во время лечения, — вопрос о прошлом ЭТОЙ
-- госпитализации, а не о сегодняшнем положении переключателя. Клиника выключила
-- переключатель, назначила лечащего с койки, включила обратно — и пациент застревал:
-- «Первичный осмотр» отказывал словами «уже закрыт назначением лечащего врача»
-- (его не было), чек-лист держал осмотр просроченным навсегда, а «Осмотр приёмного
-- врача» переставал записывать, кто осмотрел.
--
-- 1 — лечащего назначили прямо с койки (admission_set_attending, путь без осмотра);
-- 0 — обычный путь. Старые строки — 0: и те, что 091 перенесла «лечащимися» с пустыми
-- examined_*, ведут себя ровно как до этой правки.
--
-- Только ADD COLUMN — пересборок нет (урок 1.1.0).
ALTER TABLE admissions ADD COLUMN attending_without_exam INTEGER NOT NULL DEFAULT 0
  CHECK (attending_without_exam IN (0, 1));
