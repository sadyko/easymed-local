-- LAB_PANEL_DEDUP_V1 (мигр. 271, 2026-11-03, выпуск 3.21.0) — КОПИИ ПОКАЗАТЕЛЕЙ ПАНЕЛИ.
--
-- Клиника: в панели «Анализ гинекологического мазка» каждый показатель лежал
-- трижды. Лист «Внести результаты» показывал каждую копию отдельной строкой,
-- сохранённое значение вставало во все три, правка первых двух терялась, а на
-- бланк попадало только то, что успели сохранить. Копии рождались двумя путями:
--   • два сохранения панели, шедшие одновременно (повторное «Сохранить панель»
--     после перерисовки редактора, вторая вкладка): каждое удаляло только
--     прочитанные им прежние строки (исправлено: rpc/lab-panels.js — одна
--     транзакция);
--   • синхронизация справочника в филиале: каждое пересохранение панели в
--     главном здании добавляло филиалу ещё одну копию (исправлено:
--     branch-sync/catalogue.js убирает строки, которых у главного больше нет).
-- Исправления новых копий не делают; эта миграция убирает уже сделанные — в
-- КАЖДОМ здании (главном и филиалах), раз и навсегда.
--
-- Что считается копией: строки ОДНОЙ панели с тем же «Разделом бланка» и тем
-- же именем (без пробелов по краям) и с одинаковой настройкой — код, единицы,
-- тип, варианты ответа, знаки после запятой, нормы (общая, М, Ж, текстом,
-- именованные диапазоны), поле анализатора и его подтверждение, «активна».
-- Остаётся САМАЯ НОВАЯ строка (больший id): в филиале именно на неё указывает
-- соответствие строке главного здания, и в ней последняя правка оттуда.
-- Отметка «подтверждено для прибора» и её эпоха не сравниваются: их ставит
-- триггер мигр. 233, и у новой строки они последние.
--
-- Сравнение — trim(), а не lower(): lower() SQLite складывает только латиницу,
-- и «Лейкоциты» с «лейкоциты» он не уравнял бы, а латинские «WBC» и «wbc» —
-- уравнял бы. Копии и так совпадают байт в байт.
-- Ревью L1: trim() SQLite без второго аргумента снимает только ПРОБЕЛЫ, а
-- String.prototype.trim() листа ввода и lab_panel_save — любой пробельный
-- символ (табуляция, перевод строки, неразрывный пробел U+00A0 …). Копия с
-- табуляцией или NBSP в конце имени пережила бы миграцию, лист показал бы её
-- одной строкой, а «Сохранить панель» назвал бы повтор. Поэтому trim здесь —
-- с тем же набором, что у JS: char(9…13, 32, 160, 5760, 8192…8202, 8232,
-- 8233, 8239, 8287, 12288, 65279).
--
-- Строки, отличающиеся хоть чем-то из настройки (кто-то поправил единицы у
-- одной копии), остаются обе: что из них верно, решает человек. Лист ввода
-- показывает их одной строкой, а «Сохранить панель» без исправления не
-- примет — назовёт повтор.
--
-- Результаты анализов (lab_results) НЕ ТРОГАЮТСЯ: это записи о пациентах, на
-- строки панели они не ссылаются (только услуга визита и имя показателя), а
-- бланк печатает по одной строке на показатель (LAB_PANEL_DEDUP_V1,
-- laboratory.js). Значения, которые не были сохранены до обновления,
-- миграция вернуть не может — лаборатория вносит их заново.
--
-- Повторный запуск ничего не меняет: копий после первого уже нет.
DELETE FROM lab_panel_analytes WHERE id IN (
  SELECT a.id FROM lab_panel_analytes a
    JOIN lab_panel_analytes b
      ON b.panel_id IS a.panel_id AND b.id > a.id
     AND trim(COALESCE(b.group_label, ''), char(9, 10, 11, 12, 13, 32, 160, 5760, 8192, 8193, 8194, 8195, 8196, 8197, 8198, 8199, 8200, 8201, 8202, 8232, 8233, 8239, 8287, 12288, 65279))
       = trim(COALESCE(a.group_label, ''), char(9, 10, 11, 12, 13, 32, 160, 5760, 8192, 8193, 8194, 8195, 8196, 8197, 8198, 8199, 8200, 8201, 8202, 8232, 8233, 8239, 8287, 12288, 65279))
     AND trim(COALESCE(b.name, ''), char(9, 10, 11, 12, 13, 32, 160, 5760, 8192, 8193, 8194, 8195, 8196, 8197, 8198, 8199, 8200, 8201, 8202, 8232, 8233, 8239, 8287, 12288, 65279))
       = trim(COALESCE(a.name, ''), char(9, 10, 11, 12, 13, 32, 160, 5760, 8192, 8193, 8194, 8195, 8196, 8197, 8198, 8199, 8200, 8201, 8202, 8232, 8233, 8239, 8287, 12288, 65279))
     AND b.code IS a.code
     AND b.unit IS a.unit
     AND b.value_type IS a.value_type
     AND b.value_options IS a.value_options
     AND b.decimals IS a.decimals
     AND b.ref_low IS a.ref_low AND b.ref_high IS a.ref_high AND b.ref_text IS a.ref_text
     AND b.ref_low_m IS a.ref_low_m AND b.ref_high_m IS a.ref_high_m
     AND b.ref_low_f IS a.ref_low_f AND b.ref_high_f IS a.ref_high_f
     AND b.ref_ranges IS a.ref_ranges
     AND b.device_code IS a.device_code
     AND b.device_code_confirmed IS a.device_code_confirmed
     AND b.active IS a.active
);

-- Соответствия филиала «строка главного здания → наша строка», чья наша
-- строка удалена (выше или раньше, сохранением панели в этом здании). Их
-- больше никто не спросит, а занятыми они держали бы место при усыновлении.
DELETE FROM branch_sync_map
 WHERE table_name = 'lab_panel_analytes'
   AND local_id NOT IN (SELECT id FROM lab_panel_analytes);
