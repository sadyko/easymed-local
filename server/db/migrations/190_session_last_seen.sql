-- 190_session_last_seen.sql — V3120_FIX (M10): простой сессии.
--
-- Сессия жила 12 часов от входа, работает за ней кто-то или нет: компьютер
-- регистратуры, оставленный открытым в обед, оставался открытым до вечера.
-- Теперь у сессии есть «последнее обращение», и без работы дольше предела
-- (SESSION_IDLE_HOURS, по умолчанию 4 часа) она заканчивается. 12 часов от
-- входа остаются верхней границей.
--
-- NULL у существующих сессий читается как «обращение = вход» (created_at):
-- никого не выкидывает в момент обновления, если он работает.
ALTER TABLE sessions ADD COLUMN last_seen_at TEXT;
