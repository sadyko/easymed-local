--
-- Двойной щелчок «Принять оплату», повторная отправка после обрыва сети или
-- обновление страницы проводили оплату (возврат, продажу карты, депозит,
-- внесение/изъятие) второй раз: частичная оплата и сплит принимались дважды,
-- пока хватало остатка, а возврат выдавал деньги дважды, пока хватало платежа.
--
-- Экран присылает случайный idempotency_key вместе с формой (как выдача со
-- склада, stock_issue_receipts, миграция 138). Сервер пишет квитанцию в ТОЙ ЖЕ
-- транзакции, что деньги (domain/money.js idemRemember), и на повтор с тем же
-- ключом отвечает сохранённым ответом, ничего не двигая. Ключ, занятый другой
-- операцией, — отказ, а не чужой ответ.
--
-- Таблица между зданиями не ездит: повтор приходит в то же здание, куда ушла
-- первая попытка.
CREATE TABLE money_idempotency (
  key        TEXT PRIMARY KEY,
  rpc        TEXT NOT NULL,
  user_id    INTEGER,
  result     TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now'))
);
