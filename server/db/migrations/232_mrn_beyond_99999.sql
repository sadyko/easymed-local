-- MRN_BEYOND_99999_V1 (2026-09-30) — номер карты после 99 999.
--
-- ЧТО БЫЛО. Триггер patients_mrn_autogen (080) брал номер как ПОСЛЕДНИЕ ПЯТЬ
-- знаков карты — MAX(CAST(substr(mrn, -5) AS INTEGER)) + 1 среди карт года,
-- год узнавал окном от конца — substr(mrn, -9, 4) = '-ГГ-', и дополнял нулями
-- через substr('00000' || n, -5). Индекс idx_patients_mrn_seq (211) — по тем же
-- выражениям. Сотая тысяча карт за год давала «00000»: после A-26-99999 шла
-- A-26-00000, следующая — СНОВА 00000, и каждая новая карта упиралась в
-- UNIQUE(mrn). Регистрация и импорт отказывали. Доказано на копии dev: 70 120
-- карт 2026 года плюс импорт 44 606 пациентов — легли 29 806, дальше 148 порций
-- получили 409 «значение patients.mrn должно быть уникальным».
--
-- Чинить только нули мало: окно от конца ломается на шести цифрах само. У
-- 'A-26-100000' substr(mrn, -9, 4) = '6-10' — карта выпадает из своего года, и
-- номера пошли бы по второму кругу с 00001 при живых картах того же года.
--
-- ПРАВИЛО ТЕПЕРЬ (решение владельца 2026-09-30, «Yes, fix it»):
--   • формат прежний: <буква>-<ГГ>-<номер>;
--   • до 99 999 — пять цифр с нулями, как было: A-26-00042;
--   • дальше просто больше цифр: A-26-99999 → A-26-100000 → A-26-100001;
--   • номер читается ЦЕЛИКОМ после второго дефиса, год — по месту сразу после
--     первого дефиса. Позиции — от дефиса, а не от конца строки: у номера
--     переменной длины «конца» больше нет.
--
-- БУКВА ФИЛИАЛА бывает не одна: branch_identity.letter — '[A-Z]', один или
-- больше знаков (CHECK из 080), letters.js выдаёт A..Z, AA.. до восьми знаков.
-- Дефиса в букве не бывает никогда, поэтому первый дефис — всегда конец буквы:
--   instr(mrn, '-')                  → где кончается буква;
--   substr(mrn, instr(mrn,'-'), 4)   → '-ГГ-' для любой длины буквы;
--   substr(mrn, instr(mrn,'-') + 4)  → номер целиком, сколько бы в нём ни было цифр.
-- 'A-26-00001', 'AB-26-100000', 'ABCDEFGH-26-7', 'РУЧН-26-00012' — все читаются
-- одинаково. Строка без дефиса даёт instr = 0 и окно из трёх знаков, которое
-- '-ГГ-' (четыре) не равно никогда, — в счёт она не идёт, как и раньше.
--
-- СЧЁТ ПО ВСЕМ БУКВАМ ГОДА — прежний, и это не недосмотр (см. 080): legacy
-- 'P-26-…' и новые 'A-26-…' — одна серия (переход P→A продолжает нумерацию),
-- карты соседних зданий ('B-26-…') и номера, введённые руками или импортом,
-- тоже в счёте. MAX + 1 всегда за любым из них — поэтому выданный номер не
-- совпадёт ни с одной уже существующей картой.
--
-- ЧЕСТНО О ЦЕНЕ ЦЕЛОГО НОМЕРА. Опечатка на 6–9 цифр в номере карты ЭТОГО года
-- ('P-26-701280' вместо 'P-26-70128', руками или импортом) теперь поднимает
-- серию: следующая карта получит 701281, и номера пойдут оттуда. При 080 такая
-- карта была счётчику не видна (он читал последние пять знаков). Уникальность
-- держится и так — номера только прыгают; чинится это исправлением номера
-- ошибочной карты, уже выданные номера остаются.
--
-- СЧИТАЮТСЯ ТОЛЬКО 0…999 999 999 (не больше девяти цифр). Десять и больше —
-- мимо счёта: одна опечатка ('P-26-7012800000') иначе угнала бы серию к
-- десятизначным номерам, а 20 цифр переполнили бы целое SQLite (MAX + 1 стал бы
-- дробным). Отрицательные ('P-26--5') — тоже мимо. BETWEEN по второму выражению
-- индекса — тот же один спуск (SeekLE + Prev).
--
-- ПОТОЛОК: НОМЕР, КОТОРОГО ТРИГГЕР НЕ СЧИТАЕТ, НЕ ВЫДАЁТСЯ НИКОГДА. Если в
-- счёте уже 999 999 999, следующим был бы 1 000 000 000 — вне счёта: триггер
-- выдал бы его, не увидел и выдал снова, и каждая регистрация до конца года
-- падала бы на UNIQUE, ничего не объясняя. Дойти туда — не «миллиард
-- регистраций»: хватает ОДНОЙ импортированной заглушки 'P-26-999999999'. Поэтому
-- на потолке триггер отказывает сам и называет причину (текст RAISE ниже; экран
-- получает его как есть, 409, перевод — в словаре). Чинится исправлением номера
-- той карты. Окно импорта такие номера (999 999 000 — 999 999 999) и не
-- пропускает: строка отказывается с причиной (section-import-export.js).
--
-- ИНДЕКС — ровно по двум новым выражениям, как 211 был по старым: SQLite
-- сравнивает выражения индекса и запроса по структуре и отвечает на MAX одним
-- спуском по дереву. Имя прежнее. DROP обязателен: CREATE INDEX IF NOT EXISTS с
-- тем же именем молча оставил бы СТАРОЕ определение. Постройка — один проход по
-- patients (на копии dev, 70 120 карт, — десятки миллисекунд). Тот же индекс
-- служит сортировке «MRN» в реестре пациентов: год, номер целиком, потом сам
-- mrn (schema-registry.js, patients.read.order), а не текст, где 'A-26-100000'
-- стоял между 'A-26-10000' и 'A-26-10001'.
--
-- ПОРЯДОК AFTER-ТРИГГЕРОВ СОХРАНЁН, и поэтому пересоздаются ещё два. SQLite
-- запускает AFTER-триггеры таблицы в обратном порядке создания (шапка 084):
-- сейчас на вставке сначала patients_journal_ins, потом patients_uid_autogen,
-- последним patients_mrn_autogen. Пересоздай один только номер — он станет
-- ПЕРВЫМ, его UPDATE пройдёт до появления uid, и журнал обмена у нового
-- пациента изменится: пропадут запись 'mrn' и авторство колонки mrn
-- (sync_authored). Замерено: на 231 вставка даёт ['*', 'mrn'] и авторство
-- ['mrn'], с одним пересозданным триггером — ['*'] и []. Поэтому все три
-- снимаются и создаются заново в ПРЕЖНЕМ порядке, а два соседних — ДОСЛОВНО
-- текстом из 083 и 084 (не по памяти — так требует шапка 084).
-- patients_journal_upd / _del и patients_minted_del (090) срабатывают на других
-- событиях и не трогаются.
--
-- ЧЕГО ЗДЕСЬ НЕТ, НАМЕРЕННО:
--   • ни одной UPDATE: существующие номера не меняются никогда — они напечатаны
--     на картах, в журналах и на чеках. Карта 'A-26-00000', которую клиника
--     могла получить от старого триггера, остаётся как есть;
--   • перестройки таблицы patients — только DROP / CREATE триггеров и индекса.
--     Урок 1.1.0: перестройка таблицы со ссылками внутри migrate() роняет запуск
--     клиники; а по шапке 084 она к тому же разослала бы всю базу пациентов
--     соседям заново;
--   • записей в журнал обмена: DDL строк не трогает, соседям не уезжает ничего.
--
-- ПОВТОРНЫЙ НАКАТ безвреден: migrate() помнит имя файла, а сам текст — DROP IF
-- EXISTS / CREATE — даёт то же самое сколько угодно раз.
DROP TRIGGER IF EXISTS patients_journal_ins;
DROP TRIGGER IF EXISTS patients_uid_autogen;
DROP TRIGGER IF EXISTS patients_mrn_autogen;
DROP INDEX IF EXISTS idx_patients_mrn_seq;

CREATE INDEX IF NOT EXISTS idx_patients_mrn_seq
  ON patients(substr(mrn, instr(mrn, '-'), 4), CAST(substr(mrn, instr(mrn, '-') + 4) AS INTEGER));

CREATE TRIGGER patients_mrn_autogen AFTER INSERT ON patients
WHEN NEW.mrn IS NULL
BEGIN
  -- Нет строки branch_identity — отказ, а не карта без номера (080): mrn
  -- UNIQUE, а NULL-ов SQLite в UNIQUE допускает сколько угодно.
  SELECT RAISE(ABORT, 'branch identity missing')
   WHERE NOT EXISTS (SELECT 1 FROM branch_identity WHERE id = 1);

  -- Потолок: в счёте уже 999 999 999 — следующий номер триггер сам бы не
  -- увидел. Отказ с причиной вместо UNIQUE до конца года (см. шапку).
  SELECT RAISE(ABORT, 'Номер карты этого года уже 999 999 999 — новые номера выдать нельзя. Скорее всего, номер одной из карт введён или импортирован с ошибкой: найдите карту с таким номером и исправьте его.')
   WHERE (SELECT MAX(CAST(substr(mrn, instr(mrn, '-') + 4) AS INTEGER))
            FROM patients
           WHERE substr(mrn, instr(mrn, '-'), 4) = '-' || substr(strftime('%Y','now'), 3, 2) || '-'
             AND CAST(substr(mrn, instr(mrn, '-') + 4) AS INTEGER) BETWEEN 0 AND 999999999) >= 999999999;

  -- printf('%05d'): пять цифр с нулями до 99 999, дальше — все цифры числа
  -- (ширина в printf — минимум, а не обрезка). После проверки выше номер не
  -- больше 999 999 999 — всегда в счёте.
  UPDATE patients
     SET mrn = (SELECT letter FROM branch_identity WHERE id = 1)
               || '-' || substr(strftime('%Y','now'), 3, 2) || '-'
               || printf('%05d', (
                    SELECT COALESCE(MAX(CAST(substr(mrn, instr(mrn, '-') + 4) AS INTEGER)), 0) + 1
                      FROM patients
                     WHERE substr(mrn, instr(mrn, '-'), 4) = '-' || substr(strftime('%Y','now'), 3, 2) || '-'
                       AND CAST(substr(mrn, instr(mrn, '-') + 4) AS INTEGER) BETWEEN 0 AND 999999999
                  ))
   WHERE id = NEW.id;
END;

-- Дословно из 083_sync_uid.sql.
CREATE TRIGGER patients_uid_autogen AFTER INSERT ON patients
  WHEN NEW.uid IS NULL
  BEGIN UPDATE patients SET uid = lower(hex(randomblob(16))) WHERE id = NEW.id; END;

-- Дословно из 084_sync_journal.sql.
CREATE TRIGGER patients_journal_ins AFTER INSERT ON patients
  BEGIN INSERT INTO sync_journal (tbl, uid, op, cols)
        SELECT 'patients', uid, 'put', '*' FROM patients
         WHERE id = NEW.id AND uid IS NOT NULL; END;
