-- 082_rooms_setup.sql — ROOMS_SETUP_V1: помещения редактируются одним разделом,
-- и у кабинета появляется собственная очередь.
--
-- Локальная схема помещений была тоньше, чем предполагал общий редактор
-- настроек: rooms знала только (name, floor_id, active), wards — (name, type,
-- billing_mode, цены, color). Ни номера двери, ни типа кабинета, ни этажа у
-- палаты. Поэтому «кабинет диагностики на 2-м этаже» и «палата на 3-м» просто
-- негде было записать: раздел мог создать строку, но не мог описать её.
--
-- room_type — чем кабинет является (consultation / diagnostics / lab /
-- procedure / surgery). Значения те же, что в общем редакторе настроек, чтобы
-- один и тот же справочник читался одинаково.
--
-- queue_mode — КАК в этот кабинет становится очередь. Раньше маршрут очереди
-- знал только «лаборатория / врач / процедурная-вообще»: у процедур ключ
-- буквально 'proc:room', то есть ОДНА линия на все процедурные сразу, а
-- services.room_id, хотя и существует и подписан «Кабинет (очередь
-- диагностики)», не читался маршрутизатором ни разу. Теперь у кабинета есть
-- явный режим:
--   'none'   — очереди нет (склад, ординаторская): талон не выдаётся;
--   'room'   — очередь К КАБИНЕТУ: один номер на дверь, кто бы ни принимал
--              (УЗИ, рентген, забор) — там очередь к аппарату, а не к врачу;
--   'doctor' — очередь К ВРАЧУ, который в этом кабинете сидит: номер считается
--              в линию врача (QUEUE_ONE_DOCTOR_LINE_V1 — у врача одна линия на
--              весь день, чем бы услуга ни была).
-- По умолчанию 'none': существующие кабинеты не начинают внезапно выдавать
-- талоны после обновления — режим включается администратором осознанно.
--
-- wards.floor_id — палате нужен этаж по той же причине, что и кабинету: сестра
-- ищет палату по этажу, а раздел группирует помещения по этажам.

ALTER TABLE rooms ADD COLUMN code TEXT NOT NULL DEFAULT '';
ALTER TABLE rooms ADD COLUMN room_type TEXT NOT NULL DEFAULT 'consultation';
ALTER TABLE rooms ADD COLUMN capacity INTEGER NOT NULL DEFAULT 0;
ALTER TABLE rooms ADD COLUMN queue_mode TEXT NOT NULL DEFAULT 'none';

ALTER TABLE wards ADD COLUMN code TEXT NOT NULL DEFAULT '';
ALTER TABLE wards ADD COLUMN floor_id INTEGER REFERENCES floors(id);
