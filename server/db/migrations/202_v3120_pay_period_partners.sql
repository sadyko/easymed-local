-- Запись месяца (миграция 163) хранила только начисления СОТРУДНИКОВ: отчёт
-- «Рефералы» закрытого месяца оставался живым, и поздний возврат, смена ставки
-- источника или правка карточки меняли вознаграждение партнёра, которое уже
-- выплатили. Теперь при закрытии записываются и строки ПАРТНЁРОВ (источники
-- направлений без сотрудника): doctor_id NULL, source_id — источник. «Рефералы»
-- закрытого месяца читаются из записи, поздние изменения — строками
-- «Корректировка за …» по источнику в первом открытом месяце (reports.js,
-- referralReportLines).
--
-- pay_periods.partners = 1 — месяц закрыт уже с партнёрами и со ставками строк
-- (FROZEN_RATES). У месяцев, закрытых раньше, 0: их «Рефералы» партнёров
-- остаются живыми, как были, и корректировок партнёрам за них нет.
ALTER TABLE pay_periods ADD COLUMN partners INTEGER NOT NULL DEFAULT 0;
ALTER TABLE pay_period_lines ADD COLUMN source_id INTEGER;
CREATE INDEX IF NOT EXISTS idx_pay_period_lines_kind_date ON pay_period_lines(kind, date);
