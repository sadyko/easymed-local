-- 092_admission_order.sql — ADMISSION_ORDER_V1 (Задача 2 плана
-- docs/plans/2026-09-04-inpatient-workflow.md).
--
-- Две вещи, без которых заявку на госпитализацию нельзя ни ОФОРМИТЬ, ни
-- УВИДЕТЬ.
--
-- ---------------------------------------------------------------------------
-- 1. Две колонки на заявку: отделение и планируемая дата
-- ---------------------------------------------------------------------------
-- Миграция 091 дала маршруту состояния и подписи шагов, но не дала САМОЙ
-- заявке двух вещей, которые регистратура пишет в первую очередь:
--
--   department   отделение СЛОВАМИ. Палату (`ward_id`) в момент оформления
--                чаще всего ещё не знают — её выбирает медсестра, когда
--                действительно кладёт. А отделение («хирургия», «терапия»)
--                известно сразу, и без него заявка не сортируется: окно
--                медсестры показывает очередь размещения одним списком, и
--                «кому этот пациент» становится вопросом к регистратуре.
--   planned_at   на КОГДА госпитализация. Плановая заявка на 12 сентября и
--                экстренная «сейчас» — это разная работа отделения, а
--                `ordered_at` отвечает лишь «когда оформили».
--
-- ALTER TABLE ADD COLUMN, а не пересборка 091: SQLite добавляет колонку
-- правкой заголовка таблицы, ни одна строка не переписывается. Для филиалов
-- это тем более безразлично — `admissions` нет в SHIPPED (branch-sync/
-- journal.js), у неё нет ни триггеров журнала, ни uid.
--
-- NOT NULL DEFAULT '' у department — по образцу chief_complaint (091): «нет
-- отделения» и «не записали отделение» здесь не различают, а NULL заставлял бы
-- каждый экран помнить про COALESCE. planned_at, наоборот, NULL-able: «дата не
-- назначена» — это осмысленный ответ, и пустая строка соврала бы датой.
ALTER TABLE admissions ADD COLUMN department TEXT NOT NULL DEFAULT '';
ALTER TABLE admissions ADD COLUMN planned_at TEXT;

-- ---------------------------------------------------------------------------
-- 2. Стационар в меню у тех, кто в нём работает
-- ---------------------------------------------------------------------------
-- ЭТО ГЛАВНОЕ В ЭТОЙ МИГРАЦИИ. Раздел `beds` («Стационар и палаты», а с этой
-- задачей ещё и «Стационар» — окно медсестры) держал в role_permissions РОВНО
-- ОДИН admin. Ни медсестра, ни старшая медсестра, ни главный врач, ни
-- регистратура не видели его в меню вовсе.
--
-- До сих пор это не бросалось в глаза, потому что доска коек — экран
-- администратора клиники. Теперь бросится: маршрут госпитализации построен на
-- том, что КЛАДЁТ МЕДСЕСТРА (матрица прав, rpc/inpatient-flow.js —
-- 'ordered→admitted': nurse, senior_nurse, head_doctor, admin). Сервер бы её
-- пустил, а меню — нет: заявка появлялась бы в базе и не появлялась ни на
-- одном экране, до которого у медсестры есть доступ. Ровно тот же класс
-- ошибки, что чинила 055: право, которое некому выдать, и право, которое
-- некому прочитать, одинаково означают «функции нет».
--
-- Уровни: 'editor' — заводить и двигать, но не удалять (правило по умолчанию
-- из permissions.js: admin гейтит УДАЛЕНИЕ и выдаётся явно). Регистратура тоже
-- получает раздел: она оформляет и ОТМЕНЯЕТ заявки, а отменить то, чего не
-- видишь, нельзя.
--
-- Идиома — 055/065 дословно: json_insert в конец массива sections + json_set
-- уровня, и только там, где ключа ещё нет (повторный прогон и клиника с
-- вручную настроенной ролью не должны получить дубль).
UPDATE role_permissions
   SET permissions = json_set(
         json_insert(permissions, '$.sections[#]', 'beds'),
         '$.levels.beds', 'editor')
 WHERE role IN ('nurse', 'senior_nurse', 'head_doctor', 'registrar')
   AND json_valid(permissions)
   AND permissions NOT LIKE '%"beds"%';
