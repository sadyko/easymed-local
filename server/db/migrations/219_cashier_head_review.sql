-- CASHIER_HEAD_V1, ревью (2026-09-28) — две колонки.
--
-- 1. invoices.manual_discount + manual_base — РУЧНАЯ часть скидки счёта,
--    как её ДАЛИ: сумма (ручная скидка кассира / мастера записи, промокод —
--    без скидок пакета и без пола группы пациента) и база строк без своей
--    скидки, на которую её дали. Правка строк неоплаченного счёта считает
--    ручную часть от ЭТОЙ пары: сумма × min(база сейчас, база тогда) / база
--    тогда. Уменьшилась база (убрали, заменили на дешёвое) — скидка
--    уменьшается в той же доле (V3120_FIX FATAL-1); вернулась — скидка
--    возвращается; выросла (добавили услугу) — не больше данной суммы.
--    Прежде каждая правка ужимала ручную скидку от ПРЕДЫДУЩЕЙ правки и не
--    возвращала: 30 000 на 150 000, врач A→B→A — 130 000 к оплате вместо
--    120 000. NULL — счёт выставлен до этой версии: пара выводится один раз
--    из скидки счёта (billing.js repriceUnpaidInvoice) и записывается.
--    Колонки местные: чужой счёт здесь не правят (BRANCH_MONEY_GUARD_V1), и
--    соседу они не нужны — в перечень отправляемых колонок их не кладём.
ALTER TABLE invoices ADD COLUMN manual_discount REAL CHECK (manual_discount IS NULL OR manual_discount >= 0);
ALTER TABLE invoices ADD COLUMN manual_base REAL CHECK (manual_base IS NULL OR manual_base >= 0);

-- 2. cash_shifts.closed_by — КТО закрыл смену. Старший кассир теперь закрывает
--    чужие смены, и «закрыта» без имени перестало отвечать на вопрос, кто
--    пересчитал ящик. NULL — закрыта автоматически в полночь или до этой версии.
ALTER TABLE cash_shifts ADD COLUMN closed_by INTEGER REFERENCES users(id);
