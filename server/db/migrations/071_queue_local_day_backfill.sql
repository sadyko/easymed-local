-- QUEUE_LOCAL_DAY_V1 (часть 2) — чиним ДЕНЬ у уже выданных талонов.
--
-- Правка в issueQueueNumbers (queue.js) считает день очереди в местном времени,
-- но она действует только на НОВЫЕ талоны. Уже выданные остались с днём,
-- посчитанным по UTC: услуга «на 19 августа» без времени хранится как местная
-- полночь (2026-08-18T19:00Z в UTC+5), и прежний срез строки UTC отправлял её
-- в очередь ПРЕДЫДУЩЕГО дня. На боевой базе так оказалось 400 талонов из 743.
--
-- Что делает эта миграция и, главное, чего НЕ делает:
--
-- 1. Переносим только талоны, чей день ещё НЕ прошёл (сегодня и позже).
--    Прошедшие дни трогать незачем: в тех очередях уже никто не стоит, а
--    переписывание истории — это риск без выгоды. И он не теоретический:
--    из 400 неверных строк 202 при переносе столкнулись бы с номером, который
--    в целевом дне занят ДРУГИМ пациентом. Все они — в прошлом.
--
-- 2. НОМЕР НЕ МЕНЯЕТСЯ. Меняется только день в ключе. Талон уже на руках у
--    пациента, и перенумеровать его — значит сделать бумажку в руке неверной.
--    Проверено: для всех переносимых строк номер в целевой линии свободен —
--    те три очереди (лаборатория, аппарат, процедурный кабинет) записываются
--    без времени, поэтому уехали в предыдущий день ЦЕЛИКОМ, а правильный день
--    остался пустым.
--
-- 3. Условие NOT EXISTS ниже — не формальность, а гарантия: строка переносится
--    ТОЛЬКО если в целевой очереди этот номер свободен или принадлежит тому же
--    пациенту. Если данные за время до применения изменятся, миграция просто
--    оставит такую строку как есть, но дубликат номера не создаст никогда.
--
-- Идемпотентна: после переноса условие «день в ключе ≠ местный день» перестаёт
-- выполняться, и повторный прогон не находит ничего.

UPDATE visit_services AS t
   SET queue_key =
         substr(t.queue_key, 1, length(t.queue_key) - 10) ||
         (SELECT date(COALESCE(t.scheduled_at, v.visit_date), 'localtime')
            FROM visits v WHERE v.id = t.visit_id)
 WHERE t.queue_no IS NOT NULL
   AND t.queue_key IS NOT NULL
   AND length(t.queue_key) > 10
   -- день в ключе разошёлся с местной датой услуги…
   AND substr(t.queue_key, -10) <> (
         SELECT date(COALESCE(t.scheduled_at, v.visit_date), 'localtime')
           FROM visits v WHERE v.id = t.visit_id)
   -- …и этот день ещё впереди (или сегодня)
   AND (SELECT date(COALESCE(t.scheduled_at, v.visit_date), 'localtime')
          FROM visits v WHERE v.id = t.visit_id) >= date('now', 'localtime')
   -- …и в целевой очереди номер свободен либо уже принадлежит этому пациенту
   AND NOT EXISTS (
         SELECT 1
           FROM visit_services o
           JOIN visits ov ON ov.id = o.visit_id
          WHERE o.queue_no = t.queue_no
            AND o.id <> t.id
            AND o.queue_key =
                substr(t.queue_key, 1, length(t.queue_key) - 10) ||
                (SELECT date(COALESCE(t.scheduled_at, v.visit_date), 'localtime')
                   FROM visits v WHERE v.id = t.visit_id)
            AND ov.patient_id <> (SELECT vv.patient_id FROM visits vv WHERE vv.id = t.visit_id));
