-- НАЗНАЧАЕТ АДМИНИСТРАТОР.
--
-- Телефон Easy-Med входит в АТС прямо из браузера под внутренним номером
-- сотрудника, и для этого браузер получает ПАРОЛЬ SIP этого номера. Пароль
-- работает в любой SIP-программе и продолжает работать после увольнения. А
-- users.pbx_extension (миграция 134) сотрудник выбирает себе сам в «Моя трубка»
-- — значит, выбрав чужой номер, он получил бы чужой пароль и чужие звонки.
-- Решение владельца: «Only admin assigns» — номер для телефона назначается в
-- карточке сотрудника.
--
-- ПОЭТОМУ ОТДЕЛЬНАЯ КОЛОНКА. pbx_extension остаётся тем, чем был: трубка для
-- «Позвонить» и подпись оператора в журнале звонков. pbx_extension_assigned —
-- номер, который назначила карточка сотрудника (routes/users.js); телефон
-- Easy-Med включается, только когда выбранный номер совпадает с назначенным
-- (rpc/phone.js telephony_webrtc_me). /api/db её не читает и не пишет
-- (schema-registry.js: users закрыт на запись, колонки нет среди читаемых).
--
-- БЕЗ ПЕРЕНОСА ПРЕЖНИХ НОМЕРОВ. Уже записанные pbx_extension могли быть выбраны
-- самими сотрудниками — назначенными они не становятся. Телефон включится после
-- того, как администратор сохранит номер в карточке.
--
-- ТОЛЬКО ADD COLUMN.
ALTER TABLE users ADD COLUMN pbx_extension_assigned TEXT;
