-- Владелец (2026-09-17): «pbx should have one number. my calls for personal
-- numbers only, why i cant call from pbx in the system?»
--
-- ЧТО БЫЛО НЕ ТАК. Линий у клиники включено несколько, и программа выбирала
-- между ними САМА, по правилу «Binotel — главная линия, остальные — потом».
-- В этой клинике Binotel включён, ключи на месте, но он мёртв: последний звонок
-- 7 сентября и ошибка «offline», тогда как onlinePBX принимает по восемь сотен
-- звонков в сутки. То есть команда «позвони» уходила на линию, которой никто не
-- пользуется, и оператор видел «нет связи с телефонией».
--
-- Догадка кода тут неуместна в принципе: какая линия рабочая — знает клиника, а
-- не программа. Поэтому:
--   • dial_provider — ВЫБОР КЛИНИКИ: '' (сама), 'binotel' или 'pbx:<номер
--     подключения>'. Пустое значение — не «Binotel», а «выбери разумно»;
--   • «разумно» теперь значит «та линия, по которой клиника РЕАЛЬНО
--     разговаривает» — с самым свежим звонком в журнале. Это проверяемый факт,
--     а не старшинство.
--
-- ТОЛЬКО ADD COLUMN.
ALTER TABLE telephony_settings ADD COLUMN dial_provider TEXT;
