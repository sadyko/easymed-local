-- CRM_MULTI_SOURCE_V1 (2026-09-29) — НЕСКОЛЬКО ИСТОЧНИКОВ У ОДНОЙ ЗАЯВКИ.
--
-- Владелец: «can we setup multiple source selection in the crm» → «Both»:
-- фильтр доски по нескольким источникам и несколько источников у самой заявки
-- («пришла из Instagram и по совету знакомых»). Отчёты считают заявку в каждом
-- её источнике (docs/specs/2026-09-29-crm-multi-source-design.md).
--
-- sources — JSON-массив ключей справочника crm_sources в порядке выбора.
-- source ОСТАЁТСЯ и всегда равен ПЕРВОМУ ключу — «главный» источник: на него
-- опираются старые места и соседи, которые пишут заявку сами (звонок → заявка,
-- зеркало записи, слияние дублей). Сервер держит равенство при записи
-- (routes/db.js → services/crm/sources.js): пишут sources — он ставит
-- source = sources[0]; пишут один source — sources становится [source].
--
-- ПРАВИЛО ЧТЕНИЯ одно на экран и сервер: sources, если это непустой массив,
-- иначе [source], иначе ['other'] (public/js/admin/crm-sources.js). Поэтому
-- заявка, заведённая после миграции без sources (звонок, зеркало), читается
-- правильно и без бэкфилла.
--
-- ТОЛЬКО ADD COLUMN, без пересборки таблицы: на crm_requests ссылаются строки
-- услуг, задачи, метки и зеркало записи, и пересборка рисковала бы ими.
-- Без ограничения CHECK: проверка — на сервере, где известен справочник
-- (ключи, скрытые источники); битое значение правило чтения читает как [source].
ALTER TABLE crm_requests ADD COLUMN sources TEXT;

-- Бэкфилл: у каждой заявки с источником — массив из него одного. Заявка без
-- источника (старые данные) остаётся с пустым sources. Повторный накат ничего
-- не меняет: трогаются только строки с пустым sources.
UPDATE crm_requests SET sources = json_array(source)
 WHERE sources IS NULL AND source IS NOT NULL AND source <> '';
