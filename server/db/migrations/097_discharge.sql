-- 097_discharge.sql — TWO_STEP_DISCHARGE_V1: выписка в ДВА шага (Задача 8
-- плана docs/plans/2026-09-04-inpatient-workflow.md).
--
-- ─── ПОЧЕМУ ДВА ШАГА, А НЕ ОДНА КНОПКА ──────────────────────────────────────
--
-- Клиническая готовность и административная выписка — РАЗНЫЕ СОБЫТИЯ РАЗНЫХ
-- ЛЮДЕЙ, и в стационаре их разделяют часы, а иногда сутки. Врач утром решает,
-- что пациента можно отпускать, и подписывает исход и эпикриз. Койку при этом
-- освобождает не он: пациент ещё лежит, счёт не собран, документы не выданы,
-- а перевозка приедет к трём. Освободить койку в момент врачебного решения —
-- значит положить на неё второго пациента поверх первого.
--
-- Обратное так же неверно: старшая медсестра, оформляющая выписку, не вправе
-- ОБЪЯВИТЬ ИСХОД («выписан домой» / «переведён» / «летальный исход») — это
-- врачебное заключение, и подписывать его должен тот, кто лечил.
--
-- Отсюда две подписи в одной строке, а не одна: `discharge_requested_by`
-- (врач: «готов») и `discharged_by` (старшая медсестра: «оформлено»).
--
-- ─── ТОЛЬКО ADD COLUMN. НИ ОДНОЙ ПЕРЕСБОРКИ ────────────────────────────────
--
-- `admissions` в ЭТОМ ЖЕ выпуске уже пересобрана один раз — миграцией 091
-- (шесть состояний маршрута и десять колонок). Вторая пересборка той же
-- таблицы в том же выпуске — способ потерять строки, который выглядит
-- безобидно ровно до дня обновления: две копии CREATE TABLE расходятся на одну
-- колонку, и вторая переносит не всё. Поэтому здесь ТОЛЬКО ALTER TABLE ADD
-- COLUMN: SQLite правит заголовок таблицы, ни одна строка не переписывается,
-- открытые госпитализации живой клиники этого не замечают вовсе.
--
-- Для филиалов это тем более безразлично: `admissions` нет в SHIPPED
-- (branch-sync/journal.js), у неё нет ни uid, ни триггеров журнала. Стационар —
-- работа одного здания.
--
-- ─── ЧЕГО ЗДЕСЬ НЕТ ────────────────────────────────────────────────────────
--
-- Выписного ЭПИКРИЗА. Он уже есть: `admission_reviews` (095) с
-- kind='discharge' — та самая строка, место под которую 095 объявила заранее,
-- «чтобы вторую таблицу под тот же документ потом не заводить». Заявка на
-- выписку требует его ОПУБЛИКОВАННЫМ (published_at IS NOT NULL), и потому
-- никакой копии текста в `admissions` не нужно: копия разошлась бы с
-- оригиналом в первый же день, когда врач опубликует исправление.
--
-- Колонки `planned_discharge_at` — она есть с 091.

-- ---------------------------------------------------------------------------
-- ШАГ 1 — ЗАЯВКА НА ВЫПИСКУ (лечащий врач / главный врач)
-- ---------------------------------------------------------------------------

-- ИСХОД ГОСПИТАЛИЗАЦИИ — четыре значения, и это не вкусовщина, а то, что
-- спрашивает отчётность:
--   'home'      выписан домой;
--   'transfer'  переведён в другое учреждение (тогда обязателен адрес назначения);
--   'refuse'    отказ от лечения / самовольный уход;
--   'death'     летальный исход.
--
-- NULL — «заявка ещё не подана». Это осмысленный ответ, поэтому колонка
-- NULL-able, а не NOT NULL DEFAULT '': пустая строка соврала бы исходом там,
-- где исхода ещё нет. CHECK написан так, чтобы пропускать NULL: SQLite
-- проверяет CHECK и на существующих строках только при их следующей записи, а
-- у КАЖДОЙ существующей строки здесь NULL.
ALTER TABLE admissions ADD COLUMN discharge_outcome TEXT
  CHECK (discharge_outcome IS NULL OR discharge_outcome IN ('home','transfer','refuse','death'));

-- Куда переведён — обязателен при 'transfer' (проверяет сервер: SQLite не
-- умеет ADD CONSTRAINT, а пересборка ради одного условия — ровно тот риск,
-- которого эта миграция избегает). NOT NULL DEFAULT '' по образцу
-- chief_complaint (091): «не переводили» и «не записали куда» здесь не
-- различают.
ALTER TABLE admissions ADD COLUMN discharge_destination TEXT NOT NULL DEFAULT '';

-- Рекомендации при выписке — то, что пациент уносит с собой на руках. Живут
-- РЯДОМ с эпикризом, а не внутри него, потому что читают их разные люди в
-- разное время: эпикриз — врач следующего этапа, рекомендации — сам пациент.
ALTER TABLE admissions ADD COLUMN discharge_recommendations TEXT NOT NULL DEFAULT '';

-- Подпись первого шага: КТО признал пациента готовым и КОГДА. Без неё
-- «пациент третьи сутки в состоянии „оформляется выписка“» — вопрос без
-- адресата.
ALTER TABLE admissions ADD COLUMN discharge_requested_by INTEGER REFERENCES users(id);
ALTER TABLE admissions ADD COLUMN discharge_requested_at TEXT;

-- ---------------------------------------------------------------------------
-- ШАГ 2 — ОФОРМЛЕНИЕ ВЫПИСКИ (старшая медсестра / главный врач / админ)
-- ---------------------------------------------------------------------------

-- Подпись второго шага. `discharged_at` (091) отвечает КОГДА, эта колонка —
-- КЕМ. Раньше второго вопроса не существовало: выписка была одним движением
-- одного человека.
ALTER TABLE admissions ADD COLUMN discharged_by INTEGER REFERENCES users(id);

-- ЧЕК-ЛИСТ ВЫПИСКИ — три вещи, которые в бумажном стационаре проверяют перед
-- тем, как отпустить человека. Три отдельные колонки, а не один JSON: каждая
-- из них — самостоятельный ответ на самостоятельный вопрос проверки («лист
-- назначений закрыт?»), и вытаскивать его из текста запросом значило бы, что
-- сосчитать невыполненное нельзя.
--
-- 0/1 без CHECK: сюда пишет только сервер (write.roles = [] у `admissions` в
-- schema-registry.js), и добавлять CHECK ради двух значений — та же
-- пересборка, которой эта миграция избегает.
ALTER TABLE admissions ADD COLUMN discharge_orders_closed INTEGER NOT NULL DEFAULT 0;
ALTER TABLE admissions ADD COLUMN discharge_bill_settled INTEGER NOT NULL DEFAULT 0;
ALTER TABLE admissions ADD COLUMN discharge_docs_given INTEGER NOT NULL DEFAULT 0;

-- Что оформлявшая написала своими словами: «перевозка забрала в 15:40»,
-- «выписку отдали дочери». Экран это показывает, разбор — читает.
ALTER TABLE admissions ADD COLUMN discharge_note TEXT NOT NULL DEFAULT '';

-- ---------------------------------------------------------------------------
-- ДОЛГ ПРЕДУПРЕЖДАЕТ, А НЕ ЗАПРЕЩАЕТ
-- ---------------------------------------------------------------------------
--
-- Правило референса, и план называет его дважды: «Деньги при выписке
-- предупреждают, не блокируют». Перепутать это местами — классическая ошибка:
-- программа, которая держит человека в клинике до оплаты, не защищает деньги,
-- а создаёт скандал у поста и заставляет отделение выписывать «мимо системы»,
-- после чего база перестаёт знать, кто где лежит.
--
-- Поэтому долг НЕ ЗАПРЕЩАЕТ выписку — он требует, чтобы кто-то поставил под
-- ним свою подпись: «Долг согласован (гарантия / рассрочка)». Три колонки,
-- потому что вопросов три: согласован ли (0/1), КЕМ и КОГДА. Одного флага мало
-- ровно там, где к нему придут.
ALTER TABLE admissions ADD COLUMN discharge_debt_ack INTEGER NOT NULL DEFAULT 0;
ALTER TABLE admissions ADD COLUMN discharge_debt_ack_by INTEGER REFERENCES users(id);
ALTER TABLE admissions ADD COLUMN discharge_debt_ack_at TEXT;

-- СКОЛЬКО остался должен НА МОМЕНТ ВЫПИСКИ. Сумма считается из строк
-- (`admission_services`) и счетов (`invoices`) и потому МЕНЯЕТСЯ ПОСЛЕ выписки:
-- касса примет деньги, бухгалтерия сторнирует счёт — и пересчитанный «долг при
-- выписке» через неделю покажет не то, что видел человек, ставя подпись.
-- Подпись же ставили под КОНКРЕТНЫМ ЧИСЛОМ, и это число обязано остаться.
-- NULL = выписка ещё не оформлена (а не «долга не было»: ноль — это 0).
ALTER TABLE admissions ADD COLUMN discharge_debt_amount REAL;

-- ─── ПОЧЕМУ ЗДЕСЬ НЕТ НИ ОДНОГО ИНДЕКСА ────────────────────────────────────
--
-- Очередь старшей медсестры («кого сегодня оформлять») — это
-- `WHERE status = 'discharging' ORDER BY discharge_requested_at`, и первый
-- индекс, который хочется завести, — частичный по этому статусу. Он был здесь
-- написан и УБРАН: планировщик его не берёт. Отбор уже закрыт индексом
-- idx_admissions_status_ward (091), а сортировать в нём нечего — строк в
-- 'discharging' в отделении единицы, и временное B-дерево на пяти строках
-- дешевле лишнего индекса, который база обязана поддерживать при КАЖДОЙ записи
-- в `admissions`. Индекс, которого планировщик не выбирает, — не ускорение, а
-- расход, и молчаливый.
