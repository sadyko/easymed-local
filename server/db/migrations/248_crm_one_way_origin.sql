-- 1. released_held (O5, ревью r4 п. 4) — строка, отпущенная отменой записи, ДЕРЖАЛА визит без
--    строки визита (её поставят при приходе: счёт до прихода, I5; хирургия, снятое с продажи).
--    Ошибочную отмену отменили — такая строка снова держит визит и садится в него при приходе.
--    Строку, отпущенную потому, что её строку визита сняли в другом окне (O3), восстановление
--    не возвращает: её убрал человек.
ALTER TABLE crm_request_services ADD COLUMN released_held INTEGER NOT NULL DEFAULT 0;

-- 2. legacy_copy (O8, решение контролёра по ревью r4 п. 1, 5, 6) — исправление при установке
--    НИЧЕГО НЕ УДАЛЯЕТ. Строку, которую прежнее зеркало записи завело копией строки визита в ту же
--    секунду-две на записи регистратуры (шаг C 'match' или без привязки), оно только отмечает:
--    она остаётся строкой записи, а отмена этой записи потом снимает её ('cancelled'), а не
--    возвращает в карточку желанием — иначе копия стала бы вторым желанием той же услуги.
--    Решает только правило 0–2 с; строка записи колл-центра (R2) и желание оператора — не копии.
ALTER TABLE crm_request_services ADD COLUMN legacy_copy INTEGER NOT NULL DEFAULT 0;
