-- Владелец (2026-11-08): «discount not applied to the partners share — full price,
-- always», и следом — «с дня обновления»: счета, выставленные ДО того, как клиника
-- поставила 3.22.0, считаются по прежнему правилу (процент — от суммы строки после
-- скидки), и прошлые суммы не меняются ни на одном экране — ни в закрытых, ни в
-- открытых месяцах. Счета с момента обновления — по новому (reports.js
-- referralRewardOf / rewardBaseOf).
--
-- Момент пишется ОДИН раз — сейчас, в UTC ISO, как invoices.created_at, — и только
-- у клиники, которая обновляется: в базе уже есть счета. У новой базы (новая клиника
-- и каждый тест, который сеет счета после migrate()) строки нет — новое правило для
-- всех счетов.
--
-- Своя таблица, а не строка общих настроек: связь зданий её НЕ возит (её нет в
-- branch-sync/journal.js SHIPPED) — у каждого здания свой момент обновления, и счёт,
-- приехавший от соседа, судится моментом ЭТОЙ базы. Одна строка (id = 1).
CREATE TABLE referral_full_price_from (
  id      INTEGER PRIMARY KEY CHECK (id = 1),
  from_at TEXT NOT NULL
);

INSERT INTO referral_full_price_from (id, from_at)
SELECT 1, strftime('%Y-%m-%dT%H:%M:%SZ', 'now')
 WHERE EXISTS (SELECT 1 FROM invoices);
