-- 085_lab_scope.sql — LAB_ONE_CLINIC_V1: одна лаборатория на всю клинику.
--
-- Требование владельца, дословно: «the lab can be one single so whenever clinic
-- registrates the patient the all clinics laborants should see the list of the
-- patients and enter the data.» То есть лаборатория — служба КЛИНИКИ, а не
-- здания: пробирку из любого филиала берёт в работу тот лаборант, у кого стоит
-- анализатор.
--
-- Но это НЕ константа. У клиники с двумя настоящими лабораториями (в каждом
-- корпусе своя) общая очередь означала бы, что Юнусабад видит пробирки
-- Чиланзара и наоборот — то самое, от чего Фаза 2 закрывалась фильтром
-- `sync_origin IS NULL`. Поэтому настройка, с двумя значениями:
--
--   'clinic'   — очередь, ввод результатов и история показывают заказы ВСЕХ
--                филиалов; каждая строка подписана меткой «Филиал X»;
--   'building' — прежнее поведение: только то, что заведено здесь.
--
-- ПО УМОЛЧАНИЮ 'clinic' — так просил владелец. Для клиники в одном здании это
-- не меняет ничего вовсе: чужих строк (sync_origin <> NULL) там просто нет, и
-- запрос без фильтра возвращает ровно то же, что запрос с фильтром.
--
-- ПОЧЕМУ В doc_settings, а не в новой таблице. Это настройка КЛИНИКИ, а
-- doc_settings — единственная строка (id = 1, миграция 008), которая уже едет
-- из главного филиала со справочником: branch-sync/catalogue.js
-- DOC_SETTINGS_COLUMNS перечисляет её колонки, exportCatalogue выгружает,
-- applyCatalogue применяет. Настройка, добавленная сюда, начинает
-- путешествовать одной строкой в перечне — и все здания сходятся на одном
-- ответе, вместо того чтобы каждое решало у себя. Своя таблица потребовала бы
-- собственного канала переноса и разошлась бы с этим при первом же изменении.
--
-- Заметьте, чего здесь НЕТ: границы очереди врача, регистратуры, процедур и
-- заявок. Решение владельца 2026-09-02 («очередь и кабинет врача — своего
-- здания») в силе; эта настройка касается ТОЛЬКО лаборатории.
--
-- NOT NULL DEFAULT — обязателен для ALTER TABLE ADD COLUMN в SQLite, и он же
-- проставляет 'clinic' уже существующей строке: отдельный UPDATE не нужен.
ALTER TABLE doc_settings ADD COLUMN lab_scope TEXT NOT NULL DEFAULT 'clinic'
  CHECK (lab_scope IN ('clinic', 'building'));
