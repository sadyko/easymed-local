-- 093_treatment_orders.sql — TREATMENT_ORDERS_V1: ЛИСТ НАЗНАЧЕНИЙ.
--
-- Врач назначает препарат «3 раза в день 5 дней», и с этой минуты у клиники
-- появляются ПЛАНОВЫЕ ТОЧКИ ВРЕМЕНИ: 6:00, 14:00, 22:00 — пятнадцать штук, у
-- каждой своя судьба (дали / отказался / пропустили / придержали), и каждая
-- подписана тем, кто её закрыл. Лист назначений — это и есть таблица таких
-- точек, а не список препаратов.
--
-- ─── ПОЧЕМУ НОВЫЕ ТАБЛИЦЫ, А НЕ ДОРАБОТКА 025 ───────────────────────────────
--
-- В базе с миграции 025 живут `admission_prescriptions` и `med_administrations`.
-- Они ОСТАЮТСЯ КАК ЕСТЬ, ни одна их колонка не трогается, ни одна строка не
-- переносится. Причины ровно три, и все три проверены, а не предположены:
--
--   1. У них нет расписания и нет ключа отметки. Назначение хранит частоту
--      СТРОКОЙ («3 р/д» в `freq`, «5 дней» в `dur`) — из такой строки сервер не
--      может ни развернуть курс по часам, ни сказать, что доза 14:00 сегодня
--      просрочена. Журнал `med_administrations` — просто «кому что когда
--      вкололи», БЕЗ ссылки на назначение и без слота: две отметки одной и той
--      же дозы в нём неотличимы от двух разных доз, и повторное нажатие
--      кнопки дублирует запись. Именно это и есть ошибка референса, которую
--      план велит не повторить: ключ отметки — (назначение, ДАТА, слот).
--
--   2. Дотянуть их до нужной формы означало бы ПЕРЕСБОРКУ обеих: новые
--      NOT NULL (due_date), CHECK по статусам и путям введения, UNIQUE по
--      (order_id, due_date, due_slot). А на них прямо сейчас пишет работающий
--      экран (public/js/admin/views/admission-modal.js, плюс pharmacy.js
--      читает журнал выдач). Он вставляет строки БЕЗ due_date и без статуса —
--      после пересборки его INSERT падал бы на первом же нажатии, в день
--      обновления, в живой клинике. Экран заменяет Задача 5; до тех пор он
--      обязан работать.
--
--   3. Терять при этом нечего: в живых базах в обеих таблицах НОЛЬ строк.
--      Данных, ради которых стоило бы рисковать пересборкой, не существует.
--
-- Старые таблицы не удаляются — из живого продукта таблицы не выбрасывают
-- мимоходом. Когда Задача 5 переведёт экран на новые, отставку старых оформит
-- отдельная миграция, у которой не будет другой работы.
--
-- ─── ЧТО СОЗДАЁТСЯ ──────────────────────────────────────────────────────────
--
--   treatment_orders           само назначение: что, сколько, каким путём,
--                              как часто, с какого дня и сколько дней;
--   treatment_administrations  отметки: одна строка — одна плановая точка,
--                              закрытая медсестрой.
--
-- Обе — ЧИСТО СЕРВЕРНЫЕ на запись: в schema-registry.js у них write.roles = []
-- во всех трёх операциях, писать их можно только через RPC
-- (server/services/rpc/treatment-orders.js), потому что каждая запись — это
-- проверка маршрута («пациент дошёл до active») и проверка роли.
--
-- ─── СИНХРОНИЗАЦИЯ ФИЛИАЛОВ ─────────────────────────────────────────────────
--
-- Ни одной из этих таблиц нет в SHIPPED (branch-sync/journal.js), триггеров на
-- них не появляется, и `invoices` эта миграция не касается ВОВСЕ — ни
-- пересборки, ни массового UPDATE (предупреждение из шапки 084). Деньги
-- (списание со склада и начисление за введённую дозу) — Задача 6; здесь их
-- нет ни строкой, но место под них подготовлено: service_id (что начислить),
-- stock_item_id (что списать) и extra_consumption (что ушло сверх дозы —
-- разбитая ампула).

-- ---------------------------------------------------------------------------
-- Назначение
-- ---------------------------------------------------------------------------
CREATE TABLE treatment_orders (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  admission_id INTEGER NOT NULL REFERENCES admissions(id),

  -- Четыре рода назначений: препарат, инфузия (капельница), процедура и уход
  -- (перевязка, режим, наблюдение). Различие несущее: у инфузии есть объём и
  -- скорость, у процедуры — услуга прейскуранта, у ухода — ни того, ни другого.
  kind TEXT NOT NULL DEFAULT 'med' CHECK (kind IN ('med','infusion','proc','care')),

  -- Название — ВСЕГДА текстом, даже когда есть ссылка на справочник. Строка
  -- листа назначений обязана читаться через год, когда услугу переименовали
  -- или препарат вывели из оборота: тот же довод, по которому счёт хранит имя
  -- услуги, а не только её id.
  name TEXT NOT NULL,
  -- Чем это начислить (Задача 6). NULL — назначение без денег: уход, режим,
  -- препарат пациента.
  service_id INTEGER REFERENCES services(id),
  -- Что списать со склада (Задача 6). Склад в этой базе — `products`
  -- (миграция 007), движения — `stock_movements`; отдельной таблицы «позиций
  -- склада» не существует, и колонка ссылается именно на products, как это
  -- уже делает admission_services.clinic_item_id.
  stock_item_id INTEGER REFERENCES products(id),

  dose TEXT NOT NULL DEFAULT '',
  -- Путь введения — закрытый список из десяти, которыми пишет отделение.
  -- NULL допустим: у процедуры и ухода пути введения нет.
  route TEXT CHECK (route IS NULL OR route IN (
    'в/в', 'в/в кап.', 'в/в (инфузомат)', 'в/м', 'п/к',
    'внутрь', 'сублингв.', 'ингаляция', 'местно', 'ректально')),

  -- Частота — КОДОМ (домен: server/services/domain/mar-schedule.js).
  freq_code TEXT NOT NULL DEFAULT '1x'
    CHECK (freq_code IN ('1x','2x','3x','4x','q6h','once','prn')),
  -- Развёрнутые часы, СОХРАНЁННЫЕ СНИМКОМ, — JSON-массив вроде '[6,14,22]'.
  --
  -- Это не денормализация ради скорости, а защита истории. Таблица частот —
  -- настройка клиники: завтра «3 р/д» станет 8/14/20, и если бы часы каждый
  -- раз вычислялись из freq_code, то ВСЕ прошлые листы назначений молча
  -- переписались бы задним числом — включая уже закрытые отметки, которые
  -- повисли бы на несуществующих слотах. Курс живёт по тем часам, по каким
  -- его назначили.
  slots TEXT NOT NULL DEFAULT '[]',
  -- «По требованию»: плановых точек нет вовсе, медсестра отмечает по факту.
  -- Отдельный флаг рядом с freq_code='prn' — потому что спрашивают его
  -- постоянно («покажи PRN отдельным блоком»), а разбирать JSON слотов ради
  -- этого в каждом запросе нельзя.
  prn INTEGER NOT NULL DEFAULT 0 CHECK (prn IN (0,1)),

  -- Курс: с какого дня, сколько дней, по какой день.
  starts_on TEXT NOT NULL,
  -- NULL = «до отмены». Именно так пишут постоянную терапию, и подменять это
  -- большим числом дней нельзя: «до отмены» и «на 999 дней» — разные вещи для
  -- того, кто через месяц смотрит, почему препарат всё ещё идёт.
  days INTEGER CHECK (days IS NULL OR days > 0),
  -- Производное от starts_on + days, посчитанное при создании и сохранённое:
  -- запросы «какие курсы идут на эту дату» должны отбираться индексом, а не
  -- арифметикой по каждой строке.
  ends_on TEXT,

  prescribed_by INTEGER REFERENCES users(id),
  prescribed_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now')),

  -- Чей препарат. 'patient' — принесённый родственниками: его НЕ списывают со
  -- склада и НЕ начисляют (правило Задачи 6), но отмечать его введение
  -- медсестра обязана точно так же.
  source TEXT NOT NULL DEFAULT 'clinic' CHECK (source IN ('clinic','patient')),

  -- 'finished' — курс отработан (последний день прошёл или его закрыла
  -- выписка). Отдельно от 'cancelled': законченное лечение и отменённое
  -- лечение — разные вещи в истории болезни.
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active','cancelled','finished')),
  -- Отмена НИКОГДА не удаляет строку (ловушка референса, названная в плане):
  -- назначение остаётся зачёркнутым, с причиной, автором и временем, и все
  -- уже сделанные отметки при нём.
  cancel_reason TEXT NOT NULL DEFAULT '',
  cancel_note TEXT NOT NULL DEFAULT '',
  cancel_by INTEGER REFERENCES users(id),
  cancel_at TEXT,

  -- Инфузия: объём, скорость и длительность. Пустые у остальных родов.
  -- continuous — «постоянная» (инфузомат): идёт без разбиения на дозы.
  volume REAL,
  rate_ml_h REAL,
  duration_min INTEGER,
  continuous INTEGER NOT NULL DEFAULT 0 CHECK (continuous IN (0,1)),

  note TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now'))
);

-- Запрос первый: «лист назначений ЭТОЙ госпитализации на эту дату». Ходит по
-- admission_id, отбрасывает отменённые (кроме случая, когда их просят
-- показать), и попадает в диапазон курса.
CREATE INDEX idx_treatment_orders_admission
  ON treatment_orders(admission_id, status, starts_on);

-- Запрос второй: «что вообще идёт на эту дату по отделению» — основа списка
-- задач медсестры. Частичный: 'active' — единственный статус, у которого
-- бывают будущие точки, а отменённых и законченных со временем становится
-- больше, чем действующих.
CREATE INDEX idx_treatment_orders_open
  ON treatment_orders(starts_on, ends_on) WHERE status = 'active';

-- ---------------------------------------------------------------------------
-- Отметка медсестры
-- ---------------------------------------------------------------------------
-- ОДНА СТРОКА — ОДНА ПЛАНОВАЯ ТОЧКА. Ключ (назначение, ДАТА, слот), а не час:
-- курс на пять дней даёт пятнадцать разных точек в трёх слотах, и ключ по
-- одному часу схлопнул бы весь курс в один день. В референсе он схлопнут — его
-- лист назначений поэтому и однодневный.
CREATE TABLE treatment_administrations (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  order_id INTEGER NOT NULL REFERENCES treatment_orders(id),

  -- Дата плановой точки, 'YYYY-MM-DD' по МЕСТНОМУ календарю клиники (слоты —
  -- часы настенных часов отделения, см. domain/mar-schedule.js).
  due_date TEXT NOT NULL,
  -- Час плановой точки, 0..23. NULL = отметка «по требованию»: у PRN плановых
  -- точек нет, и выдумывать им слот значило бы записать в базу расписание,
  -- которого врач не назначал.
  due_slot INTEGER CHECK (due_slot IS NULL OR (due_slot >= 0 AND due_slot <= 23)),

  status TEXT NOT NULL CHECK (status IN ('given','refused','missed','held')),
  given_at TEXT,
  given_by INTEGER REFERENCES users(id),
  -- Причина обязательна для всего, кроме 'given'. Правило продублировано в
  -- RPC (там оно даёт человеческий отказ), но живёт и здесь: «отказался» без
  -- причины — это не запись в истории болезни, а её отсутствие.
  reason TEXT NOT NULL DEFAULT '',
  note TEXT NOT NULL DEFAULT '',
  -- Расход СВЕРХ дозы: разбитая ампула, второй шприц. JSON-текст
  -- ([{product_id, qty}]), потому что позиций бывает несколько, а списывать
  -- их будет Задача 6 — здесь они только записываются.
  extra_consumption TEXT,

  -- Снятие отметки (только старшая медсестра / администратор) НЕ УДАЛЯЕТ
  -- строку — в этом и разница с референсом, где снятая отметка исчезает
  -- бесследно. Строка остаётся со следом: кто снял, когда и почему; из
  -- действующих её выводит voided_at, и слот снова становится свободным для
  -- новой отметки (см. частичный UNIQUE ниже).
  voided_at TEXT,
  voided_by INTEGER REFERENCES users(id),
  void_reason TEXT NOT NULL DEFAULT '',

  created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now')),

  CHECK (status = 'given' OR TRIM(reason) <> '')
);

-- ЕДИНСТВЕННОСТЬ ОТМЕТКИ — частичным индексом, и обе половины условия несущие.
--
--   due_slot IS NOT NULL — PRN сюда не входит. Формально можно было бы
--     положиться на то, что SQL считает NULL'ы РАЗНЫМИ и UNIQUE их не ловит,
--     но это правило половина читателей помнит наоборот, и молчаливая опора на
--     него — худший способ объявить намерение. Здесь сказано вслух: у PRN
--     плановой точки нет, значит и единственности по ней нет; две инъекции по
--     требованию за день — норма, а не дубль. Отдельная таблица под PRN была
--     бы хуже: список задач медсестры и лист врача читали бы ДВА источника, и
--     каждый следующий запрос пришлось бы писать через UNION.
--
--   voided_at IS NULL — снятая отметка перестаёт занимать слот. Иначе снять
--     ошибочную отметку было бы можно, а поставить взамен верную — нет.
CREATE UNIQUE INDEX ux_treatment_admin_due
  ON treatment_administrations(order_id, due_date, due_slot)
  WHERE due_slot IS NOT NULL AND voided_at IS NULL;

-- Лист врача: все отметки одной госпитализации за период — ходят по назначению
-- и дате.
CREATE INDEX idx_treatment_admin_order
  ON treatment_administrations(order_id, due_date);

-- Список задач медсестры: «что уже закрыто на сегодня по всему отделению» —
-- ходит по дате первым столбцом, потому что назначений в отделении сотни, а
-- дата одна.
CREATE INDEX idx_treatment_admin_date
  ON treatment_administrations(due_date, order_id);
