-- FREE_SERVICE_V1 — бесплатная услуга не ждёт кассу.
--
-- В 'queued' строку визита переводит ТОЛЬКО оплата (rpc/billing.js:
-- record_payment / record_payment_split / mark_invoice_debt). У бесплатной
-- услуги счёт выходит на ноль, помечается 'paid' в момент создания, и оплаты по
-- нему не бывает никогда — record_payment отказывает при остатке <= 0. Строка
-- так и оставалась в 'added', а доска очереди читает 'added' как «ожидает
-- оплату»: «Бесплатная консультация» висела в очереди врача с этой подписью
-- вечно, и снять её оттуда было нечем.
--
-- Аллокатор с этого момента закрывает такие строки сам. Здесь — УЖЕ зависшие.
--
-- ГРАНИЦА: только строки с total = 0 в статусе 'added'. 'added' у бесплатной
-- услуги — это не история, а тупик: платить по ней нечего и не будет чем.
-- Уже принятые ('in_progress') и закрытые ('completed') не трогаем.
--
-- Номера очереди НЕ меняются: они и так выданы по порядку, после предыдущих
-- пациентов. Ломалась только подпись состояния, а не место в очереди.

UPDATE visit_services
   SET status = 'queued'
 WHERE total = 0
   AND status = 'added';
