// STOCK_QTY_V1 (V3120_FIX, 2026-09-27) — ОДНО правило точности для всего, что
// пишет остаток: products.on_hand, stock_holdings.qty, stock_movements.qty.
//
// ЧТО БЫЛО. Базовое количество считалось как round2(штуки / consumption_factor):
// таблетка из пачки по 7 — это 1/7 = 0.142857… пачки, а round2 записывал 0.14.
// Семь таблеток «по одной» списывали 0.98 пачки, и у медсестры навсегда
// оставалось 0.02 пачки — призрачная седьмая часть таблетки. У пачки по 30
// одна таблетка превращалась в 0.03 (0.9 таблетки), и из тридцати можно было
// выдать тридцать третью. Физраствор по литру: 4 мл = 0.004 л округлялись в 0 —
// «слишком мало»; одобрение заявки писало движение без округления, а остаток с
// округлением, и журнал расходился с остатком.
//
// ЧТО СТАЛО.
//   1. Количества хранятся с ШЕСТЬЮ знаками (roundQty) — везде одинаково.
//      Округление «до сотых» — только на экране.
//   2. Остаток, который после списания ближе к нулю, чем 0.001 единицы расхода
//      (одна тысячная таблетки / миллилитра), — это НОЛЬ (settleQty). Шесть
//      знаков не делают 1/7 точной: 7 × 0.142857 = 0.999999, и без этого шага
//      миллионная доля пачки висела бы строкой «на руках».
//   3. «Хватает ли» спрашивается с тем же допуском (coversQty): 0.142857 из
//      0.142856 — это «последняя таблетка», а не отказ.
//
// ЧИСТЫЙ МОДУЛЬ: ни базы, ни запросов — правило спрашивают склад, подотчёт,
// заявки и лист назначений.

/** Шесть знаков — единая точность хранения количества. */
export function roundQty(n) {
  const v = Math.round(Number(n) * 1e6) / 1e6;
  return v === 0 ? 0 : v;   // без «-0»
}

/** Единиц расхода в базовой единице товара (1, если единицы расхода нет). */
export function factorOf(product) {
  return product && product.consumption_unit && Number(product.consumption_factor) > 0
    ? Number(product.consumption_factor) : 1;
}

/**
 * Допуск в БАЗОВЫХ единицах: одна тысячная единицы расхода, но не меньше
 * шага хранения (2 миллионных) — у товара с огромным фактором иначе допуск
 * стал бы мельче самой точности.
 */
export function qtyTolerance(cf = 1) {
  const f = Number(cf) > 0 ? Number(cf) : 1;
  return Math.max(0.001 / f, 2e-6);
}

/** Единицы расхода → базовые, с точностью хранения. */
export function toBase(units, cf = 1) {
  const f = Number(cf) > 0 ? Number(cf) : 1;
  return roundQty(Number(units) / f);
}

/** Итоговый остаток: шесть знаков, а пыль округления — ноль. */
export function settleQty(value, cf = 1) {
  const v = roundQty(value);
  return Math.abs(v) < qtyTolerance(cf) ? 0 : v;
}

/** Хватает ли `have`, чтобы отдать `need` (обе — базовые), с допуском. */
export function coversQty(have, need, cf = 1) {
  return Number(have) + qtyTolerance(cf) >= Number(need);
}

/** Количество в единицах расхода для ответа экрану (три знака — не хранение). */
export function unitsOf(baseQty, cf = 1) {
  const f = Number(cf) > 0 ? Number(cf) : 1;
  return Math.round(Number(baseQty) * f * 1000) / 1000;
}
