// BRANCH_RECORDS_V1 — приём чужих изменений.
//
// ТРИ ПРАВИЛА, каждое из которых нельзя переиграть после того, как данные
// разъехались:
//
//   1. Строки приезжают по СВОИМ локальным id (uid → id через таблицу).
//      Перенести чужой id значило бы перевесить местные счета и смены кассы на
//      чужие строки — разбор этого есть в миграции 079.
//   2. Слияние ПОКОЛОНОЧНОЕ — и в обе стороны. Приехавшая запись меняет только
//      те колонки, которые отправитель ПРАВИЛ (rec.changed), и только если её
//      метка новее той, под которой эта колонка менялась в последний раз;
//      местная неотправленная правка держит СВОИ колонки, а не строку целиком.
//      Телефон, исправленный здесь, и адрес, исправленный там, обязаны выжить
//      оба — включая случай, когда обе правки ещё не отданы (шапка 084).
//   3. Удаление проигрывает более поздней правке. Молча уничтожить запись, с
//      которой кто-то ещё работал, — единственная невосстановимая ошибка в
//      этом файле.
//
// Всё это — в ОДНОЙ транзакции: половина приехавшей истории хуже, чем ничего,
// потому что в ней визиты без пациентов.
import { SqliteError } from 'better-sqlite3';
import { compareStamps, isStamp, nextStamp, parseStamp, stampAt } from './hlc.js';
import { SHIPPED, REFS, CODE_REFS, readClock, writeClock, authoredAt } from './journal.js';

// sync_seen (миграция 084): метка последнего ПРИНЯТОГО изменения каждой
// колонки. Местная правка метки не имеет — до отправки её защищает журнал.
const SEEN = 'sync_seen';
// Приехавшая запись больше этого — не хранится в ожидании, а пропускается:
// предел релея (12 МБ сжатых) ничего не говорит о размере ОДНОЙ строки.
// БАЙТЫ, а не символы: в кириллице буква — два байта, и .length занизил бы
// размер русской записи вдвое ровно там, где предел и нужен.
const MAX_PENDING_BYTES = 256 * 1024;
const PENDING_MAX_DAYS = 30;
// Сколько держим запись об отказе базы. Дольше, чем ожидание родителя: отказ
// читает человек, а не механизм, и «пришло на прошлой неделе» — это ещё
// разбираемо, «пришло вчера» — уже поздно.
const REFUSED_MAX_DAYS = 60;
// sync_seen растёт быстрее журнала: ~190 строк на принятый визит с панелью
// (повторное ревью Задачи 3: ~17 млн строк, 1.4 ГБ в год у принимающего
// филиала). Метка старше SEEN_DAYS не нужна: порции — минутной давности, а
// холодный засев несёт СВЕЖИЕ метки (пол HLC), не created_at. Надгробия '*'
// живут столько же: запоздавший put старше 90 дней — не сценарий.
const SEEN_DAYS = 90;
// Где лежит ПОСЛЕДНИЙ ПРИМЕНЁННЫЙ рубеж чистки sync_seen. Та же
// control_state, что у часов (journal.js) и у записей о выгрузках (relay.js).
const SEEN_CUTOFF_KEY = 'sync_seen_cutoff';
// Предохранитель цикла освобождения. Настоящая глубина цепочки — четыре
// (пациент → визит → услуга → результат), и каждый круг освобождает ВСЕХ, кому
// родитель уже приехал, поэтому кругов нужно не больше пяти. Ограничение стоит
// не ради нормы, а чтобы порция с неожиданной формой данных не завесила приём
// навсегда: лучше оставить ожидание на следующую порцию, чем не вернуться.
const MAX_RELEASE_ROUNDS = 64;
// Та же граница, что NODE_RE в hlc.js и LETTER_MAX_CHARS в letters.js. Здесь
// своя копия, а не импорт: hlc проверяет букву в чеканке метки, а нам нужно
// отказать ДО транзакции — на входе, где отказ ничего не стоит.
const SELF_RE = /^[A-Z]{1,8}$/;
// НАСКОЛЬКО МЕТКЕ ПОЗВОЛЕНО ОБГОНЯТЬ НАШИ ЧАСЫ (Задача 7e, I-2). Метка теперь
// решает, чья правка новее, — значит компьютер с часами, ушедшими вперёд,
// раздаёт всей сети метки из будущего, и КАЖДАЯ честная правка этой колонки
// отвергается, пока настенное время не догонит. Пять минут — обычный дрейф без
// NTP; всё, что выше, — сбитые часы, и такую метку мы подрезаем.
//
// ПОДРЕЗАЕМ, А НЕ ОТБРАСЫВАЕМ: в записи настоящая работа филиала, и терять её
// из-за севшей батарейки CMOS нельзя. Подрезанная метка означает «пришло
// только что» — то есть запись применится, а следующая честная правка
// спокойно её обгонит.
const SKEW_MAX_MS = 5 * 60 * 1000;

/**
 * Применить порцию.
 *
 * ЖУРНАЛ ПРИ ЭТОМ НЕ ПИШЕТСЯ. Триггеры 084 висят на самих таблицах, снять их
 * на время приёма нельзя (это одна база на всю клинику, рядом работают люди),
 * поэтому записи, порождённые приёмом, удаляются в конце транзакции по
 * отметке MAX(seq), снятой до её тела. Иначе принятое изменение уехало бы
 * обратно, вернулось снова и ходило бы по кругу вечно.
 *
 * КВИТАНЦИЯ (Задача 7b). `upto` — номер журнала отправителя, до которого
 * доходит этот срез. Он запоминается в sync_peers.recv_upto ТОЙ ЖЕ
 * транзакцией, что и сами записи (откатилась она — не подтверждено ничего), и
 * уезжает обратно в нашем блобе полем `acks`. Оттуда же берётся и защита от
 * повторов: срез с upto не больше уже принятого — тот самый неподтверждённый
 * хвост, который сосед повторяет в каждом блобе, и разбирать его второй раз
 * незачем.
 *
 * ЗАСЕВ ЭТОЙ ПРОВЕРКЕ НЕ ПОДЛЕЖИТ (seed): все страницы холодного засева несут
 * ОДИН И ТОТ ЖЕ upto — замороженный пол журнала, — и отсечь по нему значило бы
 * оборвать засев на первой странице.
 *
 * СТРОКА sync_peers ЗДЕСЬ НЕ ЗАВОДИТСЯ, только обновляется. Её отсутствие —
 * это «сосед ХОЛОДНЫЙ» для buildBatch (ему ещё предстоит засев из таблиц), и
 * завести её на приёме значило бы объявить соседа тёплым, ни разу ему ничего
 * не отдав: наши собственные строки не уехали бы к нему никогда. Цена —
 * первая же выгрузка (она идёт до выборки и строку заводит) ставит всё на
 * место, а до неё повтор среза просто применится ещё раз, идемпотентно.
 *
 * @param {import('better-sqlite3').Database} db
 * @param {Array} records порция, как её собрал buildBatch на той стороне
 * @param {{self: string, peer?: string, upto?: number, seed?: boolean}} opts
 *   self — буква ЭТОГО узла (идёт в часы); peer — буква узла, ЧЕЙ блоб мы
 *   забрали, если она известна вызывающему; upto/seed — заголовок среза.
 * @returns {{applied:number, released:number, skipped:number, protected:number, deferred:number, deleted:number, refused:number, already?:true}}
 *   released — сколько строк применено ИЗ ОЖИДАНИЯ; protected — сколько записей
 *   отдали хотя бы одну колонку местной неотправленной правке; deferred — сколько
 *   строк ЖДЁТ родителя на конец транзакции (не «сколько раз отложили»);
 *   already — срез уже применён раньше, работы не было.
 */
export function applyBatch(db, records, {
  self, peer = null, upto = 0, seed = false, seedPage = 0, skewMaxMs = SKEW_MAX_MS,
} = {}) {
  // Без self часы после приёма не чеканятся, и узел с отставшими часами
  // проигрывал бы слияние вечно — это тихая потеря данных, а не мелочь.
  // Проверяется ФОРМА буквы, а не просто «не пусто»: self уходит в nextStamp,
  // и мусор вроде true или 'узел-1' уронил бы там ВСЮ транзакцию в самом
  // конце — после того, как порция уже применена, но до записи часов.
  if (!SELF_RE.test(String(self == null ? '' : self).toUpperCase())) {
    throw new Error('applyBatch: self letter required, got ' + JSON.stringify(self));
  }
  const stats = {
    applied: 0, released: 0, skipped: 0, protected: 0, deferred: 0, deleted: 0, refused: 0,
    skewed: 0, skew_ms: 0,
  };
  const ctx = newCtx(db);
  // Буква нужна не только часам: ею чеканится метка МЕСТНОЙ правки, когда
  // приехавшую запись надо с этой правкой сравнить (localEditStamps).
  ctx.self = String(self).toUpperCase();
  // Чей блоб разбираем — нужно записи об отказе (sync_refused).
  ctx.peer = typeof peer === 'string' && peer ? peer : null;
  // Снимки авторства строк, которых коснулся приём: восстанавливаются в конце
  // транзакции, чтобы принятая колонка не считалась здешней правкой.
  ctx.authored = new Map();
  // Насколько метки этого соседа обгоняют наши часы и сколько записей пришлось
  // подрезать: и то, и другое едет на экран синхронизации.
  ctx.skewMs = 0;
  ctx.skewed = 0;
  // Допуск вынесен в параметр ради теста: подождать пять минут он не может.
  ctx.skewMax = Number.isFinite(Number(skewMaxMs)) && Number(skewMaxMs) >= 0 ? Number(skewMaxMs) : SKEW_MAX_MS;

  // Срез, который мы уже разбирали. Не ошибка и не потеря: сосед повторяет
  // неподтверждённое в каждом блобе, пока не увидит нашу квитанцию, а
  // квитанция уезжает только с НАШЕЙ выгрузкой — то есть один цикл повтор
  // живёт всегда. Считаем записи пропущенными, чтобы в журнале сервера было
  // видно, что срез приезжал, а не что его не было.
  const reach = sliceUpto(upto);
  const page = sliceUpto(seedPage);
  // Квитанция, СНЯТАЯ ДО ПРИЁМА: ею сужается авторство повторов (narrowChanged),
  // и снимать её после обновления в конце транзакции значило бы отобрать
  // авторство у той самой порции, которую мы сейчас применяем.
  const before = peer ? receipt(db, peer) : { recv_upto: 0, recv_seed_page: 0 };
  ctx.recvUpto = before.recv_upto;
  if (sliceAlreadyApplied(db, { peer, upto, seed, seedPage })) {
    return { ...stats, skipped: Array.isArray(records) ? records.length : 0, already: true };
  }

  const run = db.transaction((batch) => {
    const mark = db.prepare('SELECT MAX(seq) AS s FROM sync_journal').get();
    const journalFrom = mark && mark.s ? mark.s : 0;

    for (const rec of batch) {
      // ЧУЖОЙ ОТПРАВИТЕЛЬ. origin приходит из порции, то есть от того, кто её
      // прислал; проверить его подпись нечем. Но ВЫЗЫВАЮЩИЙ знает, чей блоб он
      // сейчас забрал, и запись, подписанная другой буквой, в этом блобе —
      // либо ошибка сборки, либо попытка выдать себя за третий филиал. Такая
      // запись не применяется: origin решает, чью защиту снимать (см.
      // localUnshippedCols) и чьей меткой подписывать строку.
      if (peer && (!rec || typeof rec !== 'object' || rec.origin !== peer)) { stats.skipped++; continue; }
      // И ТА ЖЕ БУКВА В МЕТКЕ (ревью 7/7b, M1). origin решает, чью защиту
      // снимать, а буква из метки уходит в sync_origin — «откуда строка» на
      // экране. Разойдись они, и запись села бы в базу подписанной ОДНИМ
      // филиалом, а слитой по правилам ДРУГОГО: подпись на карточке пациента
      // указывала бы не туда, и проверить это владельцу нечем.
      if (rec && rec.origin && isStamp(rec.stamp)) {
        const signed = parseStamp(rec.stamp);
        if (!signed || signed.node !== String(rec.origin).toUpperCase()) { stats.skipped++; continue; }
      }
      applyGuarded(db, rec, stats, ctx);
    }

    releasePending(db, stats, ctx);

    // Ребёнок, чей родитель удалён у источника (или чья услуга так и не
    // появилась в справочнике), ждал бы вечно.
    db.prepare('DELETE FROM sync_pending WHERE received_at < ?')
      .run(new Date(Date.now() - PENDING_MAX_DAYS * 86400000).toISOString());
    // Отказы тоже не вечны: строка, которую база не взяла полгода назад и
    // которую с тех пор никто не переслал, — это уже не список дел, а мусор.
    db.prepare('DELETE FROM sync_refused WHERE at < ?')
      .run(new Date(Date.now() - REFUSED_MAX_DAYS * 86400000).toISOString());
    // Метки, старше которых ничего не приедет. Сравнение строковое: метка —
    // hex миллисекунд фиксированной ширины (hlc.js), и «старше даты» это
    // «меньше метки этой даты».
    //
    // ЧИСТИТСЯ ТОЛЬКО КОГДА ГОРИЗОНТ СДВИНУЛСЯ (ревью Задачи 5b). `stamp` не
    // индексирован, а sync_seen — самая большая таблица фазы (~190 строк на
    // принятый визит с панелью), то есть каждая порция платила полным сканом
    // за удаление нуля строк: горизонт сдвигается на десятки минут в час, а
    // выселять надо то, что старше 90 дней. Прошлый рубеж лежит в control_state:
    // отдельная таблица ради одной строки не заводится, а сравнение строковое:
    // рубеж — hex фиксированной ширины (12 знаков), как и сами метки.
    const seenCutoff = seenHorizon(ctx.maxReceived);
    if (seenCutoff) {
      const prev = ctx.q('SELECT value FROM control_state WHERE key = ?').get(SEEN_CUTOFF_KEY);
      if (!prev || String(prev.value) < seenCutoff) {
        db.prepare(`DELETE FROM ${SEEN} WHERE stamp < ?`).run(seenCutoff);
        ctx.q(`INSERT INTO control_state (key, value, updated_at)
               VALUES (?, ?, strftime('%Y-%m-%dT%H:%M:%SZ','now'))
               ON CONFLICT(key) DO UPDATE SET value = excluded.value, updated_at = excluded.updated_at`)
          .run(SEEN_CUTOFF_KEY, seenCutoff);
      }
    }

    // Приём не порождает исходящих изменений — см. заголовок.
    db.prepare('DELETE FROM sync_journal WHERE seq > ?').run(journalFrom);
    restoreAuthorship(db, ctx);

    stats.skewed = ctx.skewed;
    stats.skew_ms = ctx.skewMs;
    // Последний замеченный перекос хранится по соседу: карточка филиала в
    // главной клинике показывает его словами, а не «ничего не синхронизируется».
    if (peer && ctx.skewMs) {
      db.prepare('UPDATE sync_peers SET clock_skew_ms = ? WHERE node = ?').run(Math.floor(ctx.skewMs), peer);
    }

    // Часы этой машины двигаются за самую новую чужую метку: узел с отставшими
    // часами иначе проигрывал бы каждое слияние вечно.
    if (ctx.maxReceived) writeClock(db, nextStamp(readClock(db), self, Date.now, ctx.maxReceived));

    // deferred — сколько строк ЖДЁТ, а не сколько раз откладывали. Цепочка
    // «результат → услуга → визит», приехавшая задом наперёд одной порцией и
    // разобранная тут же, — это deferred 0 и released 3, а не «отложено три
    // раза»: читающему лог важно, сколько работы ОСТАЛОСЬ висеть.
    stats.deferred = db.prepare('SELECT COUNT(*) AS n FROM sync_pending').get().n;

    // КВИТАНЦИЯ — В ТОЙ ЖЕ ТРАНЗАКЦИИ, что и записи. Порядок здесь важнее, чем
    // кажется: подтверди мы приём отдельным запросом после — и откат этой
    // транзакции (отказ базы, выключенное питание) оставил бы соседу
    // подтверждение того, чего у нас нет, а он по нему вычистил бы свой
    // журнал. MAX — квитанция не откатывается назад: срез мог приехать
    // повторно, старым (сосед выгрузился раньше, чем прочитал нашу).
    //
    // НОМЕР СТРАНИЦЫ ЗАСЕВА — вторая половина квитанции: по нему отправитель
    // двигает курсор засева, и без него страница, которую мы забрали,
    // считалась бы у него неотданной вечно. Номера имеют смысл ТОЛЬКО в
    // пределах одного пола (upto): сосед, забывший нас и начавший засев
    // заново, нумерует страницы с единицы, и сравнивать их со старыми нельзя —
    // отсюда сброс, когда пол сменился.
    if (peer && (reach || page)) {
      const sameSeed = reach === before.recv_upto;
      const nextPage = page
        ? (sameSeed ? Math.max(before.recv_seed_page, page) : page)
        : before.recv_seed_page;
      // СТРОКА ЗАВОДИТСЯ, ЕСЛИ ЕЁ НЕТ (ревью 7/7b, M2). Раньше здесь стоял
      // голый UPDATE, и у соседа, который выложился ПЕРВЫМ (мы ему ещё ничего
      // не отдавали), квитанция просто не записывалась: он повторял бы срез
      // лишний такт, а мы каждый раз разбирали бы его заново.
      //
      // ТЁПЛЫМ ЕГО ЭТО НЕ ДЕЛАЕТ, и вот это здесь главное. «Холодный» для
      // buildBatch — это отсутствие СТРОКИ, а теперь ещё и last_ok IS NULL:
      // мы ему ни разу не выкладывались, значит холодный засев ему только
      // предстоит. Без этой оговорки первая же полученная порция объявляла бы
      // соседа тёплым, и НАШИ существующие строки не уехали бы к нему никогда.
      db.prepare(`INSERT INTO sync_peers (node, recv_upto, recv_seed_page, last_ack)
                  VALUES (?, ?, ?, strftime('%Y-%m-%dT%H:%M:%SZ','now'))
                  ON CONFLICT(node) DO UPDATE SET
                    recv_upto = MAX(sync_peers.recv_upto, excluded.recv_upto),
                    recv_seed_page = excluded.recv_seed_page`)
        .run(peer, reach, nextPage);
    }
  });

  run(Array.isArray(records) ? records : []);
  return stats;
}

// ОДНА КРИВАЯ ЗАПИСЬ НЕ ОТМЕНЯЕТ ПОРЦИЮ. Проверить форму записи на входе можно,
// но не всё ловится проверкой: CHECK-ограничение (visits.status), внешний ключ,
// длина поля — это отказ САМОЙ БАЗЫ уже посреди вставки. Без savepoint такой
// отказ выбрасывает наружу всю транзакцию: сотня здоровых записей теряется
// из-за одной, и следующая порция принесёт ту же кривую снова.
//
// ROLLBACK TO не снимает savepoint — RELEASE после него обязателен, иначе
// метка копится на каждую запись до конца транзакции.
//
// Счётчики откатываются вместе с данными: applyOne успевает их тронуть до
// падения, и без восстановления в статистике осталось бы «применено» то,
// чего в базе нет.
function applyGuarded(db, rec, stats, ctx) {
  const before = { ...stats };
  // ИМЯ МЕТКИ ФИКСИРОВАННОЕ ('rec'), и это верно ровно пока эти метки не
  // ВКЛАДЫВАЮТСЯ одна в другую: одна запись — одна метка, снятая до
  // следующей (RELEASE в обеих ветвях ниже), и releasePending зовёт эту функцию
  // последовательно, а не изнутри applyOne. Появись вложенность — внутренний
  // ROLLBACK TO rec откатил бы и ВНЕШНЮЮ запись вместе со своей, молча;
  // тогда имя придётся сделать счётчиком глубины, а не константой.
  ctx.q('SAVEPOINT rec').run();
  try {
    applyOne(db, rec, stats, ctx);
    ctx.q('RELEASE rec').run();
  } catch (e) {
    ctx.q('ROLLBACK TO rec').run();
    ctx.q('RELEASE rec').run();
    Object.assign(stats, before);
    // ПРОПУСКАЕТСЯ ТОЛЬКО ОТКАЗ БАЗЫ (ревью Задачи 5b). Обещание
    // этой функции — «одна кривая ЗАПИСЬ не отменяет порцию», а не «любая
    // ошибка здесь не важна». TypeError от опечатки в applyOne или RangeError из
    // чужой библиотеки — ошибка КОДА, и записав её в «запись отвергнута»,
    // мы получили бы тихо пустую синхронизацию на всей сети: каждая запись
    // «отказана», счётчики растут, данные не едут, и никто не узнает об этом,
    // пока владелец не спросит, почему филиал пустой.
    if (!(e instanceof SqliteError)) throw e;
    stats.skipped++;
    stats.refused++;
    // ОТКАЗ ОСТАЁТСЯ НА ДИСКЕ (ревью 7/7b, I2), а не только в консоли сервера.
    // Квитанция этому соседу всё равно уедет — иначе одна «ядовитая» строка
    // повторялась бы в каждом блобе вечно, — то есть второй раз он её НЕ
    // пришлёт. Значит это уже не «пропустили», а потеряли, и молча терять
    // чужую работу нельзя: владелец увидит счётчик на экране синхронизации,
    // поддержка — таблицу с причиной от самой базы.
    //
    // Пишется в ТОЙ ЖЕ транзакции: откатится порция — исчезнет и запись об
    // отказе, потому что и отказа тогда не было.
    try {
      ctx.q(`INSERT INTO sync_refused (tbl, uid, peer, err)
             VALUES (?, ?, ?, ?)
             ON CONFLICT(tbl, uid, peer) DO UPDATE SET
               err = excluded.err, at = strftime('%Y-%m-%dT%H:%M:%SZ','now')`)
        .run(
          String(rec && rec.tbl || '?'), String(rec && rec.uid || '?'),
          // Колонка NOT NULL: сосед не назван вызывающим — берём букву из
          // самой записи (она сверена с меткой), и лишь в совсем безымянном
          // случае '?'. NULL здесь был бы хуже всего: в PRIMARY KEY он не
          // склеивается, и одна и та же строка копилась бы тысячами.
          ctx.peer || String((rec && rec.origin) || '?'),
          e.message,
        );
    } catch (writeErr) {
      // Не смогли записать отказ — это не повод уронить всю порцию.
      console.warn('[sync] could not record the refusal:', writeErr && writeErr.message);
    }
    // Именно предупреждением, а не молчанием: запись, которую база не берёт,
    // будет приезжать снова и снова, и знать об этом должен человек.
    console.warn('[sync] record refused', rec && rec.tbl, rec && rec.uid, rec && rec.stamp, e.message);
  }
}

// Готовые запросы живут на порцию, а не на запись: порция — до 5000 записей, и
// prepare на каждую из них съедал бы больше, чем сама вставка.
function newCtx(db) {
  const cache = new Map();
  return {
    maxReceived: '',
    q(sql) {
      let s = cache.get(sql);
      if (!s) { s = db.prepare(sql); cache.set(sql, s); }
      return s;
    },
  };
}

// Граница удержания sync_seen — не «сейчас минус 90 дней», а «минимум из
// СЕЙЧАС и самой новой ПРИЕХАВШЕЙ метки, минус 90 дней». Разница видна ровно
// там, где всё и ломается: у филиала с ушедшими часами (севшая батарейка CMOS —
// в клинике это не гипотеза). Его метки приезжают «из 1970»; по границе от
// местного Date.now() они были бы вычищены В ТОЙ ЖЕ транзакции, в которой
// приняты, и вместе с ними — надгробия и поколоночные метки, которые защищают
// именно от его следующей порции: запоздавший put воскресил бы удалённую
// строку. Поэтому граница считается по ТОЙ ЖЕ шкале, что и сами метки.
//
// Симметрично сверху: часы соседа, ушедшие ВПЕРЁД на год, не должны вычистить
// весь sync_seen — поэтому минимум, а не максимум. Самоисправление встроено в
// HLC: приняв нашу метку, отставший сосед подтягивает свои часы (пол в
// nextStamp), и со следующего обмена удержание работает как обычно.
//
// Чего эта граница НЕ закрывает, и об этом надо знать вслух: порция от соседа
// с нормальными часами, пришедшая МЕЖДУ двумя порциями отставшего, поднимает
// границу до «сейчас» и вычищает метки эпохи 1970 — вместе с надгробиями.
// Случай узкий (нужен именно такой порядок порций) и ограниченный по ущербу,
// но он есть: полное лечение — своя граница на КАЖДОГО соседа, то есть ещё
// одна таблица, а не строчка здесь.
//
// Порция без единой годной метки границы не двигает: чистить нечем и незачем.
function seenHorizon(maxReceived) {
  if (!maxReceived) return null;
  const receivedMs = parseInt(String(maxReceived).slice(0, 12), 16);
  const base = Math.min(Date.now(), Number.isFinite(receivedMs) ? receivedMs : 0);
  const cutoff = base - SEEN_DAYS * 86400000;
  if (cutoff <= 0) return null;
  return cutoff.toString(16).padStart(12, '0');
}

function localId(db, ctx, tbl, uid) {
  const r = ctx.q(`SELECT id FROM ${tbl} WHERE uid = ?`).get(uid);
  return r ? r.id : null;
}

/**
 * Одна запись. Тот же код и для порции, и для освобождения из ожидания:
 * ожидавшая запись обязана пройти ровно те же проверки (надгробие, защита
 * местной правки, поколоночные метки), что и только что приехавшая.
 */
function applyOne(db, rec, stats, ctx) {
  // Порция приехала снаружи — форму её записей никто не гарантировал. Мусорная
  // запись пропускается поимённо, а не роняет всю транзакцию: одна кривая
  // строка не должна отменять сотню здоровых.
  if (!rec || typeof rec !== 'object' || !SHIPPED[rec.tbl]
      || typeof rec.uid !== 'string' || !isStamp(rec.stamp)
      || !scalarPayload(rec.data)) { stats.skipped++; return; }

  // АВТОРСТВО СУЖАЕТСЯ ПО НАШЕЙ ЖЕ КВИТАНЦИИ (Задача 7b), и это не
  // оптимизация, а условие сходимости. Срез у соседа накопительный: пока наша
  // квитанция не дошла, он повторяет и то, что мы давно применили, — вместе с
  // авторством той старой записи. У ВСТАВКИ авторство — '*', вся строка; наша
  // собственная более поздняя правка адреса, уже выложенная (а значит
  // незащищённая), проигрывала бы этому повтору и пропадала. Воспроизведено на
  // двух базах: B правит телефон, C — адрес, C теряет адрес НАВСЕГДА.
  //
  // `changed_at` — номер журнала последней правки каждой колонки у
  // отправителя. Всё, что не выше recv_upto, мы уже видели: свою работу с этим
  // мы сделали, и второй раз она не «новее» ничего. Сужение делается ЗДЕСЬ,
  // до всякого ожидания, и запись уходит в sync_pending уже суженной: к моменту
  // освобождения recv_upto уедет вперёд, и повторное сужение отняло бы у
  // записи законное авторство.
  const narrowed = narrowChanged(rec, ctx.recvUpto);
  if (narrowed) rec = { ...rec, changed: narrowed, changed_at: undefined };
  // Часы двигаются за ЛЮБОЙ годной приехавшей меткой — и за удалением, и за
  // отложенной в ожидание, и за пропущенной: иначе узел с отставшими часами,
  // получивший детей раньше родителей, ничему не учится и продолжает проигрывать.
  rec = { ...rec, stamp: clampSkew(ctx, rec.stamp) };
  if (rec.stamp > ctx.maxReceived) ctx.maxReceived = rec.stamp;

  const id = localId(db, ctx, rec.tbl, rec.uid);
  // АВТОРСТВО ПРИ ПРИЁМЕ НЕ ПИШЕТСЯ — по той же причине, по которой не пишется
  // журнал (см. заголовок файла): триггеры висят на самих таблицах, снять их на
  // время приёма нельзя, и applyBatch убирает за собой. Без этого узел объявлял
  // бы СВОИМ авторством каждую принятую колонку, да ещё и временем «сейчас», —
  // и следующая честная правка соседа, сделанная минуту назад, проигрывала бы
  // ей. В прогоне сети это видно сразу: правки перестают расходиться по узлам
  // вовсе (40 расхождений из 40).
  rememberAuthorship(db, ctx, rec.tbl, rec.uid);
  // Колонки, правленные ЗДЕСЬ и ещё не отданные этому соседу. Пустое множество
  // — защищать нечего. Новой строки (id == null) здесь не правили по
  // определению: терять нечего, защита не нужна.
  // ЗАЩИТЫ БОЛЬШЕ НЕТ (Задача 7e). Она держала колонки, правленные здесь и ещё
  // не выложенные соседу, и была нужна, пока у местной правки не было метки:
  // сравнивать было нечем, и единственным способом не потерять свою работу
  // было не принимать чужую. Теперь метка есть у обеих сторон, она поколоночная
  // и от времени правки — спор решается сравнением, а не удержанием.
  //
  // И удержание стало ВРЕДНЫМ, а не просто лишним. Наша правка СТАРШЕ
  // приехавшей — защита всё равно оставляла бы наше устаревшее значение, а
  // сосед, приняв нашу правку и увидев её младше своей, оставил бы своё: две
  // базы разошлись бы на ровном месте. Плюс квитанция уезжала и на
  // «защищённую» запись — сосед считал её доставленной и второй раз не слал.
  //
  // pub_seq остался: он показывает, докуда мы выложились (экран синхронизации),
  // и ограничивает квитанцию соседа. Решать, что применять, он больше не может.
  // МЕТКИ МЕСТНЫХ ПРАВОК этой строки — по колонкам. Без них сравнение
  // «кто новее» шло между чужой меткой и ЧУЖОЙ ЖЕ (sync_seen помнит только
  // принятое), а местная правка в нём не участвовала вовсе.
  const localStamps = id == null ? null : localEditStamps(db, ctx, rec.tbl, rec.uid);
  // МЕТКА ИМЕННО ЭТОЙ КОЛОНКИ (Задача 7d). Запись сборки до 7d поля stamps не
  // несёт — тогда, как и раньше, у всех колонок метка одна, общая для записи.
  const colStamp = (col) => {
    const per = rec.stamps && typeof rec.stamps === 'object' && !Array.isArray(rec.stamps)
      ? rec.stamps[col] : null;
    return clampSkew(ctx, isStamp(per) ? per : rec.stamp);
  };
  // true — местная правка этой колонки НОВЕЕ приехавшей записи.
  //
  // ЗАПОМИНАТЬ эту метку в sync_seen НЕЛЬЗЯ, хотя руки чешутся: пробовал,
  // стало хуже (19 расхождений из 40 против 16 — прогон о нём в плане).
  // Причина ровно в том, почему отказ здесь вообще безопасен. Отказывая по
  // ЖИВОЙ журнальной записи, мы отказываем от имени правки, которая ещё не
  // подтверждена соседом, а значит ещё УЕДЕТ — сосед возьмёт наше значение, и
  // обе стороны сойдутся на одном. Метка же в sync_seen переживает чистку
  // журнала: отказ по ней делается от имени правки, которую больше никто
  // никогда не пришлёт, и расхождение застывает навсегда.
  const localWins = (col) => {
    if (!localStamps) return false;
    const mine = localStamps.get(col) || localStamps.get('*');
    // Строго БОЛЬШЕ — иначе приехавшая не применяется. На равных
    // миллисекундах спор решает буква узла внутри самой метки, и решает
    // ОДИНАКОВО на обеих сторонах: сравниваются одни и те же две строки.
    return !!mine && compareStamps(colStamp(col), mine) <= 0;
  };

  if (rec.op === 'del') {
    // Правило 3. Удаление проигрывает любой более поздней правке — местной
    // неотправленной или приехавшей с более новой меткой по любой колонке.
    // ЛЮБАЯ незаконченная местная правка держит строку целиком: удалять
    // наполовину нечем, и «уцелела одна колонка» здесь не ответ.
    const newerCol = ctx.q(`SELECT 1 FROM ${SEEN} WHERE tbl = ? AND uid = ? AND stamp > ? LIMIT 1`)
      .get(rec.tbl, rec.uid, rec.stamp);
    if (newerCol) { stats.skipped++; return; }
    // Удаление проигрывает и МЕСТНОЙ правке, которая новее его: строку, с
    // которой здесь только что работали, стирать нельзя, даже если наша
    // правка уже уехала соседу.
    if (localWins('*') || SHIPPED[rec.tbl].some((c) => localWins(c))) { stats.skipped++; return; }
    // «Удаление проигрывает более поздней правке» считается на ТОЙ ЖЕ оси, что
    // и сами правки: надгробие несёт время удаления, колонка — время своей
    // правки (Задача 7d).
    if (id != null) {
      ctx.q(`DELETE FROM ${rec.tbl} WHERE id = ?`).run(id);
      stats.deleted++;
      // Строки нет — и авторства её колонок быть не должно: восстанавливать
      // снимок поверх удаления значило бы оставить след от того, чего нет.
      ctx.authored.delete(rec.tbl + '|' + rec.uid);
    }
    // Надгробие вместо поколоночных меток: строки больше нет, помнить по
    // колонкам нечего, а помнить САМ ФАКТ удаления обязательно (правило ниже).
    ctx.q(`DELETE FROM ${SEEN} WHERE tbl = ? AND uid = ?`).run(rec.tbl, rec.uid);
    ctx.q(`INSERT INTO ${SEEN} (tbl, uid, col, stamp) VALUES (?,?,?,?)`).run(rec.tbl, rec.uid, '*', rec.stamp);
    return;
  }

  // Надгробие: строка удалена с этой меткой. put, который СТАРШЕ надгробия, не
  // воскрешает её — отправитель удаление не повторит, и воскресшая строка
  // осталась бы здесь навсегда. put НОВЕЕ надгробия — законное повторное
  // заведение той же строки, и надгробие снимается.
  const tomb = ctx.q(`SELECT stamp FROM ${SEEN} WHERE tbl = ? AND uid = ? AND col = ?`).get(rec.tbl, rec.uid, '*');
  if (tomb && compareStamps(rec.stamp, tomb.stamp) <= 0) { stats.skipped++; return; }

  // От сужения выше не осталось НИ ОДНОЙ авторской колонки: это дословный
  // повтор того, что мы у этого соседа уже брали, и делать с ним нечего.
  // У новой строки (id == null) авторство не спрашивают вовсе — её надо
  // завести, а не слить.
  if (id != null && narrowed && !narrowed.length) { stats.skipped++; return; }

  // ЧТО В ЭТОЙ ЗАПИСИ АВТОРСКОЕ. data — снимок ВСЕЙ строки отправителя (иначе
  // новую строку у нас нечем было бы завести), но правил он только колонки из
  // changed; остальное в снимке — его КОПИЯ чужих значений, часто устаревшая.
  // Применять их «заодно» значит объявлять его автором того, чего он не
  // касался: так телефон, исправленный здесь, возвращался пустым под меткой
  // новее и пропадал из сети целиком (шапка 084).
  //
  // Запись СТАРОЙ сборки без changed — '*': «неизвестно, что менялось».
  // Прежнее поведение слово в слово, и никакой сосед не ломается от обновления
  // одной стороны раньше другой.
  //
  // У НОВОЙ строки (id == null) changed не спрашиваем вовсе: терять нечего,
  // а собрать её из трёх изменённых полей нельзя — NOT NULL без умолчания.
  const changed = id == null ? null : changedSet(rec);
  const wanted = (col) => {
    if (changed && !changed.has('*') && !changed.has(col)) return false;
    return true;
  };

  const cols = [];
  const vals = [];
  const seenCol = ctx.q(`SELECT stamp FROM ${SEEN} WHERE tbl = ? AND uid = ? AND col = ?`);
  for (const col of SHIPPED[rec.tbl]) {
    if (!rec.data || !Object.prototype.hasOwnProperty.call(rec.data, col)) continue;
    if (!wanted(col)) continue;
    const prev = seenCol.get(rec.tbl, rec.uid, col);
    if (prev && compareStamps(colStamp(col), prev.stamp) <= 0) continue;   // эта колонка новее у нас
    if (localWins(col)) continue;                                          // и местная правка тоже новее
    cols.push(col); vals.push(rec.data[col]);
  }
  // Новая строка: у неё ничего не защищено и ничего не видено — все колонки едут.
  //
  // Ссылки: uid родителя → его местный id. Родителя ещё нет — запись ЦЕЛИКОМ
  // уходит в ожидание: NOT NULL и внешние ключи не дадут вставить ребёнка с
  // пустой ссылкой, и это правильно. Ссылка на справочник (CODE_REFS) ищется
  // по коду, а не по uid: у services нет uid, его синхронизирует catalogue.js.
  //
  // sync_pending хранит ОДНОГО ожидаемого родителя, и break ниже — на первом
  // отсутствующем. Сегодня у каждой таблицы одна ссылка на строку плюс не более
  // одной на справочник, и запись, дождавшаяся первого родителя, тут же уходит
  // ждать второго; вторая ссылка НА СТРОКУ потребует ждать обоих сразу.
  let waiting = null;
  for (const [col, parent] of Object.entries(REFS[rec.tbl] || {})) {
    const parentUid = rec.refs ? rec.refs[col] : null;
    if (!parentUid) {
      // Ссылки нет в самой записи. У существующей строки она давно проставлена
      // — не трогаем. У НОВОЙ вставить нечего: колонка NOT NULL, и попытка
      // уронила бы ВСЮ порцию на строке, которую всё равно нечем применить.
      if (id == null) { stats.skipped++; return; }
      continue;
    }
    // Ссылка — такая же КОЛОНКА, как телефон, и подчиняется тем же правилам:
    // и авторству (changed), и защите местной правки. У СУЩЕСТВУЮЩЕЙ строки
    // ссылка уже проставлена — не наше дело её трогать. У новой она нужна
    // всегда: без родителя строки не собрать.
    if (id != null && !wanted(col)) continue;
    // Без проверки ниже запись, отлежавшая в ожидании, при освобождении
    // перевешивала бы визит на пациента из своей УСТАРЕВШЕЙ ссылки, оставляя
    // статус от более новой записи: половина строки от вчера, половина от
    // сегодня, и никакой ошибки в логах.
    const prevRef = seenCol.get(rec.tbl, rec.uid, col);
    if ((prevRef && compareStamps(colStamp(col), prevRef.stamp) <= 0) || localWins(col)) {
      // Ссылку уже приняли новее — или новее её правили здесь. Существующей
      // строке это ничем не грозит, а НОВУЮ без обязательного родителя не
      // собрать — и выдумывать его нельзя.
      if (id == null) { stats.skipped++; return; }
      continue;
    }
    const pid = localId(db, ctx, parent, parentUid);
    if (pid == null) { waiting = { tbl: parent, uid: parentUid }; break; }
    cols.push(col); vals.push(pid);
  }
  if (!waiting) {
    for (const [col, spec] of Object.entries(CODE_REFS[rec.tbl] || {})) {
      const code = rec.refs ? rec.refs[spec.ref] : null;
      if (!code) continue;
      if (id != null && !wanted(col)) continue;
      // То же правило. Колонка необязательная (visit_services.service_id
      // допускает NULL), поэтому устаревшую ссылку достаточно не трогать.
      const prevRef = seenCol.get(rec.tbl, rec.uid, col);
      if (prevRef && compareStamps(colStamp(col), prevRef.stamp) <= 0) continue;
      if (localWins(col)) continue;
      const pid = catalogueId(db, ctx, spec, code);
      if (pid == null) { waiting = { tbl: spec.table, uid: code }; break; }
      cols.push(col); vals.push(pid);
    }
  }
  if (waiting) {
    // БЕЗ changed_at (Задача 7b). Решение о сужении принято выше, этой
    // порцией и по квитанции ЭТОГО соседа. Освобождать запись из ожидания
    // может порция ДРУГОГО соседа (приехал общий родитель), а номера журнала
    // у каждого узла свои: сузив её тогда по чужой квитанции, мы сравнили бы
    // номера из разных журналов и отняли у записи авторство наугад.
    const json = JSON.stringify({ ...rec, changed_at: undefined });
    // Ожидание — рабочая таблица, а не свалка: одна раздутая запись, которую
    // всё равно нечем применить, не должна занимать место годами.
    if (Buffer.byteLength(json, 'utf8') > MAX_PENDING_BYTES) { stats.skipped++; return; }
    // Более поздняя запись про ту же строку замещает более раннюю; более ранняя
    // НЕ затирает более позднюю — порядок прихода не гарантирован ничем.
    ctx.q(`INSERT INTO sync_pending (tbl, uid, stamp, record, waits_tbl, waits_uid)
           VALUES (?,?,?,?,?,?)
           ON CONFLICT(tbl, uid) DO UPDATE SET
             stamp = excluded.stamp, record = excluded.record,
             waits_tbl = excluded.waits_tbl, waits_uid = excluded.waits_uid,
             received_at = strftime('%Y-%m-%dT%H:%M:%SZ','now')
           WHERE excluded.stamp > sync_pending.stamp`)
      .run(rec.tbl, rec.uid, rec.stamp, json, waiting.tbl, waiting.uid);
    // Не «пропущено» — ждёт родителя; читающему лог это две разные новости.
    // Считается не здесь, а в конце транзакции: часть отложенных освободится
    // в этой же порции, и «отложено 3, применено 3» сбивало бы с толку.
    return;
  }

  // Надгробие снимается только теперь, когда запись точно применяется: сними
  // его раньше — и запись, ушедшая ждать родителя, потеряла бы защиту от
  // воскрешения, а вместе с ней и весь смысл правила.
  if (tomb) ctx.q(`DELETE FROM ${SEEN} WHERE tbl = ? AND uid = ? AND col = ?`).run(rec.tbl, rec.uid, '*');

  // Новая строка, в которой нечего записать, — не строка: у большинства этих
  // таблиц есть NOT NULL без умолчания (patients.full_name, visits.visit_date),
  // и `INSERT (uid) VALUES (?)` уронил бы транзакцию целиком.
  if (id == null && !cols.length) { stats.skipped++; return; }

  if (id == null) {
    // BRANCH_ORIGIN_V1 — откуда строка, ставится ОДИН РАЗ, при вставке. UPDATE
    // её не трогает: то, что сосед потом поправил запись, не делает её своей и
    // наоборот. В SHIPPED колонки нет — у каждого узла своя точка зрения, и
    // отправить её значило бы объявить соседу его собственные строки чужими.
    // Буква берётся из МЕТКИ, а не из rec.origin: метка уже проверена isStamp
    // выше (^[0-9a-f]{12}-[0-9a-f]{4}-[A-Z]{1,8}$), а origin — необязательное
    // поле, которое отправитель заполняет сам. Так в колонку не попадёт ни
    // мусор, ни чужое имя: подписаться буквой соседа можно только подделав
    // метку, а по ней же считается и порядок слияния.
    const stamped = parseStamp(rec.stamp);
    const origin = stamped ? stamped.node : null;
    ctx.q(
      `INSERT INTO ${rec.tbl} (uid, sync_origin${cols.length ? ', ' + cols.join(', ') : ''})
       VALUES (?, ?${cols.map(() => ', ?').join('')})`
    ).run(rec.uid, origin, ...vals);
  } else if (cols.length) {
    ctx.q(`UPDATE ${rec.tbl} SET ${cols.map(c => c + ' = ?').join(', ')} WHERE id = ?`)
      .run(...vals, id);
  }
  // Строка применена напрямую. Всё, что лежит по ней в ожидании со МЕНЬШЕЙ
  // меткой, устарело: дождавшись своего родителя, оно воспроизвело бы старое
  // состояние поверх нового. Поколоночное правило выше и так не дало бы ему
  // победить, но снять перекрытое ожидание дешевле, чем годами хранить и
  // раз за разом проигрывать его заново. Ожидание с БОЛЬШЕЙ меткой остаётся:
  // оно новее и выиграет по колонкам, когда придёт его час.
  ctx.q('DELETE FROM sync_pending WHERE tbl = ? AND uid = ? AND stamp <= ?')
    .run(rec.tbl, rec.uid, rec.stamp);
  // Строка применилась — прежний отказ по ней больше не факт, а история.
  // Оставить его значило бы держать на экране «N записей не приняты» после
  // того, как всё починилось (в базе-то теперь есть).
  ctx.q('DELETE FROM sync_refused WHERE tbl = ? AND uid = ?').run(rec.tbl, rec.uid);
  const rememberApplied = ctx.q(`INSERT INTO ${SEEN} (tbl, uid, col, stamp) VALUES (?,?,?,?)
              ON CONFLICT(tbl, uid, col) DO UPDATE SET stamp = excluded.stamp`);
  // Метка пишется ТОЛЬКО применённым колонкам. Написать её всему снимку
  // значило бы объявить отправителя автором каждой колонки строки — с этого
  // и начинался дефект, который чинит вся эта задача.
  // Метка КОЛОНКИ, а не записи: именно её сравнивает следующая приехавшая
  // запись, и подменив её общей, мы вернули бы «автор всего снимка».
  for (const col of cols) rememberApplied.run(rec.tbl, rec.uid, col, colStamp(col));
  if (cols.length || id == null) stats.applied++; else stats.skipped++;
}

// Значения, которые better-sqlite3 умеет связать. Всё прочее (true, объект,
// массив, undefined) роняет вставку — а обещание файла в том, что мусорная
// запись пропускается ПОИМЁННО. Проверка на входе честнее savepoint'а: тот
// откатит уже начатую работу, эта не даст её начать.
function scalarPayload(data) {
  if (data == null) return true;                                   // del и записи без данных
  if (typeof data !== 'object' || Array.isArray(data)) return false;
  for (const v of Object.values(data)) {
    const t = typeof v;
    if (v === null || t === 'number' || t === 'string' || t === 'bigint') continue;
    if (Buffer.isBuffer(v)) continue;
    return false;
  }
  return true;
}

/**
 * МЕТКИ МЕСТНЫХ ПРАВОК строки, по колонкам (ревью C1 → ось 7d → источник 7e).
 *
 * Читается sync_authored, а НЕ журнал, и это третья и последняя поправка к
 * одному и тому же месту. Журнал вычищается по подтверждению соседей, и вместе
 * с ним исчезала метка нашей собственной свежей правки: следующий блоб соседа
 * со СТАРЫМ значением ложился поверх неё, сеть сходилась на более ранней
 * правке, а оба журнала при этом были пусты — искать нечего. Воспроизводится
 * без экзотики: у филиала выгрузка отвечает 500, а выборка работает.
 *
 * Пол — created_at строки, и ТОЛЬКО у строки, заведённой ЗДЕСЬ
 * (sync_origin IS NULL). У приехавшей строки created_at — это момент, когда мы
 * её приняли, то есть заведомо позже чужой правки, которая её и привезла;
 * объявив его своим авторством, узел отвергал бы всё, что сосед пришлёт следом.
 * Авторство приехавших колонок хранит sync_seen, и его достаточно.
 */
function localEditStamps(db, ctx, tbl, uid) {
  const mine = authoredAt(ctx.q, tbl, uid);
  const out = new Map();
  const put = (col, ms) => {
    if (!Number.isFinite(ms)) return;
    let stamp;
    try {
      stamp = stampAt(ms, ctx.self);
    } catch {
      return;   // буква проверена на входе; это страховка, а не путь
    }
    const prev = out.get(col);
    if (!prev || prev < stamp) out.set(col, stamp);
  };
  for (const [col, at] of mine) put(col, Date.parse(at));
  const born = ctx.q(`SELECT created_at, sync_origin FROM ${tbl} WHERE uid = ?`).get(uid);
  if (born && born.sync_origin == null && born.created_at) put('*', Date.parse(born.created_at));
  return out.size ? out : null;
}

/**
 * Метка из БУДУЩЕГО — подрезать до «сейчас + допуск» и запомнить, на сколько
 * сосед спешит (Задача 7e, I-2). Возвращается метка, годная для сравнения и
 * для хранения в sync_seen; буква узла сохраняется — по ней и решается ничья.
 */
function clampSkew(ctx, stamp) {
  if (!isStamp(stamp)) return stamp;
  const parsed = parseStamp(stamp);
  const limit = Date.now() + ctx.skewMax;
  if (!parsed || parsed.ms <= limit) return stamp;
  const ahead = parsed.ms - Date.now();
  if (ahead > ctx.skewMs) ctx.skewMs = ahead;
  ctx.skewed++;
  try {
    return stampAt(limit, parsed.node);
  } catch {
    return stamp;
  }
}

/**
 * Снимок авторства строки ДО того, как приём её тронет. Берётся один раз на
 * строку: applyOne может вернуться к ней ещё раз (освобождение из ожидания), и
 * второй снимок был бы уже испорчен первой записью.
 */
function rememberAuthorship(db, ctx, tbl, uid) {
  const key = tbl + '|' + uid;
  if (ctx.authored.has(key)) return;
  ctx.authored.set(key, ctx.q('SELECT col, at FROM sync_authored WHERE tbl = ? AND uid = ?').all(tbl, uid));
}

/** Вернуть авторство ровно таким, каким оно было до приёма. */
function restoreAuthorship(db, ctx) {
  if (!ctx.authored.size) return;
  const wipe = ctx.q('DELETE FROM sync_authored WHERE tbl = ? AND uid = ?');
  const put = ctx.q('INSERT INTO sync_authored (tbl, uid, col, at) VALUES (?,?,?,?)');
  for (const [key, rows] of ctx.authored) {
    const sep = key.indexOf('|');
    const tbl = key.slice(0, sep);
    const uid = key.slice(sep + 1);
    wipe.run(tbl, uid);
    for (const r of rows) put.run(tbl, uid, r.col, r.at);
  }
}

const EMPTY = new Set();

/**
 * СРЕЗ УЖЕ РАЗОБРАН? (Задача 7b) Экспортируется ради вызывающего: fetchJournals
 * снимает перед первым применением резервную копию базы, и спросить надо ДО
 * неё — иначе неподтверждённый повтор, который сосед кладёт в каждый блоб,
 * заваливал бы диск клиники копиями ради нулевой работы. applyBatch задаёт тот
 * же вопрос второй раз, уже своей транзакцией: правило одно, и жить оно должно
 * в одном месте.
 *
 * Засев (seed) под правило не подпадает: все его страницы несут один и тот же
 * upto — замороженный пол журнала.
 */
export function sliceAlreadyApplied(db, { peer = null, upto = 0, seed = false, seedPage = 0 } = {}) {
  if (!peer) return false;
  const reach = sliceUpto(upto);
  const got = receipt(db, peer);
  if (seed) {
    // Страница засева: её upto ни о чём не говорит — он у всех страниц один
    // (замороженный пол). Сравнивается НОМЕР, и только в пределах того же
    // пола: сменился пол — засев начат заново, номера с ним тоже.
    //
    // Отсев здесь ОБЯЗАТЕЛЕН, а не бережлив. Отправитель повторяет страницу,
    // пока не придёт квитанция, а записи засева несут авторство '*' — всю
    // строку — и каждый раз под новой меткой. Применив повтор, мы отдали бы
    // ему СВОИ правки, сделанные с прошлого раза (сквозной тест ловит это на
    // телефоне и адресе). А безопасен отсев ровно потому, что набор строк
    // заморожен на начало засева (seed_started): содержимое страницы с тем же
    // номером не меняется, а заведённое позже приезжает журналом.
    const page = sliceUpto(seedPage);
    return !!page && reach === got.recv_upto && got.recv_seed_page >= page;
  }
  return !!reach && got.recv_upto >= reach;
}

// Заголовок среза приезжает СНАРУЖИ: строка, дробь, отрицательное число и
// undefined тут одинаково возможны, а число это идёт в чужой sent_seq и в
// чистку чужого журнала. Всё, что не целое положительное, — «квитанции нет».
function sliceUpto(upto) {
  const n = Math.floor(Number(upto));
  return Number.isFinite(n) && n > 0 ? n : 0;
}

/** Наша квитанция этому соседу: докуда дошли по журналу и по засеву. */
function receipt(db, peer) {
  const row = db.prepare('SELECT recv_upto, recv_seed_page FROM sync_peers WHERE node = ?').get(peer);
  return row || { recv_upto: 0, recv_seed_page: 0 };
}

// Какие колонки отправитель ПРАВИЛ (а не просто прислал в снимке). Запись без
// changed — старая сборка соседа: считаем авторской всю строку, ровно как до
// этой задачи.
function changedSet(rec) {
  if (!Array.isArray(rec.changed) || !rec.changed.length) return null;
  const set = new Set();
  for (const col of rec.changed) if (typeof col === 'string' && col) set.add(col);
  return set.size ? set : null;
}

/**
 * Авторские колонки записи МИНУС те, чьё притязание мы уже учитывали
 * (Задача 7b). `changed_at` — карта «колонка → номер журнала отправителя, на
 * котором она правилась в последний раз»; всё, что не выше нашей квитанции
 * этому соседу (recv_upto), приезжает повторно и новым авторством не является.
 *
 * @returns {string[]|null} null — сужать нечем (запись старой сборки, засев,
 *   квитанции ещё нет): вызывающий читает `changed`, как читал всегда. Пустой
 *   список — законный ответ «нового авторства нет», и путать его с null нельзя.
 */
function narrowChanged(rec, recvUpto) {
  const at = rec.changed_at;
  if (!recvUpto || !at || typeof at !== 'object' || Array.isArray(at)) return null;
  const kept = [];
  for (const [col, seq] of Object.entries(at)) {
    if (typeof col !== 'string' || !col) continue;
    const n = Number(seq);
    // Нечитаемый номер — не повод отобрать авторство: пропускаем сужение по
    // этой колонке, а не саму колонку.
    if (!Number.isFinite(n) || n > recvUpto) kept.push(col);
  }
  return kept;
}

// Строка справочника — по КОДУ. Дублей кода схема не запрещает, поэтому берём
// самую раннюю: любой другой выбор («последняя», «любая») менялся бы от порции
// к порции, и одна и та же приехавшая работа садилась бы то на одну услугу, то
// на другую.
function catalogueId(db, ctx, spec, code) {
  const r = ctx.q(`SELECT id FROM ${spec.table} WHERE ${spec.key} = ? ORDER BY id LIMIT 1`).get(code);
  return r ? r.id : null;
}

// Применить тех, кто ждал родителей, которые УЖЕ на месте.
//
// Ищем не «кто приехал в этой порции», а «чей родитель существует локально
// прямо сейчас»: родитель мог приехать и не порцией — услуга справочника
// приезжает через catalogue.js, отдельным механизмом, и ожидавшая её строка
// иначе не разобралась бы никогда.
//
// Точечно, по (waits_tbl, waits_uid): связать всех висящих детей с первым
// попавшимся родителем было бы не «не связать», а перепутать — хуже.
// Освобождённый ребёнок сам может быть родителем (визит → услуга → результат),
// поэтому цикл до неподвижной точки.
function releasePending(db, stats, ctx) {
  for (let round = 0; round < MAX_RELEASE_ROUNDS; round++) {
    const ready = ctx.q('SELECT DISTINCT waits_tbl, waits_uid FROM sync_pending').all()
      .filter((p) => parentPresent(db, ctx, p.waits_tbl, p.waits_uid));
    if (!ready.length) return;

    for (const parent of ready) {
      const rows = ctx.q('SELECT tbl, uid, record FROM sync_pending WHERE waits_tbl = ? AND waits_uid = ?')
        .all(parent.waits_tbl, parent.waits_uid);
      for (const row of rows) {
        // Строка снимается с ожидания ДО применения: если родителя уже видно, а
        // записи не хватает чего-то ещё, applyOne положит её обратно — уже с
        // новым «кого ждём». Оставить её на месте значило бы вечно ждать того,
        // кто приехал.
        ctx.q('DELETE FROM sync_pending WHERE tbl = ? AND uid = ?').run(row.tbl, row.uid);
        let rec;
        try {
          rec = JSON.parse(row.record);
        } catch {
          // Испорченный JSON применить нечем, и хранить его дальше незачем:
          // он уже снят с ожидания выше.
          stats.skipped++;
          continue;
        }
        // Дождавшаяся запись проходит те же savepoint и те же проверки, что и
        // только что приехавшая: за месяцы ожидания схема могла уйти вперёд, и
        // отказ базы на СТАРОЙ записи не должен отменять свежую порцию.
        const appliedBefore = stats.applied;
        applyGuarded(db, rec, stats, ctx);
        // Освобождением считается только настоящее применение: запись, ушедшая
        // ждать ВТОРОГО родителя, из ожидания не вышла.
        if (stats.applied > appliedBefore) stats.released++;
      }
    }
  }
}

// Родитель на месте? Строки — по uid, справочник — по коду, ровно так же, как
// их резолвит applyOne: иначе освобождение и применение разошлись бы, и запись
// ходила бы по кругу «освободили → снова в ожидание».
function parentPresent(db, ctx, tbl, key) {
  for (const specs of Object.values(CODE_REFS)) {
    for (const spec of Object.values(specs)) {
      if (spec.table === tbl) return catalogueId(db, ctx, spec, key) != null;
    }
  }
  if (!SHIPPED[tbl]) return false;   // неизвестная таблица: ждать её нечем
  return localId(db, ctx, tbl, key) != null;
}
