// BRANCH_SYNC_HOURLY_V1 — филиал забирает обновления САМ, раз в час.
//
// Решение владельца 2026-09-02, дословно: «add 1 hour syncronization period for
// the entire system. so clinics owner gets data and other reports every 1 hour».
//
// ЧТО БЫЛО ДО. Главный филиал выкладывал копию на релей по расписанию
// (relay.js), а принимающая сторона не забирала её НИКОГДА: единственный путь
// вниз — кнопка администратора (`branch_sync_now`). То есть филиал жил на том
// справочнике, который кто-то однажды не поленился нажать. Для прайса это ещё
// как-то работало, для данных, по которым владелец смотрит отчёты, — нет.
// Регистратор, обязанный помнить про кнопку, про неё забудет, и это не его
// вина: помнить должна машина.
//
// ЧЕГО ЭТОТ ФАЙЛ НЕ ДЕЛАЕТ. Не решает, что применять, и не применяет ничего сам:
// вся работа — в branchSyncNow (rpc/branch-sync.js), включая холостой прогон,
// резервную копию перед записью и падение на релей. Здесь только часы. Так
// ручной путь и часовой путь физически не могут разойтись в поведении — это
// один и тот же код, вызванный из двух мест.
//
// ПОЧЕМУ ОШИБКИ НЕ ЛЕТЯТ НАРУЖУ. Правило всего каталога branch-sync и
// control/checkin.js: СЕТИ МОЖЕТ НЕ БЫТЬ, И ЭТО НОРМА. Филиал за упавшим
// каналом, выключенный на ночь сервер главного, VPN в ремонте — всё это
// «попробуем через час», а не авария и тем более не повод уронить сервер
// клиники, который в эту секунду обслуживает регистратуру.

// Первый прогон — через 3 минуты после старта, ПОСЛЕ check-in (60 с) и после
// первой публикации релея (90 с): свежая установка должна сначала получить
// лицензию, а уже потом заниматься филиалами. Три минуты также дают серверу
// спокойно подняться на слабой машине, прежде чем он потянет справочник.
// Единственная зависимость этого файла — и та ради темпа засева: «идёт ли
// сейчас первичная загрузка» знает relay.js, и дублировать этот вопрос здесь
// значило бы завести второй ответ на него. Цикла нет: relay.js про расписание
// не знает.
import { seedingNow, SEEDING_INTERVAL_MS } from './relay.js';

const INITIAL_DELAY_MS = 3 * 60 * 1000;

// Час — решение владельца. Холостой прогон стоит одного запроса и сравнения:
// branchSyncNow сначала делает dryRun и выходит, если менять нечего, не трогая
// ни базу, ни резервные копии.
const INTERVAL_MS = 60 * 60 * 1000;

/**
 * Завести часы, которые раз в час забирают обновления у главного филиала.
 *
 * Ничего не делает на главной клинике и на непривязанной установке: забирать
 * не у кого. Решение принимается ПРИ КАЖДОМ прогоне, а не один раз при старте
 * — установку связывают филиалом без перезапуска сервера, и перезапускать её
 * ради того, чтобы часы заметили новую роль, никто не будет.
 *
 * @param {object} db
 * @param {{ syncImpl?: Function, isSecondary?: Function,
 *           initialDelayMs?: number, intervalMs?: number }} [opts]
 * @returns {{ stop: () => void }}
 */
export function scheduleBranchPull(db, opts = {}) {
  const {
    syncImpl,
    isSecondary,
    initialDelayMs = INITIAL_DELAY_MS,
    intervalMs = INTERVAL_MS,
  } = opts;

  let stopped = false;
  let running = false;

  async function tick() {
    // Перекрытие невозможно: справочник большой, канал может быть узким, и два
    // одновременных применения — это гонка за одну и ту же таблицу. Пропуск
    // такта безвреден, следующий через час.
    if (stopped || running) return;
    running = true;
    try {
      if (!isSecondary(db)) return;
      await syncImpl(db);
    } catch (e) {
      console.warn('[branch-sync] hourly sync did not go through:', e && e.message);
    } finally {
      running = false;
    }
  }

  const first = setTimeout(tick, initialDelayMs);
  const repeat = setInterval(tick, intervalMs);
  // Пока филиалу идёт первичная загрузка, он тоже торопится: страница засева
  // подтверждается ЕГО квитанцией, и час ожидания на каждую страницу — это
  // недели на большой клинике (Задача 7e, I-3). Отдельный таймер, который
  // молчит, пока засева нет, — часовой ритм остальной работы он не трогает.
  const seedRepeat = setInterval(() => { if (seedingNow(db)) tick(); }, SEEDING_INTERVAL_MS);
  seedRepeat.unref?.();
  // unref: часы не должны держать процесс живым. Сервер клиники завершают
  // штатно, и ждать ради них следующего такта незачем.
  first.unref?.();
  repeat.unref?.();

  return {
    stop() {
      stopped = true;
      clearTimeout(first);
      clearInterval(repeat);
      clearInterval(seedRepeat);
    },
  };
}

export const HOURLY_INTERVAL_MS = INTERVAL_MS;
export const HOURLY_INITIAL_DELAY_MS = INITIAL_DELAY_MS;
