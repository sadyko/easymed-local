// Ревью денег задач 1–3: копировать услуги записи в карточку строками нельзя —
// зеркало записи (booking-mirror.js) считает такие строки своими, ставит их в
// следующий визит, возвращает «ждать» при отмене и берёт снова: двойной счёт.
// Поэтому привязки, которые пишут новые правила, — ТОЛЬКО ДЛЯ ВОРОНКИ:
//   'patient' — шаг C′ (crm/visit-link.js: живая карточка пациента держит любую
//               его запись, R1/R2), и на стойке — карточка, которую закрыла стойка
//               (P-7);
//   'phone'   — карточка, найденная по телефону (шаг D, R5).
// По ним двигаются ступень и дата карточки (шаг G, cardDateOf, приход, «Не
// пришёл», отмена, «Подтверждён», проходы no-show.js), а услуги записи карточка
// показывает списком «Записи пациента» (RPC crm_card_bookings). Зеркало записи
// их не видит (requestOfVisit), «Отказ» по ним записи не отменяет
// (cancellableBookingsOf), партнёру API о них не сообщается (api/visit-events.js).
// Прежние привязки ('callcenter', 'match', без source) — как раньше.

/** Источники привязок записи, которые служат только воронке. */
export const DISPLAY_LINK_SOURCES = Object.freeze(['patient', 'phone']);

/** SQL: привязка `alias` — только для воронки (source из DISPLAY_LINK_SOURCES). */
export function displayLinkSql(alias = 'b') {
  return `COALESCE(${alias}.source, '') IN (${DISPLAY_LINK_SOURCES.map((s) => `'${s}'`).join(', ')})`;
}

/** Источник `source` — привязка только для воронки? */
export function isDisplaySource(source) {
  return DISPLAY_LINK_SOURCES.includes(String(source ?? ''));
}
