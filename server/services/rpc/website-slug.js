// WEBSITE_V1 (перенос из Chilla, WEBSITE_ADMIN_V1) — генератор слага для отделений
// и новостей сайта. У врачей и услуг здесь своего слага нет (слаг строит
// site/content.js из id и имени). Слаг участвует в публичном URL, поэтому
// только [a-z0-9-]: кириллица (RU/UZ) транслитерируется, остальное — в дефис.

// Таблица транслитерации: обычный русский алфавит а..я (+ё) плюс четыре
// узбекские кириллические буквы, которых нет в русском алфавите (ў, қ, ғ, ҳ).
// ъ и ь — «немые» знаки, из слага выпадают совсем, а не превращаются в дефис.
const CYRILLIC_TO_LATIN = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z',
  и: 'i', й: 'y', к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r',
  с: 's', т: 't', у: 'u', ф: 'f', х: 'h', ц: 'ts', ч: 'ch', ш: 'sh',
  щ: 'sch', ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
  // узбекская кириллица
  ў: 'o', қ: 'q', ғ: 'g', ҳ: 'h',
};

const MAX_LEN = 80;

export function makeSlug(name) {
  const src = String(name ?? '');
  if (!src) return '';

  let out = '';
  for (const ch of src.toLowerCase()) {
    out += Object.prototype.hasOwnProperty.call(CYRILLIC_TO_LATIN, ch) ? CYRILLIC_TO_LATIN[ch] : ch;
  }

  // Любой прогон символов, которые не a-z0-9, схлопывается в один дефис;
  // ведущие/хвостовые дефисы обрезаются.
  out = out.replace(/[^a-z0-9]+/g, '-').replace(/^-+/, '').replace(/-+$/, '');

  if (out.length > MAX_LEN) {
    // После обрезки по длине хвост мог остаться дефисом — убираем и его,
    // иначе слаг заканчивался бы на '-'.
    out = out.slice(0, MAX_LEN).replace(/-+$/, '');
  }

  return out;
}
