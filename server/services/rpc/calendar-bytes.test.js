// SOURCE_NO_CONTROL_CHARS_V1 — ИСХОДНИК КАЛЕНДАРЯ НЕ ДОЛЖЕН БЫТЬ «ДВОИЧНЫМ».
//
// В rpc/calendar.js жил НАСТОЯЩИЙ байт NUL: разделитель ключа спора за слот
// написали не escape-последовательностью `\0`, а самим символом. Программа от
// этого работала безупречно — и стоило это файлу поиска по нему:
//
//   • ripgrep на файл с нулевым байтом отвечает МОЛЧА — «No matches found», не
//     «binary file», вообще ничем;
//   • GNU grep — «Binary file … matches», ни одной строки;
//   • git diff показывает всё как обычно, поэтому обзор по diff-у не замечает.
//
// 513 строк из 876 — весь разбор межфилиальных столкновений — перестали
// находиться по имени, и понять это по симптому было нечем: поиск отвечает
// «нет совпадений», как если бы кода просто не было.
//
// Это ТРЕТИЙ такой случай в этом репозитории (rpc/diet.js, crm/config.js), и
// оба прежних лечились так же: экран вместо байта плюс проверка САМИХ БАЙТОВ.
// Проверка нужна именно байтовая: в тексте такой символ невидим — потому он и
// живёт годами.
//
// СПИСОК ФАЙЛОВ ЯВНЫЙ, а не обход дерева: у соседних задач свои файлы и свои
// авторы, и падение чужого файла в этом тесте никому ничего не объяснит. Здесь
// перечислено то, что принадлежит межфилиальному календарю.

import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));

const FILES = [
  path.join(here, 'calendar.js'),
  path.join(here, 'slot-engine.js'),
  path.join(here, '..', 'branch-sync', 'catalogue.js'),
  path.join(here, '..', '..', '..', 'public', 'js', 'admin', 'views', 'room-calendar.js'),
];

test('в исходниках календаря нет управляющих символов — иначе поиск перестаёт их видеть', () => {
  for (const file of FILES) {
    const bytes = readFileSync(file);
    const bad = [];
    for (let i = 0; i < bytes.length; i++) {
      const b = bytes[i];
      // Позволены только табуляция, перевод строки и возврат каретки.
      if (b < 0x20 && b !== 0x09 && b !== 0x0a && b !== 0x0d) bad.push(i + ':0x' + b.toString(16));
      if (b === 0x7f) bad.push(i + ':0x7f');
    }
    assert.deepEqual(bad, [], path.basename(file) + ' содержит управляющие символы: ' + bad.join(', ')
      + ' — пишите их escape-последовательностью (\\0, \\x1b), иначе grep и ripgrep перестают видеть файл');
  }
});

test('ключ спора склеивается ЭКРАНОМ \\0 — двумя символами, а не байтом', () => {
  const src = readFileSync(path.join(here, 'calendar.js'), 'utf8');
  // Ищется исходный ТЕКСТ: `\` + `0` внутри кавычек. Найдись здесь настоящий
  // байт — предыдущий тест уже покраснел бы, а этот проверяет, что замена не
  // «убрали разделитель вовсе»: пустая склейка сделала бы ключ спора
  // неоднозначным (два поля, слипшись, дают одну строку из разных пар).
  assert.match(src, /\.join\('\\0'\)/,
    'разделитель ключа обязан остаться — и остаться escape-последовательностью');
});
