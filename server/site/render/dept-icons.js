// Общая иконка для всего, что не опознали: медицинский крест в круге. Это НЕ
// заглушка «иконки нет» — отделение без неё выглядело бы поломанным рядом с
// одиннадцатью оформленными.
const FALLBACK = svg('<circle cx="12" cy="12" r="8.6"/><path d="M12 8.4v7.2M8.4 12h7.2"/>');

export function deptIcon(slug) {
    const key = String(slug || '').toLowerCase();
    if (!key) return FALLBACK;
    for (const [stem, icon] of ICONS) {
        if (key.includes(stem)) return icon;
    }
    return FALLBACK;
}

// Есть ли для отделения своя иконка. Нужна тестам и на случай, если когда-нибудь
// захочется показать «заведите иконку» в админке.
export function hasDeptIcon(slug) {
    return deptIcon(slug) !== FALLBACK;
}
