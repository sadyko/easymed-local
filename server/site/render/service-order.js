// CONSULT_FIRST_V1 — порядок услуг в любом списке на сайте.
//
// Владелец: сначала ПЛАТНЫЕ консультации, затем БЕСПЛАТНЫЕ, затем всё
// остальное. Смысл прямой: пациент приходит на приём, а процедуры и операции
// выбирает уже после него, и первым в списке должно стоять то, на что
// записываются.
//
// ДВА ПРИЗНАКА КОНСУЛЬТАЦИИ, и они расходятся. services.type='consultation' —
// старое поле маршрутизации; service_types.name='Консультации' — группа
// каталога. На боевой базе по первому признаку 31 услуга, по второму 29, и
// расходятся ровно две — обе бесплатные консультации без проставленной группы.
// Если смотреть только на группу, эти две провалятся в общую массу, то есть
// правило не сработает ровно на тех строках, которые проверяют первыми.
// Поэтому консультация — это ЛЮБОЙ из двух признаков.
//
// ПЛАТНОСТЬ — цена строго больше нуля. У бесплатных price = 0 (не NULL), и
// money()/priceFrom() на нуле возвращают пустую строку, так что «без цены на
// экране» и «бесплатная» — это одно и то же состояние.
const CONSULT_TYPE = 'consultation';
const CONSULT_GROUP = 'консультаци';   // «Консультации», «Консультация» — по корню

export function isConsultation(s) {
    if (!s) return false;
    if (String(s.type || '').trim().toLowerCase() === CONSULT_TYPE) return true;
    return String(s.type_name || '').trim().toLowerCase().includes(CONSULT_GROUP);
}

export function isPaid(s) {
    const n = Number(s && s.price);
    return Number.isFinite(n) && n > 0;
}

// 0 — платная консультация, 1 — бесплатная, 2 — всё прочее.
export function serviceRank(s) {
    if (!isConsultation(s)) return 2;
    return isPaid(s) ? 0 : 1;
}

// Сортировка СТАБИЛЬНАЯ и только по ступеням: внутри каждой прежний порядок
// (sort_order, потом id — его задаёт запрос) сохраняется. Пересортировать всё
// заново значило бы без причины перемешать остальные строки, к которым у
// клиники уже привык персонал.
export function sortServices(list) {
    return (list || [])
        .map((s, i) => ({ s, i }))
        .sort((a, b) => serviceRank(a.s) - serviceRank(b.s) || a.i - b.i)
        .map((x) => x.s);
}
