-- 008_relay_token_scopes.sql — BRANCH_RECORDS_V1 (Задача 7a): токен релея
-- принадлежит ФИЛИАЛУ и несёт ОБЛАСТЬ адресов, а не один адрес.
--
-- ЧТО СЛОМАЛОСЬ. 006 привязала токен к одному relay_id, и это было верно ровно
-- пока у всей группы адрес был ОДИН — справочник (relay-crypto.js relayIdFor(key)).
-- Фаза 2 даёт КАЖДОМУ филиалу свой адрес под его журнал
-- (relayIdFor(key, буква), Задача 6): вторичный филиал обязан писать по своему
-- адресу и читать адреса всех соседей. По 006 каждый такой запрос — 401, а
-- клиника переводит 401 в «главный филиал отозвал доступ, возьмите новый ключ»
-- (services/branch-sync/relay.js relay_branch_revoked). Совет неверный: отзыва
-- не было, это ошибка кода. Главная клиника при этом ходит по install_token,
-- который к адресу не привязан вовсе, — то есть на ОДНОЙ машине всё выглядит
-- рабочим, и увидеть это можно только на двух вторичных филиалах.
--
-- ПОЧЕМУ НЕ «ТОКЕН НА АДРЕС». Потолок MAX_LIVE_TOKENS_PER_CLINIC = 64
-- (routes/relay-token.js) считается на КЛИНИКУ по всем адресам, и считаться
-- иначе не может: relay_id приходит в теле запроса из пространства 2^128, так
-- что потолок на пару (клиника, адрес) не ограничивает ничего. Один токен на
-- каждый адрес даёт ≈ N² токенов на сеть из N филиалов — 63 при восьми узлах,
-- 409 при девяти: сеть упирается в потолок на девятом филиале. Одна строка на
-- филиал с областью растёт как N.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ ТАБЛИЦА, А НЕ СПИСОК В КОЛОНКЕ. Проверка доступа —
-- единственная горячая операция этого сервиса на стороне филиалов, и она обязана
-- оставаться поиском по индексу. Список в TEXT потребовал бы читать строку и
-- разбирать её на каждом запросе, а CHECK на форму адреса (он же второй рубеж
-- 006) на элементы списка не наложить вовсе.
--
-- СОВМЕСТИМОСТЬ — не пожелание, а условие. Токены, выписанные до этой миграции,
-- УЖЕ лежат в ключах подключения, которые владелец отнёс в другое здание руками;
-- перевыписать их удалённо нельзя. Поэтому колонка relay_tokens.relay_id
-- остаётся на месте (теперь это «первый адрес» — для показа и для этого
-- переноса), а перенос ниже даёт каждому старому токену ровно ту область,
-- которая у него была: один адрес, тот же самый.
CREATE TABLE relay_token_scopes (
  -- ON DELETE CASCADE по той же причине, что и у relay_tokens.clinic_id: право
  -- не должно переживать учётку, которой оно выдано. Сюда попадают ОБА способа
  -- удаления — выметание неиспользуемых токенов (routes/relay-token.js
  -- pruneRelayTokens) и удаление клиники, которое каскадом сносит её токены.
  -- Осиротевшая строка была бы правом на адрес, ожидающим токен с тем же
  -- случайным именем.
  token    TEXT NOT NULL REFERENCES relay_tokens(token) ON DELETE CASCADE,

  -- Та же форма из 32 строчных шестнадцатеричных, что проверяет routes/relay.js
  -- на пути URL, и тот же CHECK, что 006 ставит на relay_tokens.relay_id.
  -- Повторён здесь намеренно: ИМЕННО ЭТУ колонку теперь читает проверка доступа,
  -- и право на адрес, которого релей не знает, было бы живой учёткой, которая
  -- необъяснимо не работает.
  relay_id TEXT NOT NULL CHECK (length(relay_id) = 32 AND relay_id NOT GLOB '*[^0-9a-f]*'),

  -- Токен первым: каждый запрос спрашивает «что можно ЭТОМУ токену», и первичный
  -- ключ отвечает на него одним спуском по дереву. Он же запрещает выдать одно
  -- право дважды.
  PRIMARY KEY (token, relay_id)
);

-- Обратный вопрос — «кому вообще разрешён этот адрес» — задаёт разбор
-- происшествий («кто мог переписать этот блоб»), и по первичному ключу он не
-- отвечается: relay_id в нём вторая колонка.
CREATE INDEX relay_token_scopes_relay ON relay_token_scopes (relay_id);

-- ПЕРЕНОС. Каждому существующему токену — его собственный единственный адрес.
-- После этого ни один токен в поле не становится ни шире, ни уже, чем был, и
-- обновление сервера не 401-ит ни одного работающего филиала.
INSERT INTO relay_token_scopes (token, relay_id) SELECT token, relay_id FROM relay_tokens;
