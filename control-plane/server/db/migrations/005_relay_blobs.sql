-- BRANCH_SYNC_RELAY_V1 (docs/plans/2026-08-29-branch-sync-DESIGN-QUESTION.md,
-- «Маршрут Б») — ОДИН НЕПРОЗРАЧНЫЙ БЛОБ НА ГРУППУ ФИЛИАЛОВ, и больше ничего.
--
-- ЧТО ЭТО. Два филиала одной клиники на разных интернет-каналах друг друга не
-- видят, и прямая синхронизация (Маршрут А) между ними невозможна. Тогда
-- главный филиал кладёт сюда зашифрованный справочник, а второй его забирает.
--
-- ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ. Смысла. Столбец `bytes` — это AES-256-GCM,
-- зашифрованный КЛЮЧОМ КЛИНИКИ, которого у поставщика нет и не было никогда:
-- он рождается при активации клиники в её собственном каталоге данных и
-- переносится во второй филиал руками владельца, в ключе подключения
-- (server/services/branch-sync/sync-group.js). Поставщик хранит байты, отдаёт
-- байты и НИ ПРИ КАКИХ УСЛОВИЯХ их не разбирает — ни здесь, ни в маршруте.
-- Это не обещание в комментарии, а свойство схемы: BLOB без единого столбца,
-- который заставил бы кого-нибудь заглянуть внутрь.
--
-- Прямое следствие, записанное здесь, чтобы его нельзя было потом «забыть»:
-- КЛИНИКА, ПОТЕРЯВШАЯ КЛЮЧ, НЕ ВОССТАНОВИТ ЭТИ ДАННЫЕ. Поставщик не может
-- помочь. Владельцу это сказано на экране до того, как он на это положится.
--
-- ПОЧЕМУ ТАБЛИЦА, А НЕ ФАЙЛЫ НА ДИСКЕ (как у releases). Релизы отдаёт nginx
-- напрямую, статикой, и файл там обязан быть файлом. Здесь наоборот: отдавать
-- блоб имеет право только активированная установка, то есть отдача всё равно
-- проходит через процесс. А раз так, строка в базе даёт то, чего файл не даёт
-- даром: атомарную замену (UPSERT вместо «записать рядом и переименовать») и
-- удержание одним DELETE вместо обхода каталога.
CREATE TABLE relay_blobs (
  -- Адрес блоба. НЕ идентификатор клиники и НЕ group_id, который владелец видит
  -- на экране, а HMAC-SHA256 от ключа группы (relay-crypto.js relayIdFor).
  -- Два следствия, ради которых так и сделано:
  --   * его нельзя угадать — он выведен из 256-битного ключа, а знает его
  --     только тот, у кого этот ключ уже есть;
  --   * обратно ключ из него не достаётся, поэтому поставщик, видя адрес, не
  --     приближается к содержимому ни на шаг.
  -- Перевыпуск ключа в клинике меняет адрес сам собой, и старый блоб становится
  -- сиротой, которого вычистит удержание ниже.
  relay_id     TEXT PRIMARY KEY,

  -- Кто выгрузил в последний раз. Не для доступа (доступ решает install_token
  -- в заголовке, см. routes/relay.js) и не для расшифровки, а для того, чтобы
  -- было кого спросить, если группа начнёт вести себя странно. Это ЧЕСТНО
  -- признаваемая метаданная: поставщик видит, что клиника X пользуется
  -- резервным каналом и когда, — но не видит, чем именно. Каскад, потому что
  -- удалённая клиника не должна оставлять после себя чужие байты.
  clinic_id    TEXT NOT NULL REFERENCES clinics(clinic_id) ON DELETE CASCADE,

  -- Шифротекст целиком. Единственный столбец, ради которого таблица есть.
  bytes        BLOB NOT NULL,
  -- Длина отдельным столбцом: удержание и обзор состояния не должны читать сам
  -- блоб с диска ради одного числа.
  size         INTEGER NOT NULL,

  -- Когда положили. Обновляется при каждой выгрузке.
  updated_at   TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%SZ','now')),
  -- Когда в последний раз забирали. Нужен именно для удержания: группа, где
  -- справочник не менялся полгода, всё это время ЧИТАЕТ блоб, и стирать его как
  -- «заброшенный» означало бы ломать работающую связь.
  read_at      TEXT
);

-- Удержание ходит по «последнему касанию» — max(updated_at, read_at), — а
-- индекс по updated_at делает ежедневную уборку дешёвой, пока таблица маленькая
-- (одна строка на группу филиалов, а не на клинику).
CREATE INDEX relay_blobs_updated ON relay_blobs (updated_at);
