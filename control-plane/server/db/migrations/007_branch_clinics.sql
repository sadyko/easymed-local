-- 007_branch_clinics.sql — BRANCH_SELF_SERVICE_V1: филиал как отдельная клиника
-- с собственной подпиской, заведённая ГЛАВНОЙ клиникой, а не вендором.
--
-- До сих пор каждая строка clinics была самостоятельной: свой enrollment_code,
-- свой install_token, своя подписка — и завести её мог только человек в панели
-- вендора. Филиал при этом заводился дважды: сначала вендор выдавал ему код,
-- потом главная клиника выдавала ключ связывания. Два разных артефакта из двух
-- разных мест ради одной установки.
--
-- parent_clinic_id связывает филиал с его главной клиникой. Это НЕ «одна
-- подписка на всех»: у филиала остаётся собственная строка, собственная
-- подписка и собственный install_token — по чьему install_token он был создан,
-- видно здесь. Так и биллинг остаётся пофилиальным, и понятно, кто кого завёл.
--
-- Колонка nullable: у существующих клиник родителя нет, и REFERENCES с NULL
-- ничего не требует. Обратной миграции не нужно — старый код колонку просто не
-- читает.
ALTER TABLE clinics ADD COLUMN parent_clinic_id TEXT REFERENCES clinics(clinic_id);

-- Кто чей филиал — вопрос, который задаёт панель («покажи филиалы этой
-- клиники»), поэтому индекс по родителю, а не по ребёнку.
CREATE INDEX IF NOT EXISTS idx_clinics_parent ON clinics(parent_clinic_id);
